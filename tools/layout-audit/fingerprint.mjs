// Отпечаток СОСТАВА данных и вердикт сравнимости двух прогонов (задача T25).
//
// ЗАЧЕМ. Отсутствие побочных эффектов правки мы доказываем построчным
// сравнением двух отчётов: «изменилось только то, что чинили». Это сравнение
// молча опирается на допущение «данные между прогонами те же» — а инструмент
// его не проверял вовсе.
//
// СЛУЧАЙ 03.08.2026. Между прогонами 18:45 и 20:55 появился один чек. Список
// «Чеков» сдвинулся, под плавающей кнопкой оказались другие суммы — в отчёте
// это выглядело как 18 новых строк, неотличимых от побочного эффекта правки.
// Разобрались запросом в прод-БД, то есть ВНЕШНИМ доказательством, которого
// в следующий раз никто не сделает.
//
// Цена ошибки симметрична и одинаково дорога:
//   • сдвиг из-за данных примем за регрессию — будем чинить несуществующее;
//   • настоящую регрессию спишем на «наверное, данные другие» — пропустим.
//
// Отпечаток снимается БЕЗ ЕДИНОГО ЛИШНЕГО ЗАПРОСА: слушаем ответы, которые
// приложение и так получает при загрузке (T23 — прогон и без того почти
// упирается в лимит 60 запросов в минуту).
//
// Строка «данные загрузились: сумм видно N» этого НЕ заменяет: она про то,
// что данные ДОЕХАЛИ, а не про то, что они ТЕ ЖЕ.

export const EMPTY = { receipts: null, lastReceiptId: null, reports: null };

// Читает состав из ответа API. Возвращает патч отпечатка или null.
export function fromResponse(url, body) {
  if (!Array.isArray(body)) return null;
  if (/\/api\/receipts\/?($|\?)/.test(url))
    return {
      receipts: body.length,
      lastReceiptId: body.reduce((m, x) => Math.max(m, Number(x?.id) || 0), 0),
    };
  if (/\/api\/reports\/?($|\?)/.test(url)) return { reports: body.length };
  return null;
}

export const known = (f) =>
  !!f && f.receipts !== null && f.receipts !== undefined;

export function format(f) {
  if (!known(f)) return "не снят (ответы API не разобрались)";
  return `чеков ${f.receipts} (последний id ${f.lastReceiptId}), отчётов ${
    f.reports ?? "—"
  }`;
}

// Вердикт сравнимости. Возвращает { comparable, banner } — banner печатается
// ОТДЕЛЬНОЙ СТРОКОЙ СВЕРХУ отчёта, а не примечанием внизу: примечание читают
// после того, как вывод уже сделан.
export function compare(prev, now) {
  if (!known(now))
    return {
      comparable: false,
      banner:
        "⛔ СРАВНЕНИЕ С ПРЕДЫДУЩИМ ПРОГОНОМ НЕВОЗМОЖНО: состав данных не снят.\n" +
        "Отличия в таблице ничего не доказывают — ни наличия побочных эффектов, ни отсутствия.",
    };
  if (!known(prev))
    return {
      comparable: false,
      banner:
        "⚠️ СРАВНИВАТЬ НЕ С ЧЕМ: отпечаток предыдущего прогона отсутствует (первый запуск\n" +
        `или очищенный out/). Состав этого прогона: ${format(now)}.`,
    };
  const same =
    prev.receipts === now.receipts &&
    prev.lastReceiptId === now.lastReceiptId &&
    prev.reports === now.reports;
  if (same) return { comparable: true, banner: null };
  return {
    comparable: false,
    banner:
      "⛔ СРАВНЕНИЕ С ПРЕДЫДУЩИМ ПРОГОНОМ НЕВОЗМОЖНО: состав данных изменился.\n" +
      `Было: ${format(prev)}\nСтало: ${format(now)}\n` +
      "Любые отличия в таблице могут быть следствием ДАННЫХ, а не правки. " +
      "Отчёт ниже сам по себе годен — негодно именно сравнение с прошлым.",
  };
}
