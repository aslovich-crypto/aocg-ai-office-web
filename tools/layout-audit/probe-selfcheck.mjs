#!/usr/bin/env node
// Самопроверка измерителя probe.mjs (задача T26).
//
// ПРАВИЛО, ПО КОТОРОМУ ОНА НАПИСАНА: каждое требование модуля ломается
// мутацией, и результат сверяется ПО СООБЩЕНИЮ, а не по коду возврата.
// Красный прогон отвечает «что-то не так», а нам нужно «не так ИМЕННО ТО,
// что я сломал»: иначе мутация, задевшая соседнюю ветку, читается как
// подтверждение проверяемой (случай ⑤ из шапки probe.mjs).
//
// ДВЕ ЧАСТИ:
//   A · СИНТЕТИКА, без прода — ядро (pick/measure/textWidth/tap) и чистый
//       вердикт ворот. Прод для них не нужен и вреден: синтетика
//       воспроизводима, а прод меняется под руками.
//   B · ПРОД — УМОЛЧАНИЯ ПРИМЫ (login/goto/gate). Их нельзя проверить
//       на синтетике, а сломаться они могут молча — и тогда виноватым
//       назначат следующее приложение, а не устаревший селектор.
//       Запуск: node probe-selfcheck.mjs --prod

import {
  openBlank,
  openApp,
  pick,
  measure,
  textWidth,
  tap,
  dataVerdict,
  ПРИМА,
} from "./probe.mjs";

const PROD = process.argv.includes("--prod");
let провалов = 0;

// Ждём ошибку и сверяем ТЕКСТ, а не факт падения.
async function ждуОшибку(имя, ожидаюТекст, fn) {
  try {
    await fn();
    console.log(`  ✖ ${имя}: ошибки НЕ БЫЛО, а должна быть`);
    провалов++;
  } catch (e) {
    const ok = new RegExp(ожидаюТекст, "i").test(e.message);
    console.log(
      `  ${ok ? "✓" : "✖"} ${имя}: ${e.message.split("\n")[0].slice(0, 96)}`,
    );
    if (!ok) {
      console.log(`      ожидал в сообщении: /${ожидаюТекст}/`);
      провалов++;
    }
  }
}
function равно(имя, факт, ожидание) {
  const ok = String(факт) === String(ожидание);
  console.log(
    `  ${ok ? "✓" : "✖"} ${имя}: ${факт}${
      ok ? "" : ` (ожидалось ${ожидание})`
    }`,
  );
  if (!ok) провалов++;
}

// ── A · ЯДРО НА СИНТЕТИКЕ ───────────────────────────────────────────────────
const HTML = `
<body style="margin:0;font:400 13px/1.4 sans-serif">
  <div id="карточка" style="width:200px;border:1px solid #ccc;padding:8px">
    <div id="мета" style="width:90px;font:400 13px/1.4 sans-serif;white-space:nowrap;overflow:hidden;text-overflow:ellipsis">05.08.2026 · 3950</div>
    <div id="двойник" style="font:400 13px/1.4 sans-serif">05.08.2026 · 3950</div>
    <div id="заголовок" style="font:600 18px/1.25 sans-serif">Nothing Fancy</div>
  </div>
  <div id="подложка" style="position:relative;width:200px;height:40px">
    <div id="накрытый" style="position:absolute;inset:0">под оверлеем</div>
    <div id="оверлей" class="over" style="position:absolute;inset:0;background:#fff"></div>
  </div>
  <div id="закраем" style="position:fixed;left:600px;top:20px;width:80px;height:20px">за краем</div>
</body>`;

console.log("══ A · ЯДРО (синтетика, без прода)");
{
  const { page, close } = await openBlank({ html: HTML, width: 375 });

  await ждуОшибку("два кандидата вместо одного", "найдено 2 кандидат", () =>
    pick(page, { что: "мета", найти: { текст: /^05\.08\.2026/ } }),
  );

  await ждуОшибку(
    "ожидание шрифта не совпало",
    "шрифт: ожидал 400 13px, элемент 600 18px",
    () =>
      pick(page, {
        что: "заголовок под видом меты",
        найти: { текст: /^Nothing/ },
        ожидаю: { шрифт: "400 13px" },
      }),
  );

  await ждуОшибку("ожидание текста не совпало", "текст: ожидал", () =>
    pick(page, {
      что: "заголовок",
      найти: { текст: /^Nothing/ },
      ожидаю: { текст: /^\d{2}\./ },
    }),
  );

  await ждуОшибку(
    "индекс без сильного ожидания",
    "индекс задан ЯВНО, но ожидание слабое",
    () =>
      pick(page, {
        что: "любой div с индексом",
        найти: { тег: "div", индекс: 0 },
        ожидаю: { виден: true },
      }),
  );

  // Успешный выбор: сужаем по контейнеру и берём индекс ЯВНО.
  const мета = await pick(page, {
    что: "мета карточки",
    найти: { внутри: "#карточка", текст: /^05\.08\.2026/, индекс: 0 },
    ожидаю: { тег: "div", шрифт: "400 13px", виден: true },
  });
  const m = await measure(мета);
  равно("замер: усечён (200px контейнер)", m.усечён, true);
  равно("замер: многоточие включено", m.многоточие, true);

  const было = (await measure(мета)).нужно;
  const ширинаЧужого = await textWidth(мета, "01.01.2026 · 0000");
  const стало = (await measure(мета)).нужно;
  равно("textWidth вернул текст на место", стало, было);
  console.log(`  · ширина чужого текста в этом элементе: ${ширинаЧужого}px`);

  const закраем = await pick(page, {
    что: "элемент за краем экрана",
    найти: { текст: /^за краем/ },
  });
  await ждуОшибку("тап по элементу вне экрана", "вне экрана", () =>
    tap(закраем),
  );

  const накрытый = await pick(page, {
    что: "накрытый оверлеем",
    найти: { текст: /^под оверлеем/ },
  });
  await ждуОшибку(
    "тап в точку, где лежит другой элемент",
    "лежит div\\.over",
    () => tap(накрытый),
  );

  await close();
}

// ── A3 · УМОЛЧАНИЕ ВХОДА НА ИЗМЕНЁННОЙ РАЗМЕТКЕ ────────────────────────────
// Проверяем НАСТОЯЩУЮ ПРИМА.login, а не заглушку: на странице есть экран
// входа, но полей и кнопки нет — так выглядит переименование классов.
// Умолчание обязано сказать про СЕБЯ, а не выдать «элемент не найден».
console.log("\n══ A3 · умолчание входа при изменённой разметке (синтетика)");
{
  const { page, close } = await openBlank({
    html: '<div class="aocg-login-input"></div>',
  });
  await ждуОшибку(
    "ПРИМА.login на изменённой разметке",
    "разметка входа изменилась",
    () => ПРИМА.login(page),
  );
  await close();
}

// ── A2 · ВОРОТА ДАННЫХ: ПЯТЬ РАЗНЫХ ДИАГНОЗОВ ──────────────────────────────
console.log("\n══ A2 · ВОРОТА ДАННЫХ (чистая функция, пять случаев)");
{
  const случаи = [
    [
      "данные на экране",
      { apiRows: 8, apiSeen: 2, domHas: true },
      true,
      "данные на экране",
    ],
    [
      "маркер есть, ответов ноль",
      { apiRows: 0, apiSeen: 0, domHas: true },
      false,
      "ВОРОТА СЛЕПЫ",
    ],
    [
      "ни маркера, ни ответов",
      { apiRows: 0, apiSeen: 0, domHas: false },
      false,
      "НИ МАРКЕРА, НИ ОТВЕТОВ",
    ],
    [
      "API вернул ноль строк",
      { apiRows: 0, apiSeen: 3, domHas: false },
      false,
      "ДАННЫХ НЕТ",
    ],
    [
      "строки есть, экран пуст",
      { apiRows: 3, apiSeen: 1, domHas: false },
      false,
      "ЭКРАН ИХ НЕ ПОКАЗАЛ",
    ],
  ];
  for (const [имя, вход, окОжид, кусок] of случаи) {
    const v = dataVerdict(вход);
    const ok = v.ok === окОжид && v.reason.includes(кусок);
    console.log(`  ${ok ? "✓" : "✖"} ${имя}: ${v.reason.slice(0, 80)}`);
    if (!ok) провалов++;
  }
}

// ── B · УМОЛЧАНИЯ ПРИМЫ НА ПРОДЕ ────────────────────────────────────────────
if (!PROD) {
  console.log("\n══ B · умолчания Примы: ПРОПУЩЕНО (нужен --prod)");
} else {
  console.log("\n══ B · УМОЛЧАНИЯ ПРИМЫ (прод)");
  // B1 · умолчания работают
  {
    const { page, close } = await openApp({ width: 375, screen: "Чеки" });
    const карточка = await pick(page, {
      что: "название организации в карточке",
      найти: { текст: /^(ООО|АО|ИП)\s/, индекс: 0 },
      ожидаю: { виден: true },
    });
    равно("умолчания довели до данных", !!карточка.sel, true);
    await close();
  }
  // B2 · МУТАЦИЯ goto: несуществующий экран
  await ждуОшибку(
    "goto на несуществующий экран",
    "не подтверждён",
    async () => {
      const { close } = await openApp({ screen: "Бюджет проекта" });
      await close();
    },
  );
  // B3 · МУТАЦИЯ gate: устаревший шаблон ручки
  await ждуОшибку("шаблон ручки устарел", "ВОРОТА СЛЕПЫ", async () => {
    const { close } = await openApp({
      screen: "Чеки",
      gate: { маркер: "₽", апи: /\/api\/finance\// },
    });
    await close();
  });
}

console.log(
  провалов === 0
    ? "\n✓ probe.mjs: все требования проверены мутацией и сверены по сообщению"
    : `\n✖ probe.mjs: провалов ${провалов}`,
);
process.exit(провалов === 0 ? 0 : 1);
