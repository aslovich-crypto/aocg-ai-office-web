#!/usr/bin/env node
/**
 * МУТАЦИИ СТОРОЖА ВОССТАНОВЛЕНИЯ ПАРОЛЯ (`scripts/check-reset-password.mjs`).
 *
 * ЗАЧЕМ ОТДЕЛЬНЫЙ ФАЙЛ. Сторож ходит в `npm run lint` и отвечает «сходится ли».
 * Он НЕ отвечает на вопрос «а заметил бы он, если бы сломали». Правило прямое:
 * сторож, не проверенный мутацией, считается неработающим (T11).
 *
 * ⚠️ КАЖДАЯ МУТАЦИЯ ПОДТВЕРЖДАЕТ ПОСТАНОВКУ, И ЭТО НЕ ФОРМАЛЬНОСТЬ (T77).
 * 26.08.2026 в бэкенде из девяти мутантов ДВА не встали — якорь разъехался
 * после форматирования, — и в своде это выглядело бы как «все поймано».
 * Непойманный мутант ВИДЕН: он краснеет нулём. Непоставленный НЕ ВИДЕН:
 * он неотличим от проверенного. Поэтому свод печатает ТРИ числа, и ненулевое
 * «не поставлено» делает прогон несостоявшимся.
 *
 * ЗАПУСК (в `npm run lint` НЕ входит — правит файл и возвращает на место):
 *     node tools/mutate-reset-password.mjs
 */

import { readFileSync, writeFileSync } from "node:fs";
import { execFileSync } from "node:child_process";
import { createHash } from "node:crypto";

const ФАЙЛ = "src/App.jsx";
const эталон = readFileSync(ФАЙЛ, "utf8");
const отпечаток = createHash("sha256").update(эталон).digest("hex");

const МУТАНТЫ = [
  {
    имя: "M1 маршрут письма /reset-password убран",
    было: 'const isReset = route.startsWith("/reset-password");',
    стало: "const isReset = false;",
  },
  {
    имя: "M2 маршрут объявлен, но вынут из условия LoginScreen",
    было: "!isForgot && !isReset",
    стало: "!isForgot",
  },
  {
    имя: "M3 ответ сервера заменён своим текстом",
    было: 'setОтвет(d.message || "Запрос принят");',
    стало: 'setОтвет("Письмо отправлено на ваш адрес");',
  },
  {
    имя: "M4 два разных 400 свалены в один",
    было: 'setСсылкаМертва(текст.includes("Ссылка"));',
    стало: "setСсылкаМертва(true);",
  },
  {
    имя: "M5 кнопка снова врёт про «скоро»",
    было: 'onClick={() => navigate("/forgot-password")}',
    стало:
      'onClick={() => alert("Восстановление пароля скоро будет доступно")}',
  },
];

let поставлено = 0;
let поймано = 0;
const непоставленные = [];

for (const м of МУТАНТЫ) {
  const сколько = эталон.split(м.было).length - 1;
  if (сколько !== 1) {
    непоставленные.push(
      `${м.имя} — якорь найден ${сколько} раз, нужен ровно 1`,
    );
    console.log(`  ${м.имя}: ⚠️ НЕ ПОСТАВЛЕН`);
    continue;
  }
  поставлено++;
  writeFileSync(ФАЙЛ, эталон.replace(м.было, м.стало));
  let красный = false;
  try {
    execFileSync("node", ["scripts/check-reset-password.mjs"], {
      stdio: "pipe",
    });
  } catch {
    красный = true;
  } finally {
    writeFileSync(ФАЙЛ, эталон);
  }
  if (красный) поймано++;
  console.log(`  ${м.имя}: ${красный ? "ПОЙМАН" : "⚠️ НЕ ПОЙМАН"}`);
}

const вернулось = createHash("sha256")
  .update(readFileSync(ФАЙЛ, "utf8"))
  .digest("hex");

console.log("");
console.log(`  поставлено ..... ${поставлено} из ${МУТАНТЫ.length}`);
console.log(`  поймано ........ ${поймано}`);
console.log(`  НЕ ПОСТАВЛЕНО .. ${непоставленные.length}`);
console.log(`  эталон восстановлен побайтно: ${вернулось === отпечаток}`);

if (непоставленные.length) {
  console.error("\n⚠️ ПРОГОН НЕ СОСТОЯЛСЯ: мутант, который не встал, ничего");
  console.error("   не проверил, но в своде неотличим от проверенного.");
  for (const н of непоставленные) console.error("   ✗ " + н);
  process.exit(2);
}
if (поймано !== поставлено) process.exit(1);
if (вернулось !== отпечаток) {
  console.error("⚠️ ФАЙЛ НЕ ВЕРНУЛСЯ В ИСХОДНОЕ СОСТОЯНИЕ");
  process.exit(3);
}
