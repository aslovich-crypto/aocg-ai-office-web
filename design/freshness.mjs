#!/usr/bin/env node
/**
 * СВЕЖЕСТЬ ВЕНДОРНОЙ КОПИИ ДИЗАЙН-СИСТЕМЫ (задача T12).
 *
 * СРАВНИВАЕТ ТОКЕНЫ, А НЕ БАЙТЫ ФАЙЛОВ — и это не мелочь реализации.
 * Следующий человек предложит «просто сравнить файлы»; вот почему нельзя:
 * в каноне (`colors_and_type.css`) живут комментарии, отступы и порядок
 * блоков, которые меняются сами по себе и ни на что не влияют. Байтовое
 * сравнение подняло бы тревогу на переписанном комментарии, а тревога,
 * которая чаще ложная, чем верная, обучает себя игнорировать — ровно то,
 * из-за чего в T12 отвергнут и сигнал по дате. Вендорим мы ТОКЕНЫ,
 * значит и сверять надо их: имя, значение, наличие.
 *
 * ТРИ АРТЕФАКТА, А НЕ ДВА (выяснено замером 08.08.2026):
 *   ① канон      — colors_and_type.css в проекте Claude Design;
 *   ② выгрузка   — export/theme.mjs ТАМ ЖЕ, её собирает tools/build-tokens.js;
 *   ③ наша копия — design/theme.mjs здесь.
 * Расхождение может сидеть на любом из двух стыков, и лечится оно по-разному:
 * между ① и ② — пересобрать выгрузку В ПРОЕКТЕ ДС (мы этого сделать не можем);
 * между ② и ③ — подтянуть файл сюда. Поэтому скрипт называет стык, а не
 * просто «устарело».
 *
 * ОТЧЁТ РАЗЛИЧАЕТ «КАНОН НЕДОСТУПЕН» И «РАСХОЖДЕНИЙ НЕТ». Это два разных
 * факта, которые выглядят одинаково успокаивающе, если их не разделить:
 * первый означает, что проверка НЕ ВЫПОЛНЯЛАСЬ. Коды выхода:
 *   0 — сверено, расхождений нет
 *   1 — сверено, есть расхождения (перечислены)
 *   2 — сверить не с чем: канон не передан или не читается
 *
 * ЗАПУСК (канон достаёт агент коннектором к claude.ai и кладёт во временный
 * файл — из CI и с Railway коннектора нет, см. design/README.md):
 *   node design/freshness.mjs --canon /tmp/colors_and_type.css
 *   node design/freshness.mjs --canon /tmp/canon.css --export /tmp/theme.mjs
 *   node design/freshness.mjs --selfcheck
 */

import { readFileSync, existsSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const ЗДЕСЬ = dirname(fileURLToPath(import.meta.url));
const КОПИЯ = join(ЗДЕСЬ, "theme.mjs");

/** Токены канона: `--имя: значение;` без комментариев внутри значения. */
export function токеныКанона(текст) {
  const из = {};
  for (const m of текст.matchAll(/--([a-z0-9-]+)\s*:\s*([^;]+);/gi)) {
    из[вCamel(m[1])] = m[2].replace(/\/\*.*?\*\//g, "").trim();
  }
  return из;
}

/** Токены нашей копии или выгрузки: `имя: "значение",`. */
export function токеныКопии(текст) {
  const из = {};
  for (const m of текст.matchAll(/^\s*([A-Za-z0-9]+):\s*"([^"]*)"/gm)) {
    из[m[1]] = m[2].trim();
  }
  return из;
}

function вCamel(имя) {
  const [первый, ...остальные] = имя.split("-");
  return первый + остальные.map((ч) => ч[0].toUpperCase() + ч.slice(1)).join("");
}

function сравнить(слева, справа) {
  const тольКоСлева = Object.keys(слева).filter((k) => !(k in справа)).sort();
  const тольКоСправа = Object.keys(справа).filter((k) => !(k in слева)).sort();
  const разошлись = Object.keys(слева)
    .filter((k) => k in справа && слева[k] !== справа[k])
    .sort();
  return { тольКоСлева, тольКоСправа, разошлись, чисто: !тольКоСлева.length && !тольКоСправа.length && !разошлись.length };
}

function печать(имяСтыка, слева, справа, итог) {
  if (итог.чисто) {
    console.log(`  ✓ ${имяСтыка}: расхождений нет (${Object.keys(слева).length} токенов)`);
    return;
  }
  console.log(`  ✗ ${имяСтыка}: расхождения есть`);
  if (итог.тольКоСлева.length)
    console.log(`      нет справа (${итог.тольКоСлева.length}): ${итог.тольКоСлева.join(", ")}`);
  if (итог.тольКоСправа.length)
    console.log(`      нет слева (${итог.тольКоСправа.length}): ${итог.тольКоСправа.join(", ")}`);
  for (const k of итог.разошлись)
    console.log(`      ${k}: ${слева[k]} → ${справа[k]}`);
}

function самопроверка() {
  // Известные ответы прямо здесь: пример крошечный и от него зависит смысл
  // кодов выхода. Разойдётся разбор — увидим сразу, а не на живых данных.
  const канон = токеныКанона(":root{ --cherry: #A4161A; --split-1: #3D4550; }");
  const копия = токеныКопии('  cherry: "#A4161A",\n  other: "#000000",\n');
  const итог = сравнить(канон, копия);
  const ок =
    канон.cherry === "#A4161A" &&
    канон.split1 === "#3D4550" &&
    итог.тольКоСлева.join() === "split1" &&
    итог.тольКоСправа.join() === "other" &&
    !итог.чисто;
  console.log(ок ? "  ✓ самопроверка разбора пройдена" : "  ✗ самопроверка разбора ПРОВАЛЕНА");
  return ок;
}

const арг = process.argv.slice(2);
const значение = (имя) => {
  const i = арг.indexOf(имя);
  return i >= 0 ? арг[i + 1] : null;
};

console.log("САМОПРОВЕРКА РАЗБОРА");
if (!самопроверка()) {
  console.log("\nРАЗБОР НЕ ГОДЕН — сверка не выполнялась.");
  process.exit(2);
}
if (арг.includes("--selfcheck")) process.exit(0);

const путьКанона = значение("--canon");
if (!путьКанона || !existsSync(путьКанона)) {
  console.log("\n⚠️  КАНОН НЕДОСТУПЕН — СВЕРКА НЕ ВЫПОЛНЯЛАСЬ.");
  console.log("Это НЕ «расхождений нет»: про свежесть копии сейчас ничего не известно.");
  console.log("Канон достаёт агент коннектором к claude.ai (colors_and_type.css");
  console.log("проекта «AOCG AI Office Design System») и кладёт во временный файл,");
  console.log("после чего: node design/freshness.mjs --canon <файл>");
  process.exit(2);
}

const канон = токеныКанона(readFileSync(путьКанона, "utf8"));
const копия = токеныКопии(readFileSync(КОПИЯ, "utf8"));
const путьВыгрузки = значение("--export");

console.log(`\nСВЕРКА ТОКЕНОВ (канон: ${Object.keys(канон).length}, наша копия: ${Object.keys(копия).length})`);
const итогКопии = сравнить(канон, копия);
печать("канон ↔ наша копия", канон, копия, итогКопии);

if (путьВыгрузки && existsSync(путьВыгрузки)) {
  const выгрузка = токеныКопии(readFileSync(путьВыгрузки, "utf8"));
  const итогВыгрузки = сравнить(канон, выгрузка);
  печать("канон ↔ выгрузка в ДС", канон, выгрузка, итогВыгрузки);
  печать("выгрузка ↔ наша копия", выгрузка, копия, сравнить(выгрузка, копия));
  if (!итогВыгрузки.чисто) {
    console.log("\nСТЫК НАЗВАН: отстаёт ВЫГРУЗКА в проекте ДС, а не наша копия.");
    console.log("Лечится там: пересобрать tools/build-tokens.js в проекте ДС,");
    console.log("после чего подтянуть файл сюда. Руками токены в копию НЕ дописывать —");
    console.log("копия перестанет быть копией, и следующий не поймёт, намеренно это или забыли.");
  }
} else {
  console.log("  (выгрузка не передана — стык «канон ↔ выгрузка» не проверялся)");
}

process.exit(итогКопии.чисто ? 0 : 1);
