#!/usr/bin/env node
// Сторож словаря категорий на фронте (T39, шаг ②).
//
// ЗАЧЕМ. Словарь (9 видов расхода, 11 групп, статья-фолбэк) имеет ЕДИНЫЙ
// ИСТОЧНИК в репозитории бэкенда — app/dictionaries/categories.json. Сюда он
// попадает генерацией в src/lib/dictionaries.js. Сторож следит, чтобы копию
// не правили руками и чтобы вокруг неё не заводились вторые экземпляры
// тех же имён.
//
// ЧТО ПРОВЕРЯЕТСЯ:
//   ① копия на месте, несёт штамп источника и разбирается;
//   ② ключи GROUP_COLORS в lib/categories.js совпадают с GROUPS. Цвета —
//      решение дизайн-линии и НЕ генерируются, поэтому файл не перезаписывается;
//      сходство имён приходится проверять, а не обеспечивать. Разошлись —
//      группа молча покрасится в серый GROUP_FALLBACK, без ошибки;
//   ③ фронтовые семантические константы (NON_DEDUCTIBLE, SPECIAL_TK) —
//      реальные значения из TAX_KINDS. Это ФРОНТОВЫЙ выбор одного из девяти
//      видов (бэкенд их семантически не выделяет), поэтому генерации не
//      подлежит, но принадлежность обязана держаться.
//
// ╔══════════════════════════════════════════════════════════════════════╗
// ║ ГРАНИЦА — ЧИТАТЬ ОБЯЗАТЕЛЬНО                                         ║
// ╚══════════════════════════════════════════════════════════════════════╝
// Этот сторож НЕ ВИДИТ репозиторий бэкенда и потому НЕ ОТВЕЧАЕТ на вопрос
// «отвечает ли копия ТЕКУЩЕМУ источнику». Он проверяет лишь внутреннюю
// связность: копия цела, вокруг неё нет вторых экземпляров. Копия может быть
// побайтно исправной, нести правильный штамп — и отставать от источника,
// если генератор не гоняли. Этот вопрос задаётся ТОЛЬКО со стороны бэкенда
// (tools/gen_dictionaries.py --check и tests/tools/dict_stamp.py), где видны
// оба репозитория; в CI фронта он не задаётся вовсе.
// Наличие штампа — не то же самое, что его СОВПАДЕНИЕ с источником.

import { readFileSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const КОПИЯ = join(ROOT, "src", "lib", "dictionaries.js");
const ЦВЕТА = join(ROOT, "src", "lib", "categories.js");

// Семантические константы фронта: файл → имя константы. Каждая обязана быть
// одним из TAX_KINDS. Добавляешь такую константу — впиши сюда, иначе она
// станет вторым экземпляром имени и разойдётся молча.
const СЕМАНТИЧЕСКИЕ = [
  ["src/lib/tax.js", "NON_DEDUCTIBLE"],
  ["src/components/CategorySheet.jsx", "SPECIAL_TK"],
];

const провалы = [];
const шаг = (ок, текст) => {
  console.log(`  ${ок ? "✓" : "✗"} ${текст}`);
  if (!ок) провалы.push(текст);
};

let копия;
try {
  копия = readFileSync(КОПИЯ, "utf8");
} catch {
  console.error(
    "\n✖ Нет src/lib/dictionaries.js — генерируемой копии словаря.",
  );
  console.error("  Сгенерировать: ./venv/bin/python tools/gen_dictionaries.py");
  console.error("  (запускается в репозитории бэкенда aocg-ai-office)\n");
  process.exit(1);
}

console.log("СЛОВАРЬ КАТЕГОРИЙ — сторож фронта");

// ① штамп и разбор копии
const штамп = копия.match(/ШТАМП-ИСТОЧНИКА sha256:\s*([0-9a-f]{64})/);
шаг(
  Boolean(штамп),
  штамп
    ? `копия несёт штамп источника ${штамп[1].slice(0, 12)}…`
    : "копия БЕЗ штампа — правлена руками либо собрана не генератором",
);

const массив = (имя) => {
  const м = копия.match(
    new RegExp(`export const ${имя} = \\[([\\s\\S]*?)\\];`),
  );
  return м ? [...м[1].matchAll(/"([^"]*)"/g)].map((x) => x[1]) : null;
};
const TAX_KINDS = массив("TAX_KINDS");
const GROUPS = массив("GROUPS");
шаг(
  Boolean(TAX_KINDS?.length && GROUPS?.length),
  `копия разбирается: ${TAX_KINDS?.length ?? 0} видов, ${
    GROUPS?.length ?? 0
  } групп`,
);
if (!TAX_KINDS || !GROUPS) {
  console.error("\n✖ Копия не разбирается — дальше проверять нечего.\n");
  process.exit(1);
}

// ② ключи GROUP_COLORS против GROUPS
const цвета = readFileSync(ЦВЕТА, "utf8");
const блок = цвета.slice(
  цвета.indexOf("GROUP_COLORS"),
  цвета.indexOf("GROUP_FALLBACK"),
);
// Ключи бывают И в кавычках, И голыми (Связь, Транспорт) — читать надо оба
// вида: разбор по одним кавычкам увидел бы 7 групп из 11 и промолчал.
const ключи = [...блок.matchAll(/^\s*(?:"([^"]+)"|([^\s:{}]+))\s*:/gm)]
  .map((м) => м[1] ?? м[2])
  .filter((к) => к && !["bg", "fg"].includes(к));
const нет_цвета = GROUPS.filter((г) => !ключи.includes(г));
const лишние = ключи.filter((к) => !GROUPS.includes(к));
шаг(
  нет_цвета.length === 0 && лишние.length === 0,
  нет_цвета.length || лишние.length
    ? `GROUP_COLORS РАЗОШЁЛСЯ со словарём — без цвета: [${нет_цвета}]; лишние ключи: [${лишние}]`
    : `GROUP_COLORS покрывает все ${GROUPS.length} групп, лишних ключей нет`,
);

// ③ семантические константы принадлежат TAX_KINDS
for (const [файл, имя] of СЕМАНТИЧЕСКИЕ) {
  let текст;
  try {
    текст = readFileSync(join(ROOT, файл), "utf8");
  } catch {
    шаг(false, `${файл}: файл не читается, а в списке семантических значится`);
    continue;
  }
  const м = текст.match(new RegExp(`${имя}\\s*=\\s*"([^"]*)"`));
  if (!м) {
    шаг(false, `${файл}: константа ${имя} не найдена — список устарел`);
    continue;
  }
  шаг(
    TAX_KINDS.includes(м[1]),
    TAX_KINDS.includes(м[1])
      ? `${файл}: ${имя} — реальный вид расхода`
      : `${файл}: ${имя} = "${м[1]}" НЕТ среди 9 видов расхода`,
  );
}

if (провалы.length) {
  console.error(
    `\n✖ Словарь разошёлся: ${провалы.length} проверок не прошло.`,
  );
  console.error(
    "  Правится ИСТОЧНИК (app/dictionaries/categories.json в бэкенде),",
  );
  console.error("  затем ./venv/bin/python tools/gen_dictionaries.py\n");
  process.exit(1);
}
console.log("  ИТОГ: копия цела, вторых экземпляров имён нет\n");
