#!/usr/bin/env node
// Сторож: на старте страницы НЕТ зависимостей от чужих хостов (T43).
//
// ЗАЧЕМ. 10.08.2026 выяснилось, что index.html тянул шрифт с fonts.googleapis.com
// и держал ДВА `preconnect` к хостам Google — то есть браузер открывал два лишних
// TLS-соединения к зарубежным адресам в первые миллисекунды загрузки. При
// фильтрации зарубежных хостингов на уровне оператора это прямой вход в описанный
// триггер «больше трёх параллельных TLS подряд». Шрифт переведён на самохостинг.
//
// Без сторожа ссылку на CDN вернут следующей же правкой «чтобы быстрее» — и
// заметить это будет нечем: локально всё работает, а ломается только у того,
// чей оператор фильтрует.
//
// ЧТО ПРОВЕРЯЕТСЯ: в index.html нет ни одного АТРИБУТА src/href/preconnect,
// указывающего на внешний хост. Упоминание хоста в КОММЕНТАРИИ разрешено —
// комментарий не заставляет браузер открывать соединение, а объяснять, почему
// мы отсюда ушли, полезнее, чем молчать.
//
// ГРАНИЦА: сторож смотрит ТОЛЬКО index.html. Внешний запрос, сделанный из кода
// (fetch/XHR к чужому домену) или подтянутый через CSS `@import` внутри бандла,
// он не увидит. Это не «поймает всё», а «не даст вернуться тому, что уже было».

import { readFileSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const ФАЙЛ = join(ROOT, "index.html");

const html = readFileSync(ФАЙЛ, "utf8");
// Комментарии вырезаем: в них внешний хост упоминать МОЖНО и нужно.
const безКомментариев = html.replace(/<!--[\s\S]*?-->/g, "");

const внешние = [
  ...безКомментариев.matchAll(/(?:src|href)\s*=\s*"(https?:\/\/[^"]+)"/g),
].map((м) => м[1]);

console.log("ВНЕШНИЕ ЗАВИСИМОСТИ НА СТАРТЕ СТРАНИЦЫ");
if (внешние.length) {
  console.error(`  ✗ найдено ${внешние.length}:`);
  for (const u of внешние) console.error(`      ${u}`);
  console.error(
    "\n✖ index.html снова тянет чужой хост. Каждый такой адрес — отдельное\n" +
      "  TLS-соединение при открытии приложения, к адресу, который мы не\n" +
      "  контролируем. Положите ресурс к себе (образец: public/fonts/).\n",
  );
  process.exit(1);
}
console.log(
  `  ✓ внешних src/href нет (проверен index.html, ${html.length} символов)\n`,
);
