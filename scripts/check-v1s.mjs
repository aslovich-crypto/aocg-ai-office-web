// Любой другой ответ значит, что бэкенд стенда видит 1С, — стоп, сценарий
// не идёт. Проверяется ТЕКСТ отказа, а не только код: 503 даёт и «1С не
// отвечает», а это был бы как раз поход в 1С (CLAUDE.md, принцип замера №4).
//
// ⚠️ ДВЕ ПРОВЕРКИ У КАЖДОЙ ФАЗЫ, как у skvoz: что видно на экране и что лежит
// в базе. Журнал отправок засевается SQL-ом между снимками, и после каждой
// вставки — сверка «строка легла»: изБазы теряет ошибки psql, и без сверки
// засев молча пуст, а прибор мерил бы чужое состояние.
//
// ЗАПУСК: npm run v1s        (бэкенд рядом: ../aocg-ai-office или AOCG_BACKEND)
