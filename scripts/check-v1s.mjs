// Живая запись журнала для фазы. Прежние живые сперва гасятся в «cancelled»
// — это история, и индекс живой выгрузки (одна на отчёт) их пропустит.
function засеять(исход, минутНазад = 0) {
  sql(
    `UPDATE odata_exports SET outcome='cancelled' WHERE report_id=${отчёт} ` +
      `AND outcome IN ('running','ok','partial','unposted','error','unavailable')`,
  );
  const номер = исход === "unposted" ? "'0000-000077'" : "NULL";
  const конец = исход === "running" ? "NULL" : "NOW()";
  sql(
    `INSERT INTO odata_exports (org_id, report_id, user_id, outcome, ` +
      `doc_number, started_at, finished_at, error_note) VALUES ` +
      `(${организация}, ${отчёт}, ${кто}, '${исход}', ${номер}, ` +
      `NOW() - make_interval(mins => ${минутНазад}), ${конец}, 'проба')`,
  );
  const легла = sql(
    `SELECT count(*) FROM odata_exports WHERE report_id=${отчёт} ` +
      `AND outcome='${исход}'`,
  );
  if (легла !== "1") неВыполнена(`засев «${исход}» не лёг: строк ${легла}`);
}

