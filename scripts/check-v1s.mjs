// (решение владельца, В8): успешную отправку принимает владелец на проде,
// а прибор проверяет пути отказа и показ состояния — то, что на проде
// нарочно не устроишь.
//
// ⚠️⚠️ СНАЧАЛА САМОПРОВЕРКА, ПОТОМ СЦЕНАРИЙ (решение владельца, В1). В окружение
// стенда НАРОЧНО подкладываются доступы к 1С на заведомо мёртвый адрес
