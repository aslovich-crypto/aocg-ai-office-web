// Сторож текстов сканера чека (T94).
//
// ПОВОД, 29.08.2026: диалог «Чек не найден в ФНС» называл две причины —
// «старше 30 дней» и «не зарегистрирован». Обе неверны для СВЕЖЕГО чека,
// а он и будет самым частым, когда с 01.09 сканируют сотрудники.
// «Не зарегистрирован» вдобавок читается как ОБВИНЕНИЕ ПРОДАВЦА и посылает
// человека ругаться с кассиром вместо того, чтобы подождать.
//
// ⚠️ ЧТО ИМЕННО СТЕРЕЖЁТСЯ. Не «текст красивый» — это не проверяется, — а три
// свойства, каждое куплено разбором:
//   ① «не зарегистрирован» НЕТ НИГДЕ. Слово вернётся легко: оно короткое
//      и звучит технически верно.
//   ② названа причина ожидания. Без неё сообщение снова станет про поиск.
//   ③ порог «30 дней» НЕ НАЗВАН ЧИСЛОМ: он на стороне ФНС, называть его
//      значит обещать за налоговую.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const КОРЕНЬ = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const ФАЙЛ = path.join(КОРЕНЬ, "src/pages/ScanReceiptModal.jsx");

const беды = [];
const сказать = (ok, текст) => {
  console.log(`  ${ok ? "✓" : "✗"} ${текст}`);
  if (!ok) беды.push(текст);
};

console.log("\nТЕКСТЫ СКАНЕРА ЧЕКА (T94)");

// ⚠️ Сначала — выполнима ли проверка вообще (T87): нет файла или нет блока —
// это «НЕ ВЫПОЛНЕНА», а не «совпало».
if (!fs.existsSync(ФАЙЛ)) {
  console.log(`  ✗ НЕ НАЙДЕН ${ФАЙЛ}`);
  process.exit(1);
}
const весь = fs.readFileSync(ФАЙЛ, "utf8");
const начало = весь.indexOf("setSaveSheet({");
if (начало < 0) {
  console.log("  ✗ НЕ НАЙДЕН вызов setSaveSheet — проверять нечего");
  process.exit(1);
}
const блок = весь.slice(начало, весь.indexOf("});", начало) + 3);

// ⚠️ Комментарии вырезаются: пояснение рядом с кодом называет и старый текст,
// и слово «не зарегистрирован». Без вырезания сторож покраснел бы на
// собственном объяснении — этот класс за два дня стоил четырёх случаев,
// правило записано в CLAUDE.md («комментарий НАД конструкцией»).
const код = блок.replace(/\/\/[^\n]*/g, "");

сказать(
  !/не зарегистрирован/i.test(код),
  "«не зарегистрирован» убрано — не обвиняем продавца",
);
сказать(
  /не дошёл/i.test(код),
  "заголовок про ВРЕМЯ («ещё не дошёл»), а не про поиск",
);
сказать(
  /от нескольких часов до суток/i.test(код),
  "названа причина ожидания и сколько ждать",
);
сказать(
  !/30 дн/i.test(код),
  "порог «30 дней» не назван числом — он на стороне ФНС",
);
сказать(
  /ФНС временно недоступна/.test(код),
  "текст про сбой ФНС на месте — его не трогали",
);
сказать(
  /Сохранить как фото/.test(код),
  "кнопка «Сохранить как фото» на месте — граница правки",
);

if (беды.length) {
  console.log(`\n  ⚠️ РАСХОЖДЕНИЙ ${беды.length}`);
  process.exit(1);
}
console.log("  ИТОГ: сообщение объясняет ожидание, а не обвиняет продавца");
console.log(
  "  ⓘ Тот же текст повторён в docs/onboarding-employee.md репозитория\n" +
    "    aocg-ai-office (таблица «Если что-то не так»). Отсюда его не видно:\n" +
    "    в CI выкачивается один репозиторий. Меняете здесь — правьте и там.",
);
