#!/usr/bin/env node
// МУТАЦИИ К СТОРОЖУ ОГРАНИЧЕНИЙ КАМЕРЫ (scripts/check-camera-constraints.mjs).
//
// Правило T11: сторож без мутации считается неработающим, и мутация нужна
// на КАЖДЫЙ заявленный источник. Источников три — разрешение, переключение
// объектива, фонарик из capabilities, — и у каждого своя мутация; у
// разрешения их три: снять ideal, ослабить числа, снять с ОДНОГО из запусков.
// Контроли К1–К2 проверяют обратное: сторож НЕ краснеет от переименования
// функции выбора и от снятого кода, процитированного в комментарии.
// Прибор, краснеющий впустую, отменяет сам себя.
//
// ⚠️ СВОД ЧЕТЫРЁХГРАФНЫЙ: ПОСТАВЛЕНО · ПОЙМАНО · НЕ ПОСТАВЛЕНО · НЕ МЕРЕНО.
// «Мутант не пойман» и «прибор не дал вердикта» — разные исходы, и второе
// не засчитывается за первое (RULES-FRONTEND, 08.09.2026). Вердикт — это
// код выхода ВМЕСТЕ с итоговой строкой сторожа: упавший Node тоже выходит
// с кодом 1, и без строки его падение читалось бы как «поймал».
//
// ЗАПУСК: node scripts/camera-mutations.mjs
import { spawnSync } from "node:child_process";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const КОРЕНЬ = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const ф = (о) => path.join(КОРЕНЬ, о);
const СТОРОЖ = ф("scripts/check-camera-constraints.mjs");

// Итоговая строка сторожа на каждый код выхода.
const СТРОКА = {
  0: "ОГРАНИЧЕНИЯ КАМЕРЫ НА МЕСТЕ",
  1: "ОГРАНИЧЕНИЯ КАМЕРЫ ОСЛАБЛЕНЫ",
  2: "ПРОВЕРКА НЕ ВЫПОЛНЕНА",
};

// Вердикт или null, если прибор его не дал. Без вердикта — до трёх попыток.
function прогнать() {
  for (let попытка = 1; попытка <= 3; попытка++) {
    const р = spawnSync("node", [СТОРОЖ], { encoding: "utf8" });
    if (СТРОКА[р.status] && р.stdout.includes(СТРОКА[р.status]))
      return { код: р.status, попытка };
  }
  return null;
}

// Мутация = список правок [файл, было, стало]; стало === null — удалить файл.
// Цель проверяется ДО замены, результат — ПОСЛЕ: непоставленный мутант
// неотличим от проверенного (T77).
function мутация(имя, правки, ждём) {
  const снимки = правки
    .filter(([о]) => fs.existsSync(ф(о)))
    .map(([о]) => [ф(о), fs.readFileSync(ф(о), "utf8")]);
  try {
    for (const [о, было, стало] of правки) {
      if (!fs.existsSync(ф(о))) return { имя, исход: "НЕ ПОСТАВЛЕНО" };
      const т = fs.readFileSync(ф(о), "utf8");
      if (стало === null) {
        fs.rmSync(ф(о));
        if (fs.existsSync(ф(о))) return { имя, исход: "НЕ ПОСТАВЛЕНО" };
        continue;
      }
      const есть = было instanceof RegExp ? было.test(т) : т.includes(было);
      if (!есть) return { имя, исход: "НЕ ПОСТАВЛЕНО" };
      fs.writeFileSync(ф(о), т.replace(было, стало));
      if (fs.readFileSync(ф(о), "utf8") === т)
        return { имя, исход: "НЕ ПОСТАВЛЕНО" };
    }
    const в = прогнать();
    if (!в) return { имя, исход: "НЕ МЕРЕНО" };
    return {
      имя,
      исход: в.код === ждём ? "ПОЙМАНО" : "НЕ ПОЙМАНО",
      подробно:
        `ждали ${ждём}, вышло ${в.код}` +
        (в.попытка > 1 ? ` (с попытки ${в.попытка} из 3)` : ""),
    };
  } finally {
    for (const [п, т] of снимки) fs.writeFileSync(п, т);
  }
}

console.log("\nМУТАЦИИ ОГРАНИЧЕНИЙ КАМЕРЫ\n");
const исходно = прогнать();
console.log(`  исходно: код ${исходно ? исходно.код : "— вердикта нет"}\n`);
if (!исходно || исходно.код !== 0) {
  console.log("  ⚠️ Сторож не зелёный до мутаций — мерить нечем.");
  process.exit(2);
}

const СКАНЕР = "src/pages/ScanReceiptModal.jsx";
const РАЗРЕШЕНИЕ =
  "const RESOLUTION = { width: { ideal: 1920 }, height: { ideal: 1080 } };";

const итоги = [
  // ① РАЗРЕШЕНИЕ — три мутации: снять, ослабить, снять с одного запуска.
  // М1 — ровно «редизайн для чистоты»: объект пуст, слова про ideal в
  // комментариях рядом остаются — сторож обязан читать код, не комментарии.
  мутация(
    "М1 ideal снят (объект пуст)",
    [[СКАНЕР, РАЗРЕШЕНИЕ, "const RESOLUTION = {};"]],
    1,
  ),
  // М2 — числа на месте, но это дефолт Chromium, ради ухода от которого всё.
  мутация(
    "М2 разрешение ослаблено до 640×480",
    [
      [СКАНЕР, "ideal: 1920", "ideal: 640"],
      [СКАНЕР, "ideal: 1080", "ideal: 480"],
    ],
    1,
  ),
  // М3 — запуск по facingMode с разрешением, а запуск по deviceId — без:
  // после переключения объектива снова 640×480. «КАЖДОМУ запуску».
  мутация(
    "М3 разрешение снято с запуска по deviceId",
    [
      [
        СКАНЕР,
        "{ deviceId: { exact: better }, ...RESOLUTION }",
        "{ deviceId: { exact: better } }",
      ],
    ],
    1,
  ),
  // ② ПЕРЕКЛЮЧЕНИЕ ОБЪЕКТИВА — ветка удалена целиком, от решения до
  // повторного afterStart(). Функция выбора остаётся неиспользуемой:
  // сторож стережёт ветку, а не имя.
  мутация(
    "М4 переключение объектива снято",
    [[СКАНЕР, /const noAutofocus =[\s\S]*?afterStart\(\);\n/, ""]],
    1,
  ),
  // ③ ФОНАРИК — константа вместо capabilities текущей дорожки.
  мутация(
    "М5 фонарик константой true",
    [[СКАНЕР, "setTorchSupported(!!caps.torch)", "setTorchSupported(true)"]],
    1,
  ),
  // Нет файла сканера — сторож обязан сказать «не проверял», а не «чисто».
  мутация("М6 файл сканера удалён", [[СКАНЕР, null, null]], 2),
  // ── КОНТРОЛИ: здесь всё на месте, краснеть нельзя ──
  мутация(
    "К1 функция выбора переименована",
    [[СКАНЕР, /pickLowerBackCamera/g, "выбратьОсновнуюЗаднюю"]],
    0,
  ),
  мутация(
    "К2 снятое процитировано в комментарии",
    [
      [
        СКАНЕР,
        РАЗРЕШЕНИЕ,
        `// было: setTorchSupported(true); const RESOLUTION = {};\n    ${РАЗРЕШЕНИЕ}`,
      ],
    ],
    0,
  ),
];

for (const и of итоги)
  console.log(
    `  ${и.исход === "ПОЙМАНО" ? "✓" : "✗"} ${и.имя} — ${и.исход}` +
      (и.подробно ? ` (${и.подробно})` : ""),
  );

const сколько = (исход) => итоги.filter((и) => и.исход === исход).length;
const поставлено = итоги.length - сколько("НЕ ПОСТАВЛЕНО");
console.log(
  `\n  ПОСТАВЛЕНО ${поставлено} · ПОЙМАНО ${сколько("ПОЙМАНО")} · ` +
    `НЕ ПОСТАВЛЕНО ${сколько("НЕ ПОСТАВЛЕНО")} · НЕ МЕРЕНО ${сколько(
      "НЕ МЕРЕНО",
    )}` +
    ` · НЕ ПОЙМАНО ${сколько("НЕ ПОЙМАНО")}  (из ${итоги.length})`,
);

// Файлы возвращены — сторож снова зелёный. Иначе набор оставил мусор.
const после = прогнать();
console.log(`  после отката: код ${после ? после.код : "— вердикта нет"}\n`);
process.exit(сколько("ПОЙМАНО") === итоги.length && после?.код === 0 ? 0 : 1);
