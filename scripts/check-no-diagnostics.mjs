/**
 * СТОРОЖ: ДИАГНОСТИКА НЕ ДОЛЖНА ПОПАДАТЬ В БОЕВУЮ СБОРКУ (T19).
 *
 * ЗАЧЕМ. До 08.08.2026 отладочный модуль `src/lib/overflowDebug.js` (807 строк)
 * импортировался безусловно и ЛЕЖАЛ В БОЕВОМ БАНДЛЕ. Замер: в dist были
 * `__overflowScan`, `overflow-hit`, `overflow-test`. Молчал он лишь потому,
 * что сам проверял метку в адресе, — то есть защитой служило его собственное
 * поведение, а не отсутствие кода: любой, кто знал метку, вооружал панель
 * на проде одним адресом.
 *
 * ═══ ПОЧЕМУ НЕ СПИСОК ИМЁН ═══
 * «Диагностика» своего маркера в языке не имеет, и ловить её перечнем
 * (`__overflowScan`, `#overflow`, …) бессмысленно: следующий режим назовут
 * иначе и он проедет. Поэтому проверяются ПРИЗНАКИ КЛАССА, а не имена:
 *   ① СЛЕД НА window — продакшен-коду незачем вешать что-либо на глобальный
 *      объект; любое `window.X = …` это либо диагностика, либо утечка;
 *   ② ВХОД ПО АДРЕСУ — чтение `location.hash` как условия включения. Замер
 *      08.08.2026: во всём `src/` его читает РОВНО один файл, отладочный,
 *      то есть правило даёт ноль ложных срабатываний.
 * Оба признака ловят и модуль, который вооружается адресом, но НИЧЕГО
 * не вешает на window, — на нём первый признак слеп, второй нет.
 *
 * ═══ ДВЕ ПОЛОВИНЫ, И ОНИ ОТВЕЧАЮТ НА РАЗНОЕ ═══
 *   СТАТИЧЕСКАЯ (всегда, входит в `npm run lint`) — «в исходниках не завёлся
 *   новый диагностический вход». Ловит ДО сборки и до деплоя.
 *   СБОРОЧНАЯ (`--bundle dist`, в CI и перед выкаткой) — «в собранном файле
 *   диагностики нет». Отвечает на главный вопрос: что реально уедет на прод.
 * Сборочная НЕ включена в lint намеренно: локально разработчик собирает
 * с флагом `VITE_DIAG=1` для прогона вёрстки, и такая сборка обязана
 * содержать модуль — иначе сторож ругался бы на штатную работу.
 *
 * ЗАПУСК:
 *   node scripts/check-no-diagnostics.mjs                 # только исходники
 *   node scripts/check-no-diagnostics.mjs --bundle dist   # + собранный бандл
 *
 * ОТЧЁТ РАЗЛИЧАЕТ «НЕ ПРОВЕРЯЛОСЬ» И «ЧИСТО»: если каталог сборки не передан
 * или отсутствует, так и пишется. Молчание не выдаётся за успех (T26).
 */

import { readFileSync, readdirSync, existsSync, statSync } from "node:fs";
import { join, dirname, relative } from "node:path";
import { fileURLToPath } from "node:url";

const КОРЕНЬ = join(dirname(fileURLToPath(import.meta.url)), "..");
const ИСХОДНИКИ = join(КОРЕНЬ, "src");

// Единственный зарегистрированный диагностический модуль. Список намеренно
// КОРОТКИЙ и лежит здесь, а не в отдельном файле: чтобы добавить сюда строку,
// надо открыть этого сторожа и прочитать, что он проверяет.
const РАЗРЕШЁННЫЕ_ДИАГНОСТИЧЕСКИЕ = ["src/lib/overflowDebug.js"];

// Законные обращения к адресу, не связанные с диагностикой. Каждое — с
// объяснением: список без причин зарастает.
const ИСКЛЮЧЕНИЯ_АДРЕСА = [
  // Токен подтверждения почты приходит ссылкой из письма — это не режим,
  // а разовый параметр запуска; и это `search`, а не `hash`.
  {
    файл: "src/App.jsx",
    шаблон: /URLSearchParams\(window\.location\.search\)/,
  },
];

// Маркеры диагностики для проверки собранного бандла. ЭТО НЕ ОСНОВНОЙ
// признак, а страховка «известное точно не проехало»: основную работу
// делает статическая половина, которая ловит НОВЫЕ входы.
const МАРКЕРЫ_В_БАНДЛЕ = ["__overflowScan", "overflow-hit", "overflow-test"];

// Имя свойства берём ЛЮБОЕ, включая кириллическое: первая версия шаблона
// требовала латинскую букву, и `window.__отладка = …` проехала бы насквозь —
// ровно та лазейка «назовут иначе», ради которой мы ушли от списка имён.
// `window.location = …` исключено отдельно: это штатный переход, не след.
const НАЗНАЧЕНИЕ_НА_WINDOW =
  /\bwindow\.(?!location\s*=)[\p{L}_$][\p{L}\p{N}_$]*\s*=[^=]/gu;
const ЧТЕНИЕ_ХЕША = /\blocation\.hash\b/g;

function файлыИсходников(каталог) {
  const результат = [];
  for (const имя of readdirSync(каталог)) {
    const путь = join(каталог, имя);
    if (statSync(путь).isDirectory()) результат.push(...файлыИсходников(путь));
    else if (/\.(jsx?|mjs|ts|tsx)$/.test(имя)) результат.push(путь);
  }
  return результат;
}

function проверитьИсходники() {
  const беды = [];
  let проверено = 0;
  for (const путь of файлыИсходников(ИСХОДНИКИ)) {
    const отн = relative(КОРЕНЬ, путь);
    if (РАЗРЕШЁННЫЕ_ДИАГНОСТИЧЕСКИЕ.includes(отн)) continue;
    проверено++;
    const текст = readFileSync(путь, "utf8");
    const строки = текст.split("\n");

    строки.forEach((строка, i) => {
      if (строка.trimStart().startsWith("//")) return;
      for (const m of строка.matchAll(НАЗНАЧЕНИЕ_НА_WINDOW)) {
        беды.push(
          `${отн}:${i + 1}: след на window — ${m[0].trim()}\n` +
            `      Боевому коду незачем вешать что-либо на window. Если это` +
            ` диагностика,\n      её место в отдельном модуле за флагом сборки` +
            ` (см. src/main.jsx).`,
        );
      }
      if (ЧТЕНИЕ_ХЕША.test(строка)) {
        ЧТЕНИЕ_ХЕША.lastIndex = 0;
        const законно = ИСКЛЮЧЕНИЯ_АДРЕСА.some(
          (и) => и.файл === отн && и.шаблон.test(строка),
        );
        if (!законно)
          беды.push(
            `${отн}:${i + 1}: вход по адресу — чтение location.hash\n` +
              `      Это признак режима, вооружаемого снаружи. Диагностика` +
              ` подключается\n      только за флагом сборки; если обращение` +
              ` законное — впишите его\n      в ИСКЛЮЧЕНИЯ_АДРЕСА с причиной.`,
          );
      }
    });
  }
  return { беды, проверено };
}

function проверитьБандл(каталог) {
  const полный = join(КОРЕНЬ, каталог);
  if (!existsSync(полный)) return { состояние: "нет", файлы: 0, беды: [] };
  const файлы = [];
  const обойти = (к) => {
    for (const имя of readdirSync(к)) {
      const п = join(к, имя);
      if (statSync(п).isDirectory()) обойти(п);
      else if (/\.(js|css|html)$/.test(имя)) файлы.push(п);
    }
  };
  обойти(полный);
  const беды = [];
  for (const путь of файлы) {
    const текст = readFileSync(путь, "utf8");
    for (const маркер of МАРКЕРЫ_В_БАНДЛЕ) {
      if (текст.includes(маркер))
        беды.push(
          `${relative(КОРЕНЬ, путь)}: содержит «${маркер}»\n` +
            `      Диагностика уехала в сборку. Собирайте боевое БЕЗ` +
            ` VITE_DIAG=1.`,
        );
    }
  }
  return { состояние: "проверено", файлы: файлы.length, беды };
}

const каталогБандла = (() => {
  const i = process.argv.indexOf("--bundle");
  return i >= 0 ? process.argv[i + 1] : null;
})();

const исходники = проверитьИсходники();
let провал = исходники.беды.length > 0;

if (исходники.беды.length) {
  console.error("\n✖ диагностика в исходниках:");
  for (const б of исходники.беды) console.error(`  • ${б}`);
} else {
  console.log(
    `✓ диагностика: входов вне ${РАЗРЕШЁННЫЕ_ДИАГНОСТИЧЕСКИЕ.join(", ")} нет ` +
      `(проверено ${исходники.проверено} файлов)`,
  );
}

if (каталогБандла) {
  const б = проверитьБандл(каталогБандла);
  if (б.состояние === "нет") {
    console.log(
      `⚠ сборка НЕ ПРОВЕРЯЛАСЬ: каталог ${каталогБандла} отсутствует. ` +
        `Это не «чисто» — соберите и повторите.`,
    );
  } else if (б.беды.length) {
    провал = true;
    console.error("\n✖ диагностика в собранном бандле:");
    for (const x of б.беды) console.error(`  • ${x}`);
  } else {
    console.log(`✓ бандл чист: маркеров нет (проверено ${б.файлы} файлов)`);
  }
} else {
  console.log("⚠ сборка НЕ ПРОВЕРЯЛАСЬ: каталог не передан (--bundle dist).");
}

process.exit(провал ? 1 : 0);
