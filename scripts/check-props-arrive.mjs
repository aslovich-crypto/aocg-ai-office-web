// ЧТО ЛОВИТ: проп передан в компонент, а компонент его НЕ ОБЪЯВЛЯЕТ — и он
// молча выбрасывается. Ни ошибки, ни предупреждения, ни падения: функция
// просто не видит аргумента, которого не назвала.
//
// ⚠️ ЭТО НЕ ГИПОТЕТИЧЕСКИЙ КЛАСС. `onUpdateUser={updateUser}` передавался
// в `NastroykiPage` с 13.06.2026 и выбрасывался ровно так. Смена роли
// сотруднику не работала ДВА С ПОЛОВИНОЙ МЕСЯЦА, и увидеть это было нельзя
// ничем: экран рисовался, кнопки нажимались, тесты были зелёными. Нашёл
// владелец глазами, а не прибор — потому прибор и появился.
//
// ⚠️ ПОЧЕМУ ЧТЕНИЕ ИСХОДНИКА ЗДЕСЬ ЗАКОННО: у «объявлен ли проп» нет
// наблюдаемого следствия до тех пор, пока кто-то не нажмёт на кнопку,
// которая им пользуется. Это ровно тот случай, для которого правило
// оставляет чтение исходника — следствия нет, значит наблюдать нечего.

import { readFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const КОРЕНЬ = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const сырой = readFileSync(path.join(КОРЕНЬ, "src/App.jsx"), "utf8");
// ⚠️ КОММЕНТАРИИ СНИМАЮТСЯ ДО РАЗБОРА. Первая редакция читала их как код и
// обрывала подпись компонента на первой же фигурной скобке ВНУТРИ пояснения
// (`PATCH /api/users/{id}`) — прибор объявил потерянными два пропа, которые
// объявлены строкой выше. Поймано первым же прогоном на себе.
const app = сырой
  .replace(/\/\*[\s\S]*?\*\//g, " ")
  .replace(/(^|[^:])\/\/[^\n]*/g, "$1");

console.log("\nПРОПЫ ДОЕЗЖАЮТ ДО КОМПОНЕНТА");

// Компоненты, объявленные с деструктуризацией: `function Имя({ a, b }) {`
// Многострочная запись — обычная, поэтому берём до закрывающей скобки.
const объявления = new Map();
for (const м of app.matchAll(
  /(?:export\s+)?function\s+([A-ZА-Я][A-Za-zА-Яа-я0-9]*)\s*\(\s*\{([\s\S]*?)\}\s*\)\s*\{/g,
)) {
  const имена = м[2]
    .split(",")
    .map((с) => с.replace(/\/\/[^\n]*/g, "").trim())
    .map((с) => с.split(/[:=]/)[0].trim())
    .filter((с) => /^[A-Za-zА-Яа-я_$][\w$А-Яа-я]*$/.test(с));
  объявления.set(м[1], new Set(имена));
}

// Места применения: `<Имя ... />` или `<Имя ...>`; собираем `проп={` и `проп`.
const беды = [];
let местПроверено = 0;
for (const м of app.matchAll(/<([A-ZА-Я][A-Za-zА-Яа-я0-9]*)\s([^>]*?)\/?>/g)) {
  const имя = м[1];
  if (!объявления.has(имя)) continue; // сторонний или импортированный — не наше дело
  местПроверено += 1;
  const переданные = [
    ...м[2].matchAll(/(?:^|\s)([a-zA-Zа-яА-Я_$][\w$А-Яа-я]*)\s*=\s*\{/g),
  ].map((x) => x[1]);
  const объявлено = объявления.get(имя);
  for (const п of переданные) {
    if (п === "key" || п === "ref") continue; // внутренние для React
    if (!объявлено.has(п))
      беды.push(`${имя}: получает «${п}», но не объявляет его — проп теряется`);
  }
}

console.log(`  МЕСТ ПРИМЕНЕНИЯ ПРОВЕРЕНО : ${местПроверено}`);
console.log(`  КОМПОНЕНТОВ С ПРОПАМИ     : ${объявления.size}`);

// ⚠️ ПРОВЕРКА ОБЯЗАНА БЫТЬ ВЫПОЛНИМОЙ (T87): если разбор ничего не нашёл,
// это «НЕ ВЫПОЛНЕНА», а не «всё в порядке». Пустой зелёный тут — та же ложь,
// что молчащий пропуск.
if (местПроверено < 20 || объявления.size < 20) {
  console.log(
    `  ✗ ПРОВЕРКА НЕ ВЫПОЛНЕНА: разбор нашёл слишком мало ` +
      `(мест ${местПроверено}, компонентов ${объявления.size}) — ` +
      `похоже, сломался сам разбор, а не код`,
  );
  process.exit(1);
}

if (беды.length) {
  console.log(`  ✗ ПОТЕРЯННЫХ ПРОПОВ: ${беды.length}`);
  for (const б of беды) console.log(`      ${б}`);
  process.exit(1);
}
console.log("  ✓ ни один переданный проп не выбрасывается молча");
