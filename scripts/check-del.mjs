// ⚠️ ПРИБОР «УДАЛЕНИЕ ОТЧЁТА» (REP-EXPDEL ③). Карточка отчёта и список на
// НАСТОЯЩЕМ стенде: экран → FastAPI → PostgreSQL → экран. Предмет — что
// удаление ушло из низа в «⋯», спрашивает шторкой и доводит запрос до базы.
//
// ⚠️ ПОЧЕМУ ОТДЕЛЬНО ОТ `npm run v1s`, А НЕ ФАЗАМИ В НЕЙ. Фазы удаления СНОСЯТ
// отчёт, на котором стоит вся та проба: добавь их туда — и порядок фаз станет
// несущим, а сломается это молча, красным в чужом шаге. Стенд у них общий,
// сценарий — нет.
//
// ⚠️ ДВЕ ПРОВЕРКИ У КАЖДОЙ ФАЗЫ, как у v1s: что видно на экране и что лежит
// в базе. Именно здесь это не формальность: до этого захода строка списка
// исчезала ДО запроса, и «на экране удалено» с «в базе удалено» расходились
// по построению.
//
// ⚠️ ЧЕГО ПРИБОР НЕ ПРОВЕРЯЕТ, НАЗВАНО ПРЯМО: свайп выполняется НЕ ЖЕСТОМ —
// нажимается кнопка действия строки. Значит проверено, что за действием стоит
// шторка, а не прежний тост, и НЕ проверено, что до действия доводит палец.
// Это известная слепота всех наших проб (улика 06.09.2026).
//
// ЗАПУСК: npm run vdel     (бэкенд рядом: ../aocg-ai-office или AOCG_BACKEND)
import {
  итог,
  неВыполнена,
  поднятьСтенд,
  сверитьШаги,
} from "./lib/skvoznoy-stend.mjs";

const ПОЧТА = "vdel@example.com";
const ПАРОЛЬ = "probe-pass-123";
const ЧЕРНОВИК = "Черновик на снос";
const ПРОВЕРКА = "Проверка на снос";
const ОДОБРЕН = "Одобрен уехавший";
const ОТКЛОНЁН = "Отклонён на снос";
const СВАЙП = "Свайпом на снос";
const ПРОДАВЕЦ = "Лавка Снос";

const беды = [];
console.log("\nУДАЛЕНИЕ ОТЧЁТА: карточка и список на живом стенде");
// Предел запросов поднят только для этой пробы и только на стенде — тот же
// довод, что у v1s: каждый снимок загружает приложение целиком, и на третьей
// фазе прогон упирался бы в общий предел, а красные шаги читались бы
// как дефект экрана. Прод и потолки в коде не трогаются.
const стенд = await поднятьСтенд("probe-del", {
  бэкенд: { SECURITY_RATE_LIMIT: "600" },
});
const sql = (запрос) => стенд.изБазы(запрос);

const рег = await fetch(`${стенд.адресБэка}/api/auth/register`, {
  method: "POST",
  headers: { "Content-Type": "application/json" },
  body: JSON.stringify({
    email: ПОЧТА,
    password: ПАРОЛЬ,
    first_name: "Проба",
    last_name: "Удаляев",
    org_type: "company",
    org_name: "ООО Проба удаления",
  }),
});
const токены = await рег.json().catch(() => ({}));
const токен = токены.access_token;
if (!рег.ok || !токен) неВыполнена(`регистрация на стенде: код ${рег.status}`);
// Вход один на прогон: токены уходят пробе в адресе, иначе ограничитель
// входа отвечает 429 на третьем снимке (тот же замер, что у v1s).
const ВХОД = `&a=${encodeURIComponent(токен)}&r=${encodeURIComponent(
  токены.refresh_token || "",
)}`;
const [кто, организация] = sql(
  `SELECT id || '|' || org_id FROM users WHERE email='${ПОЧТА}'`,
).split("|");
if (!кто || !организация) неВыполнена("пользователь стенда не найден в базе");

function отчёт(название, статус) {
  const ид = sql(
    `INSERT INTO reports (title, status, total, org_id, user_id) VALUES ` +
      `('${название}', '${статус}', 0, ${организация}, ${кто}) RETURNING id`,
  ).split("\n")[0];
  if (!ид) неВыполнена(`отчёт «${название}» не лёг в базу`);
  return ид;
}

// Чек внутри черновика: после удаления отчёта он обязан остаться в базе
// и освободиться. Это половина ответа задачи, и проверяется она запросом,
// а не экраном.
const чек = sql(
  `INSERT INTO receipts (org, amount, date, org_id, user_id, source) VALUES ` +
    `('${ПРОДАВЕЦ}', 900, CURRENT_DATE, ${организация}, ${кто}, 'manual') ` +
    `RETURNING id`,
).split("\n")[0];
const ид = {
  черновик: отчёт(ЧЕРНОВИК, "Черновик"),
  проверка: отчёт(ПРОВЕРКА, "На проверке"),
  одобрен: отчёт(ОДОБРЕН, "Одобрен"),
  отклонён: отчёт(ОТКЛОНЁН, "Отклонён"),
  свайп: отчёт(СВАЙП, "Черновик"),
};
sql(
  `INSERT INTO report_items (report_id, receipt_id) VALUES (${ид.черновик}, ${чек})`,
);
if (
  sql(`SELECT count(*) FROM report_items WHERE report_id=${ид.черновик}`) !==
  "1"
)
  неВыполнена("чек не лёг в черновик — мерить нечего");
// Успешная выгрузка у одобренного: живая запись журнала обязана убрать
// «Удалить отчёт» из меню — бэкенд такой отчёт не отдаст (409), и звать
// на него человека значит обещать работу и отдать отказ.
sql(
  `INSERT INTO odata_exports (org_id, report_id, report_number, report_title, ` +
    `user_id, outcome, doc_number, finished_at) VALUES (${организация}, ` +
    `${ид.одобрен}, ${ид.одобрен}, '${ОДОБРЕН}', ${кто}, 'ok', '0000-000077', NOW())`,
);
if (
  sql(`SELECT outcome FROM odata_exports WHERE report_id=${ид.одобрен}`) !==
  "ok"
)
  неВыполнена("живая выгрузка не легла в журнал");

const нет = (и) => [`SELECT count(*) FROM reports WHERE id=${и}`, "0"];
const есть = (и) => [`SELECT count(*) FROM reports WHERE id=${и}`, "1"];

const ФАЗЫ = [
  {
    фаза: "черновик",
    ждём: [
      ["⓪ экран отчётов", "Отчёты"],
      ["⓪б карточка открыта", "открыта"],
      ["①а низ без удаления", "На проверку →"],
      ["①б удаление в меню", "Удалить отчёт"],
      ["①в шторка, а не тост", "шторка открыта"],
      ["①г удалено", "в списке нет"],
    ],
    база: [
      ["черновик снесён", ...нет(ид.черновик)],
      ["чек остался", `SELECT count(*) FROM receipts WHERE id=${чек}`, "1"],
      [
        "чек освободился",
        `SELECT count(*) FROM report_items WHERE receipt_id=${чек}`,
        "0",
      ],
    ],
  },
  {
    фаза: "на-проверке",
    ждём: [
      ["⓪ экран отчётов", "Отчёты"],
      ["⓪б карточка открыта", "открыта"],
      ["②а низ по канону", "Отклонить · ✓ Одобрить"],
      ["②б отзыв и удаление в меню", "Отозвать с проверки · Удалить отчёт"],
      ["②в удалено", "в списке нет"],
    ],
    база: [["отчёт на проверке снесён", ...нет(ид.проверка)]],
  },
  {
    фаза: "одобрен-выгружен",
    ждём: [
      ["⓪ экран отчётов", "Отчёты"],
      ["⓪б карточка открыта", "открыта"],
      ["③а удаления в меню нет", "Отменить отправку в 1С"],
    ],
    база: [
      ["выгруженный отчёт цел", ...есть(ид.одобрен)],
      [
        "журнал цел",
        `SELECT outcome FROM odata_exports WHERE report_id=${ид.одобрен}`,
        "ok",
      ],
    ],
  },
  {
    фаза: "отклонён",
    ждём: [
      ["⓪ экран отчётов", "Отчёты"],
      ["⓪б карточка открыта", "открыта"],
      ["④а низ без удаления", "Исправить"],
      ["④б удалено из меню", "шторка открыта"],
      ["④в удалено", "в списке нет"],
    ],
    база: [["отклонённый снесён", ...нет(ид.отклонён)]],
  },
  {
    фаза: "свайп",
    ждём: [
      ["⓪ экран отчётов", "Отчёты"],
      ["⑤а действие строки", "шторка открыта"],
      ["⑤б удалено", "в списке нет"],
    ],
    база: [["снесённый свайпом", ...нет(ид.свайп)]],
  },
];

for (const ф of ФАЗЫ) {
  console.log(`  ── фаза «${ф.фаза}»`);
  const замер = await стенд.снять(`?f=${encodeURIComponent(ф.фаза)}${ВХОД}`);
  сверитьШаги(замер, ф.ждём, беды);
  замер
    .slice(ф.ждём.length)
    .forEach((ш) => console.log(`  ℹ ${String(ш).split(" ~ ")[0]}`));
  for (const [имя, запрос, ждём] of ф.база) {
    const было = sql(запрос);
    const ок = было === ждём;
    console.log(
      `  ${ок ? "✓" : "✗"} база, ${имя}: ${было || "пусто"}${
        ок ? "" : `  ← ждали «${ждём}»`
      }`,
    );
    if (!ок) беды.push(`база, ${имя}: «${было || "пусто"}» вместо «${ждём}»`);
  }
}

итог(
  беды,
  стенд.журналБэка(),
  "удаление отчёта: низ без удаления, «⋯» у всех статусов, шторка вместо тоста, запрос доходит до базы",
);
