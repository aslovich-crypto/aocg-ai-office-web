#!/usr/bin/env node
/**
 * СТОРОЖ РАСЧЁТА ВХОДЯЩЕГО НДС (`src/lib/tax.js`).
 *
 * ЗАЧЕМ. До 10.08.2026 НДС считался как `vat_20 + vat_10` — список из двух
 * ставок в коде фронта. С 2026 года действует 22%, и блок «Входящий НДС»
 * на «Сводке» и «Главной» показывал МЕНЬШЕ ТРЕТИ настоящей суммы: замер
 * по проду дал 1 385,62 ₽ при верных 4 702,11 ₽ — занижение 3 316,49 ₽,
 * то есть 70,5%. Цифру переносят в декларацию.
 *
 * Дефект был НЕ в арифметике, а в том, что список ставок вообще существовал:
 * он устарел молча, при появлении новой ставки. Поэтому сторож проверяет
 * не «сумма верна», а три свойства, каждое из которых можно сломать:
 *   ① новая ставка попадает в сумму САМА, без правки кода;
 *   ② фото-чек, у которого разбивки нет по построению, берёт старые колонки
 *      `vat_20`/`vat_10` — там и лежит его НДС (поля `nds` в сохранённом чеке
 *      НЕ БЫВАЕТ: оно живёт только в ответе ручки распознавания);
 *   ③ чек, где есть И разбивка, И колонки, считается ОДИН раз.
 * Третье — против ошибки, которую легко наделать самой починкой.
 *
 * Тест-раннера в этом репозитории нет; проверки живут скриптами и ходят
 * через `npm run lint` — тем же способом, что сторожа темы и вёрстки.
 */

import { receiptVat, computeTaxAccounting } from "../src/lib/tax.js";

const случаи = [
  {
    имя: "① ФНС: ставки 10 и 22 — новая ставка входит сама",
    чек: { vat_breakdown: { 10: 1385.62, 22: 3316.49 } },
    надо: 4702.11,
  },
  {
    имя: "① ставка, которой мы никогда не видели (12,5%)",
    чек: { vat_breakdown: { 12.5: 100 } },
    надо: 100,
  },
  {
    имя: "② фото: разбивки нет (OCR не даёт кодов ставок) — берём колонки",
    чек: { vat_breakdown: null, vat_20: 200, vat_10: 22.5 },
    надо: 222.5,
  },
  {
    имя: "③ есть И разбивка, И старые колонки — считаем ТОЛЬКО разбивку",
    чек: { vat_breakdown: { 20: 100 }, vat_20: 100 },
    надо: 100,
  },
  {
    имя: "чек без НДС вовсе",
    чек: { vat_breakdown: null, vat_20: null, vat_10: null },
    надо: 0,
  },
  {
    имя: "пустая разбивка = НДС нет, но колонки заполнены",
    чек: { vat_breakdown: {}, vat_10: 55 },
    надо: 55,
  },
];

let бед = 0;
for (const { имя, чек, надо } of случаи) {
  const факт = Number(receiptVat(чек).toFixed(2));
  if (факт !== надо) {
    бед++;
    console.error(`  ✗ ${имя}\n      ждали ${надо}, получили ${факт}`);
  }
}

// Сквозная проверка на наборе: сумма и счётчик чеков с НДС.
const набор = [
  { amount: 1000, category_id: 1, vat_breakdown: { 22: 220 } },
  { amount: 500, category_id: 1, vat_breakdown: { 10: 50 } },
  { amount: 300, category_id: 1, vat_breakdown: null, vat_20: 30 },
  { amount: 200, category_id: 1, vat_breakdown: null },
];
const итог = computeTaxAccounting(набор, { groups: [] });
if (Number(итог.vatSum.toFixed(2)) !== 300) {
  бед++;
  console.error(`  ✗ сумма по набору: ждали 300, получили ${итог.vatSum}`);
}
if (итог.vatCount !== 3) {
  бед++;
  console.error(`  ✗ чеков с НДС: ждали 3, получили ${итог.vatCount}`);
}

if (бед) {
  console.error(
    "\n  Входящий НДС считается неверно. Напоминание, откуда правило:\n" +
      "  список ставок в коде фронта устарел молча на ставке 22% и занизил\n" +
      "  сумму на 70,5%. Суммируйте ВСЮ разбивку, список не заводите.\n",
  );
  process.exit(1);
}
console.log(
  `✓ входящий НДС: ${случаи.length} случаев + сквозной набор, ` +
    `новая ставка входит сама, фото берёт колонки, двойного счёта нет`,
);
