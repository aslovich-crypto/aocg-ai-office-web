// Сторож заголовка плашки дублей (№25, мера А).
//
// ⚠️ ПРОВЕРЯЕТ ПУТЬ ДАННЫХ, А НЕ НАЛИЧИЕ СЛОВА. «В App.jsx есть слово
// message» ловится грепом и не значит ничего: поле может быть прочитано
// и выброшено, а заголовок собран рядом своими руками. Поэтому сторож
// прослеживает цепочку: warning.message → переменная → эта переменная
// в разметке компонента.
//
// ПОВОД, 29.08.2026: бэкенд собирал «Этот чек уже добавлен 2 августа»,
// плашка рисовала «Возможный дубль», а `warning.message` не читался
// вовсе — грепом ноль обращений. Требование владельца было выполнено
// на сервере и не доходило до экрана, и это было НЕЗАМЕТНО: тест
// проверял ответ API, то есть то, чего никто не показывает.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const КОРЕНЬ = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const ФАЙЛ = path.join(КОРЕНЬ, "src/App.jsx");

const беды = [];
const сказать = (ok, текст) => {
  console.log(`  ${ok ? "✓" : "✗"} ${текст}`);
  if (!ok) беды.push(текст);
};

console.log("\nЗАГОЛОВОК ПЛАШКИ ДУБЛЕЙ (№25, мера А)");

// ⚠️ Сначала убеждаемся, что сторону вообще есть с чем сравнивать (T87):
// нет файла или нет компонента — это «проверка НЕ ВЫПОЛНЕНА», а не «совпало».
if (!fs.existsSync(ФАЙЛ)) {
  console.log(`  ✗ НЕ НАЙДЕН ${ФАЙЛ}`);
  process.exit(1);
}
const весь = fs.readFileSync(ФАЙЛ, "utf8");
const начало = весь.indexOf("function DuplicateWarningBanner(");
if (начало < 0) {
  console.log(
    "  ✗ НЕ НАЙДЕН компонент DuplicateWarningBanner — проверять нечего",
  );
  process.exit(1);
}
// конец компонента — следующее объявление верхнего уровня
const хвост = весь.slice(начало + 1);
const смещение = хвост.search(/\n(?:function|const|export|\/\/ ─)/);
const тело = хвост.slice(0, смещение > 0 ? смещение : хвост.length);

// ── ① поле читается В ПЕРЕМЕННУЮ ──────────────────────────────────────
const чтение = тело.match(
  /const\s+([\wА-Яа-яЁё]+)\s*=\s*\(?\s*typeof\s+warning\.message/,
);
сказать(
  Boolean(чтение),
  чтение
    ? `warning.message читается в переменную «${чтение[1]}»`
    : "warning.message НЕ читается в переменную — заголовок собирается мимо сервера",
);

// ── ② эта переменная попадает В РАЗМЕТКУ ──────────────────────────────
if (чтение) {
  const имя = чтение[1];
  const разметка = тело.slice(тело.indexOf("return ("));
  const врендере = new RegExp(`\\{\\s*${имя}\\s*\\}`).test(разметка);
  сказать(врендере, `переменная «${имя}» отрисовывается в разметке компонента`);

  // ── ③ запасной текст на месте (требование владельца) ───────────────
  сказать(
    /\|\|[\s\S]{0,200}Возможный дубль/.test(тело.slice(тело.indexOf(имя))),
    "запасной текст есть — пустой message не даёт пустую плашку",
  );

  // ── ④ свой заголовок НЕ рисуется поверх пришедшего ─────────────────
  // ⚠️ Мутация «вернуть свой текст рядом» иначе пройдёт молча: поле
  // читается, отрисовывается, и тут же рядом стоит второй заголовок.
  const литералВРазметке = /["'`][^"'`]*Возможный дубль[^"'`]*["'`]/.test(
    разметка,
  );
  сказать(
    !литералВРазметке,
    "в разметке нет своего заголовка поверх пришедшего с сервера",
  );
}

if (беды.length) {
  console.log(`\n  ⚠️ РАСХОЖДЕНИЙ ${беды.length}`);
  process.exit(1);
}
console.log("  ИТОГ: текст с сервера доходит до экрана");
