// ⚠️ МУТАЦИИ ПОДТВЕРЖДЕНИЯ «ВЫ ТЕРЯЕТЕ ДОСТУП СРАЗУ» (T137, правило T11).
//
// Зелёный сторож ничего не доказывает, пока не показано, что он умеет
// краснеть. Каждая правка ниже — отдельный дефект, каждый обязан дать
// красный `npm run sebya`. Файлы возвращаются в исходное состояние всегда,
// даже при падении рунера.
//
// ⚠️ ПОЛОВИНА МУТАЦИЙ ЛОМАЕТ ГРАНИЦУ В СТОРОНУ ЛИШНИХ ВОПРОСОВ, И ЭТО
// НАМЕРЕННО. «Спросить лишний раз» кажется безобидным — поэтому такая правка
// и проходит незамеченной; а стоит она ровно того же: человек, привыкший
// нажимать «да» на каждом шаге, нажмёт его и там, где предупреждение
// единственное. Мутации ①, ③ и ⑥ — про это.
//
// ⚠️ МУТАЦИИ ИДУТ ПО ДВУМ ФАЙЛАМ: экран и правило имён живут раздельно,
// и сломать их можно порознь.
//
// ЗАПУСК: npm run sebya-mut
import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const КОРЕНЬ = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const ЭКРАН = "src/App.jsx";
const ПРАВИЛО = "src/lib/self_lock.js";

// (имя, файл, было, стало, что ловит)
const МУТАЦИИ = [
  [
    "① подтверждение показывается и на ЧУЖОЙ строке",
    ЭКРАН,
    "                u.id === me?.id ? setГасимСебя(u) : onDeleteUser(u.id)",
    "                setГасимСебя(u)",
    "граница владельца сломана в сторону лишних вопросов: чужого гасят через окно",
  ],
  [
    "② подтверждение НЕ показывается на своей",
    ЭКРАН,
    "                u.id === me?.id ? setГасимСебя(u) : onDeleteUser(u.id)",
    "                onDeleteUser(u.id)",
    "ровно тот дефект, ради которого заведена T137: свайп по себе гасит сразу",
  ],
  [
    "③ окно показывается, когда других активных админов нет",
    ЭКРАН,
    '    этоЯ && user.role === "admin" && роль !== "admin" && ктоВернёт.length > 0;',
    '    этоЯ && user.role === "admin" && роль !== "admin";',
    "окно обещает «вернуть сможет» там, где называть некого и сервер откажет",
  ],
  [
    "④ в списке «вернуть сможет» оказывается сам себя гасящий",
    ЭКРАН,
    "  const ктоВернёт = активныеАдмины\n    .filter((u) => u.id !== me?.id)\n    .map((u) => имяАвтора(u.id, users));",
    "  const ктоВернёт = активныеАдмины.map((u) => имяАвтора(u.id, users));",
    "человеку называют его самого — то есть отвечают «вернёте себе сами», хотя доступа у него уже нет",
  ],
  [
    "⑤ правило имён: при четырёх печатаются все четверо",
    ПРАВИЛО,
    "export const ИМЁН_ЦЕЛИКОМ = 3;",
    "export const ИМЁН_ЦЕЛИКОМ = 4;",
    "порог обрезки уехал: список растёт, пока не перестанет читаться",
  ],
  [
    "⑥ понижение ЧУЖОГО из админов спрашивает подтверждение",
    ЭКРАН,
    '    этоЯ && user.role === "admin" && роль !== "admin" && ктоВернёт.length > 0;',
    '    user.role === "admin" && роль !== "admin" && ктоВернёт.length > 0;',
    "вопрос задаётся там, где человек НЕ теряет доступ, — та же граница с другого конца",
  ],
];

const исходники = Object.fromEntries(
  [...new Set(МУТАЦИИ.map((м) => м[1]))].map((ф) => [
    ф,
    readFileSync(path.join(КОРЕНЬ, ф), "utf8"),
  ]),
);
const выжившие = [];

console.log(
  "\nМУТАЦИИ ПОДТВЕРЖДЕНИЯ ПОТЕРИ ДОСТУПА: каждая обязана покраснеть\n",
);
try {
  for (const [имя, файл, было, стало, зачем] of МУТАЦИИ) {
    const исходный = исходники[файл];
    const сколько = исходный.split(было).length - 1;
    if (сколько !== 1) {
      console.log(`  ✗ ${имя}: ЯКОРЬ встречается ${сколько} раз, нужен один`);
      выжившие.push(имя + " (якорь)");
      continue;
    }
    writeFileSync(path.join(КОРЕНЬ, файл), исходный.replace(было, стало));
    let красный = false;
    try {
      execFileSync("node", [path.join(КОРЕНЬ, "scripts/check-sebya.mjs")], {
        cwd: КОРЕНЬ,
        stdio: "pipe",
        timeout: 900000,
      });
    } catch {
      красный = true;
    }
    writeFileSync(path.join(КОРЕНЬ, файл), исходный);
    console.log(
      `  ${красный ? "✓" : "✗"} ${имя}: ${красный ? "покраснел" : "ВЫЖИЛА"}`,
    );
    console.log(`      ломает: ${зачем}`);
    if (!красный) выжившие.push(имя);
  }
} finally {
  for (const [ф, т] of Object.entries(исходники))
    writeFileSync(path.join(КОРЕНЬ, ф), т);
}

if (выжившие.length) {
  console.log(`\n  ⚠️ ВЫЖИВШИХ ${выжившие.length}`);
  выжившие.forEach((в) => console.log(`     · ${в}`));
  process.exit(1);
}
console.log("\n  ✓ все мутации пойманы — сторож умеет краснеть\n");
