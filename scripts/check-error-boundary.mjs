// ⚠️ СТОРОЖ ПЕРЕХВАТА ОШИБОК. Заведён 31.08.2026 по блокеру: владелец нажал
// «Отправить приглашение» и получил БЕЛЫЙ ЭКРАН. Перехвата не было ни одного,
// поэтому любая ошибка отрисовки уносила приложение целиком — и выглядела бы
// точно так же завтра, на любом другом экране.
//
// ⚠️ ПРОВЕРЯЕТСЯ ПОВЕДЕНИЕ, А НЕ НАЛИЧИЕ ФАЙЛА. Проба поднимает НАСТОЯЩИЙ
// ErrorBoundary с ребёнком, который бросает при отрисовке, и сторож смотрит
// на получившийся экран: осталось ли на нём хоть что-то, названа ли причина,
// есть ли чем её передать. Сверка исходника ответила бы «перехват написан» —
// ровно так же, как отвечала сверка на возврате после выхода, пока поведение
// было сломано.
//
// ⚠️ И ВТОРАЯ ПРОВЕРКА, БЕЗ КОТОРОЙ ПЕРВАЯ НИЧЕГО НЕ СТОИТ: рядом стоит целый
// экран. Перехватчик, который показывает свой экран ВСЕГДА, был бы зелёным по
// первой проверке и сломал бы приложение целиком.

import { spawn } from "node:child_process";
import { execFile } from "node:child_process";
import { existsSync, readFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const КОРЕНЬ = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const ПУТИ_CHROME = [
  "/Applications/Google Chrome.app/Contents/MacOS/Google Chrome",
  "/Applications/Chromium.app/Contents/MacOS/Chromium",
];

console.log("\nПЕРЕХВАТ ОШИБОК (по отрисованному экрану)");

const браузер = ПУТИ_CHROME.find((п) => existsSync(п));
if (!браузер) {
  console.log("  ✗ ПРОВЕРКА НЕ ВЫПОЛНЕНА: не найден Chrome ни по одному пути:");
  ПУТИ_CHROME.forEach((п) => console.log(`      ${п}`));
  process.exit(1);
}

const собрать = () =>
  new Promise((готово, споткнулись) => {
    execFile(
      "npx",
      ["vite", "build", "-c", "scripts/probe-boundary/vite.config.mjs"],
      { cwd: КОРЕНЬ },
      (е) => (е ? споткнулись(е) : готово()),
    );
  });

try {
  await собрать();
} catch {
  console.log("  ✗ ПРОВЕРКА НЕ ВЫПОЛНЕНА: проба перехвата не собралась");
  process.exit(1);
}

const ФАЙЛ =
  "file://" + path.join(КОРЕНЬ, "scripts/probe-boundary/__dist/index.html");

const снять_разом = () =>
  new Promise((готово) => {
    const дитя = spawn(
      браузер,
      [
        "--headless",
        "--disable-gpu",
        "--virtual-time-budget=20000",
        "--window-size=430,1200",
        "--allow-file-access-from-files",
        "--dump-dom",
        ФАЙЛ,
      ],
      { stdio: ["ignore", "pipe", "ignore"] },
    );
    let вывод = "";
    const часы = setTimeout(() => дитя.kill("SIGKILL"), 90000);
    дитя.stdout.on("data", (к) => (вывод += к));
    дитя.on("close", () => {
      clearTimeout(часы);
      готово(вывод);
    });
    дитя.on("error", () => {
      clearTimeout(часы);
      готово("");
    });
  });

// ⚠️ Пересъём — только несостоявшегося измерения, никогда не расхождения
// (правило заведено по T123: сторож срывался 1 прогон из 6 и краснел впустую).
let dom = "";
let попыток = 0;
for (; попыток < 3; попыток++) {
  dom = await снять_разом();
  if (/<div id="ЗАМЕР">[\s\S]*?\S[\s\S]*?<\/div>/.test(dom)) break;
}
const м = dom.match(/<div id="ЗАМЕР">([\s\S]*?)<\/div>/);
if (!м || !м[1].trim()) {
  console.log(
    `  ✗ ПРОВЕРКА НЕ ВЫПОЛНЕНА: браузер не вернул замер за 3 попытки ` +
      `(DOM ${dom.length} знаков)`,
  );
  process.exit(1);
}
if (попыток > 0)
  console.log(`  ⚠️ замер снялся только с попытки ${попыток + 1} из 3`);

const замер = JSON.parse(
  м[1]
    .replace(/&quot;/g, '"')
    .replace(/&amp;/g, "&")
    .replace(/&lt;/g, "<")
    .replace(/&gt;/g, ">"),
);

const беды = [];
const проверить = (условие, зелёное, красное) => {
  console.log(`  ${условие ? "✓" : "✗"} ${условие ? зелёное : красное}`);
  if (!условие) беды.push(красное);
};

const сломанный = замер.сломанный || "";
console.log(`  ЭКРАН ПОСЛЕ ПОЛОМКИ: «${сломанный.slice(0, 90)}…»`);

проверить(
  сломанный.length > 0,
  "после поломки на экране что-то есть — белого экрана нет",
  "БЕЛЫЙ ЭКРАН: после поломки отрисовки не осталось ничего",
);
проверить(
  сломанный.includes("Экран не открылся"),
  "человеку сказано, что произошло",
  "экран не объясняет человеку, что произошло",
);
проверить(
  сломанный.includes("подставная поломка отрисовки"),
  "причина названа дословно — есть что передать",
  "причина НЕ показана: человек видит заглушку и не может сказать, что сломалось",
);
проверить(
  замер.кнопок >= 2,
  `выход есть: кнопок ${замер.кнопок}`,
  "из экрана поломки некуда деться — ни скопировать, ни перезагрузить",
);
проверить(
  замер.целый === "целый экран на месте",
  "целый экран рядом не тронут — перехват срабатывает только на поломке",
  "перехват показывает свой экран и там, где ничего не сломано",
);

// ⚠️ И ШЕСТАЯ, БЕЗ КОТОРОЙ ПЯТЬ ПРЕДЫДУЩИХ НИЧЕГО НЕ ЗНАЧАТ: перехват может
// быть безупречным и НЕ БЫТЬ ПОДКЛЮЧЁННЫМ. Проба поднимает его сама, напрямую,
// и о точке входа не знает ничего. Читать исходник здесь законно: у «обёрнут ли
// App» нет наблюдаемого следствия, пока что-нибудь не сломается.
const вход = readFileSync(path.join(КОРЕНЬ, "src/main.jsx"), "utf8");
const обёрнут =
  /<ErrorBoundary>\s*<App\s*\/>\s*<\/ErrorBoundary>/.test(вход) &&
  /from\s+"\.\/components\/ErrorBoundary\.jsx"/.test(вход);
проверить(
  обёрнут,
  "перехват подключён в src/main.jsx — App обёрнут",
  "перехват НЕ ПОДКЛЮЧЁН: компонент есть, но App им не обёрнут — белый экран вернётся",
);

if (беды.length) {
  console.log(`\n  ⚠️ РАСХОЖДЕНИЙ ${беды.length}`);
  process.exit(1);
}
console.log("  ИТОГ: поломка одного экрана не уносит приложение");
