// ⚠️ СТОРОЖ ФОРМЫ ПРИГЛАШЕНИЯ: что уходит на сервер, а не что видно в форме.
//
// ЗАЧЕМ, ЗАМЕРОМ ПРОДА 04.09.2026 (бастион): 5 бессрочных ссылок из 8, включая
// последнюю выпущенную, и почта, потерянная кнопкой «Скопировать ссылку» — она
// слала `email: null`, и именное приглашение молча становилось
// предъявительским. Форма при этом выглядела правильной: человек видел поле с
// адресом. Поэтому сторож смотрит НА ТЕЛО ЗАПРОСА, а не на экран.
//
// ⚠️ ПРОГОН ПО ЭКРАНУ ПРИГЛАШЕНИЯ, где человек нажимает (правило T165).
// ⚠️ Замер читает ВИДИМЫЙ текст, а не body.textContent: сценарий пробы лежит
// инлайновым <script> внутри body и нашёл бы искомое в самом себе (T169).
//
// ЗАПУСК: npm run invite (нужен Chrome; без него — «ПРОВЕРКА НЕ ВЫПОЛНЕНА»).
import { execFileSync, spawn } from "node:child_process";
import { existsSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const КОРЕНЬ = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const ПРОБА = path.join(КОРЕНЬ, "scripts/probe-priglashenie");
const ПОРТ = 6100 + Math.floor(Math.random() * 200);

const БРАУЗЕРЫ = [
  "/Applications/Google Chrome.app/Contents/MacOS/Google Chrome",
  "/Applications/Chromium.app/Contents/MacOS/Chromium",
  "/usr/bin/google-chrome",
  "/usr/bin/chromium",
];

// Два прогона: сервер согласен и сервер отказал. Второй нужен, чтобы отказ
// не выдавался за успех — «ссылка готова» после 400 отправляет человека
// копировать то, чего нет.
const ПРОГОНЫ = [
  { имя: "форма · сервер отвечает ок", хвост: "", шаги: "ок" },
  { имя: "форма · сервер отказал 400", хвост: "?otkaz=1", шаги: "отказ" },
];

const ОЖИДАЕМО = {
  ок: [
    ["① форма приглашения открыта", "открыта"],
    // Срок выбран всегда: «Бессрочная» снята, умолчание — 7 дней.
    ["② срока «Бессрочная» в форме нет", "нет «Бессрочной» · выбрано: 7 дней"],
    // Общая ссылка не возникает сама — её берут осознанно.
    ["③ общей ссылки по умолчанию не видно", "скрыта до включения"],
    // ⚠️ ГЛАВНОЕ УТВЕРЖДЕНИЕ ПРАВКИ: почта не теряется второй кнопкой.
    ["④ «Скопировать ссылку» шлёт почту", "email=ivan@example.com · срок=168"],
    ["⑤о отказ 400 виден словами сервера", "прогон без отказа"],
    ["⑤ общая ссылка — за явным включением", "объяснено до нажатия"],
    // У общей роль и срок не наши: их не шлём вовсе, ставит сервер.
    ["⑥ общая ссылка шлёт запрос без почты и роли", "поля: max_uses"],
  ],
  отказ: [
    ["① форма приглашения открыта", "открыта"],
    ["② срока «Бессрочная» в форме нет", "нет «Бессрочной» · выбрано: 7 дней"],
    ["③ общей ссылки по умолчанию не видно", "скрыта до включения"],
    ["④ «Скопировать ссылку» шлёт почту", "email=ivan@example.com · срок=168"],
    ["⑤о отказ 400 виден словами сервера", "сказано сервером · ссылки нет"],
  ],
};

const беды = [];
console.log("\nФОРМА ПРИГЛАШЕНИЯ: на сервер уходит то, что человек ввёл");

const браузер = БРАУЗЕРЫ.find((п) => existsSync(п));
if (!браузер) {
  console.log("  ✗ ПРОВЕРКА НЕ ВЫПОЛНЕНА: не найден Chrome — смотреть нечем");
  process.exit(1);
}

try {
  execFileSync(
    path.join(КОРЕНЬ, "node_modules/.bin/vite"),
    ["build", "--config", path.join(ПРОБА, "vite.config.mjs")],
    { cwd: КОРЕНЬ, stdio: "pipe", timeout: 180000 },
  );
} catch (е) {
  console.log("  ✗ ПРОВЕРКА НЕ ВЫПОЛНЕНА: проба не собралась");
  String(е.stdout || е.message)
    .split("\n")
    .slice(-6)
    .forEach((с) => console.log("      " + с));
  process.exit(1);
}

const сервер = spawn(
  path.join(КОРЕНЬ, "node_modules/.bin/vite"),
  [
    "preview",
    "--config",
    path.join(ПРОБА, "vite.config.mjs"),
    "--port",
    String(ПОРТ),
    "--strictPort",
  ],
  { cwd: КОРЕНЬ, stdio: "ignore" },
);

const снятьРазом = (хвост) =>
  new Promise((готово, споткнулись) => {
    const дитя = spawn(
      браузер,
      [
        "--headless",
        "--disable-gpu",
        "--virtual-time-budget=30000",
        "--window-size=430,1400",
        "--dump-dom",
        `http://localhost:${ПОРТ}/${хвост}`,
      ],
      { stdio: ["ignore", "pipe", "ignore"] },
    );
    let вывод = "";
    const часы = setTimeout(() => {
      дитя.kill("SIGKILL");
      споткнулись(new Error("браузер не ответил за 120 с"));
    }, 120000);
    дитя.stdout.on("data", (к) => (вывод += к));
    дитя.on("error", (е) => {
      clearTimeout(часы);
      споткнулись(е);
    });
    дитя.on("close", () => {
      clearTimeout(часы);
      готово(вывод);
    });
  });

const разобрать = (dom) => {
  const м = dom.match(/<div id="ЗАМЕР">([\s\S]*?)<\/div>/);
  if (!м || !м[1].trim()) return null;
  try {
    return JSON.parse(
      м[1]
        .replace(/&quot;/g, '"')
        .replace(/&amp;/g, "&")
        .replace(/&lt;/g, "<")
        .replace(/&gt;/g, ">"),
    );
  } catch {
    return null;
  }
};

try {
  let поднялся = false;
  for (let i = 0; i < 60 && !поднялся; i++) {
    await new Promise((г) => setTimeout(г, 250));
    try {
      поднялся = (await fetch(`http://localhost:${ПОРТ}/`)).ok;
    } catch {
      /* ещё не поднялся */
    }
  }
  if (!поднялся) throw new Error("сервер пробы не поднялся за 15 с");

  for (const прогон of ПРОГОНЫ) {
    console.log(`\n  ${прогон.имя.toUpperCase()}`);
    let замер = null;
    // Переснимаем только НЕСОСТОЯВШЕЕСЯ измерение; расхождение шага —
    // это результат, его не переснимают.
    for (let п = 0; п < 3 && !замер; п++) {
      const р = разобрать(await снятьРазом(прогон.хвост));
      if (Array.isArray(р)) замер = р;
    }
    if (!замер) {
      console.log("  ✗ ПРОВЕРКА НЕ ВЫПОЛНЕНА: замер не снялся за 3 попытки");
      process.exitCode = 1;
      continue;
    }
    ОЖИДАЕМО[прогон.шаги].forEach(([имя, ждём], i) => {
      const было = String(замер[i] ?? "")
        .split(": ")
        .slice(1)
        .join(": ");
      const ок = было === ждём;
      console.log(
        `  ${ок ? "✓" : "✗"} ${имя}: ${было || "НЕТ"}${
          ок ? "" : `  ← ждали «${ждём}»`
        }`,
      );
      if (!ок)
        беды.push(`${прогон.имя}/${имя}: «${было || "НЕТ"}» вместо «${ждём}»`);
    });
  }
} catch (е) {
  console.log(`  ✗ ПРОВЕРКА НЕ ВЫПОЛНЕНА: ${String(е.message).slice(0, 200)}`);
  сервер.kill("SIGKILL");
  process.exit(1);
} finally {
  сервер.kill("SIGKILL");
}

if (беды.length) {
  console.log(`\n  ⚠️ РАСХОЖДЕНИЙ ${беды.length}`);
  беды.forEach((б) => console.log(`     · ${б}`));
  process.exit(1);
}
console.log(
  "\n  ✓ обе кнопки шлют введённую почту; срок выбран всегда; общая ссылка\n" +
    "    появляется только по явному включению, а отказ доходит словами сервера\n",
);
process.exit(0);
