// Сторож S-54: служебные поля ОТВЕТА распознавания не должны уезжать
// в тело запроса на создание чека.
//
// ЧТО СТЕРЕЖЁТ. Ручка распознавания отдаёт, кроме данных чека, служебные
// поля: `photo_key`, `photo_saved`, `photo_base64`, `reason`. Фронт строит
// из ответа тело запроса на создание чека — и всё, что не вычищено, уедет
// туда вместе с данными. Ровно на этом чуть не сорвался замер задачи №3:
// ключ снимка оказался бы внутри raw_data, а не в колонке.
//
// ЧЕГО НЕ ДЕЛАЕТ И НЕ ПРИТВОРЯЕТСЯ. Это ПРОВЕРКА ИСХОДНИКА, а не запроса:
// сторож читает код и убеждается, что вычистка на месте. Он НЕ выполняет
// запрос и не смотрит, что реально ушло по сети. Отдельно замерено на
// бэкенде: `ReceiptIn` — обычная модель Pydantic без запрета лишних полей,
// то есть неизвестный ключ она молча отбросит, и в базу он не попадёт.
// Значит цена протечки — не порча данных, а тихое расхождение между тем,
// что фронт думает, что отправляет, и тем, что отправляет.
//
// ЗАПУСК:
//   node scripts/check-ocr-response-cleanup.mjs
//   node scripts/check-ocr-response-cleanup.mjs --selfcheck
//
// САМОПРОВЕРКА (правило T11/T30: сперва известный ответ). Гоняется двумя
// заведомо разными образцами: дырявый — обязан быть пойман, здоровый —
// обязан пройти. Без второй половины «расхождений 0» неотличимо от
// «проверка не выполнялась».

import { readFileSync } from "node:fs";
import process from "node:process";

const ФАЙЛ = "src/App.jsx";
// Поля ответа, которым в чеке не место. Список расширять вместе с ручкой.
const СЛУЖЕБНЫЕ = ["photo_key", "photo_saved", "photo_base64", "reason"];

// Вычистка засчитывается в двух видах: поле снято деструктуризацией
// (`const { поле, ...остальное } = d`) либо удалено (`delete тело.поле`).
function вычищено(текст, поле) {
  const деструктуризация = new RegExp(
    `const\\s*\\{[^}]*\\b${поле}\\b[^}]*\\.\\.\\.\\w+\\s*\\}\\s*=`,
    "s",
  );
  const удаление = new RegExp(`delete\\s+\\w+\\.${поле}\\s*;`);
  return деструктуризация.test(текст) || удаление.test(текст);
}

function проверить(текст, метка) {
  const пропущены = СЛУЖЕБНЫЕ.filter((поле) => !вычищено(текст, поле));
  return { метка, проверено: СЛУЖЕБНЫЕ.length, пропущены };
}

function самопроверка() {
  const здоровый = `
    const { photo_key, photo_saved, ...receiptData } = d;
    delete receiptData.photo_base64;
    delete receiptData.reason;
  `;
  const дырявый = `
    const { photo_key, photo_saved, ...receiptData } = d;
    delete receiptData.photo_base64;
  `;
  const a = проверить(здоровый, "здоровый образец");
  const b = проверить(дырявый, "дырявый образец");
  console.log("САМОПРОВЕРКА");
  console.log(
    `  здоровый образец прошёл ................ ${
      a.пропущены.length === 0 ? "да" : "НЕТ"
    }`,
  );
  console.log(
    `  дырявый образец пойман (ждём reason) ... ${
      b.пропущены.join(",") === "reason" ? "да" : "НЕТ"
    }`,
  );
  if (a.пропущены.length !== 0 || b.пропущены.join(",") !== "reason") {
    console.log("  ИТОГ: самопроверка НЕ ПРОШЛА — обычный прогон не запускать");
    process.exit(2);
  }
  console.log("  ИТОГ: сторож отвечает верно на известных образцах");
}

самопроверка();

const текст = readFileSync(ФАЙЛ, "utf8");
const { проверено, пропущены } = проверить(текст, ФАЙЛ);
console.log("\nВЫЧИСТКА СЛУЖЕБНЫХ ПОЛЕЙ ОТВЕТА РАСПОЗНАВАНИЯ");
console.log(`  файл: ${ФАЙЛ}`);
console.log(`  ПРОВЕРЕНО ПОЛЕЙ ${проверено} · НЕ ВЫЧИЩЕНО ${пропущены.length}`);
if (пропущены.length) {
  for (const поле of пропущены) {
    console.log(`  ⛔ ПОЛЕ НЕ ВЫЧИЩЕНО: ${поле} — уедет в тело запроса на чек`);
  }
  process.exit(1);
}
console.log("  ✓ все служебные поля вычищены");
