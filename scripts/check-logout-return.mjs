// ⚠️ СТОРОЖ ВОЗВРАТА ПОСЛЕ ВЫХОДА. Проверяет ПРОВОДКУ событий, а не
// отрисовку — и здесь чтение исходника законно, в отличие от вёрстки:
// стережётся то, что в исходнике и живёт, а на экране не видно вовсе.
//
// ⚠️ ЧТО БЫЛО. Экран не сохранялся никогда — он просто оставался в живом
// дереве компонентов, потому что выход его не размонтирует. Человек
// нажимал «Выйти» в профиле и после входа возвращался ровно туда же,
// на экран выхода. Читается как «выход не сработал», хотя он сработал:
// пароль при следующем входе спрашивают.
//
// ⚠️ ДВА ВЫХОДА РАЗЛИЧАЮТСЯ НАМЕРЕННО. Явный — человек ушёл сам, вернуть
// на «Главную». Автоматический (401 в authFetch) — его выкинуло посреди
// работы, вернуть ровно туда, где был. Одинаковое поведение вежливо
// ровно в одном из двух случаев.
import { readFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const КОРЕНЬ = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const app = readFileSync(path.join(КОРЕНЬ, "src/App.jsx"), "utf8");
const api = readFileSync(path.join(КОРЕНЬ, "src/lib/api.js"), "utf8");

const беды = [];
console.log("\nВОЗВРАТ ПОСЛЕ ВЫХОДА");

const явный =
  /dispatchEvent\(\s*new CustomEvent\(\s*"auth:logout",\s*\{\s*detail:\s*\{\s*явный:\s*true/.test(
    app,
  );
console.log(
  `  явный выход помечен признаком .......... ${явный ? "да" : "НЕТ"}`,
);
if (!явный)
  беды.push("явный выход не помечен — его не отличить от автоматического");

const авто = /dispatchEvent\(new Event\("auth:logout"\)\)/.test(api);
console.log(
  `  автоматический БЕЗ признака ............ ${авто ? "да" : "НЕТ"}`,
);
if (!авто) беды.push("автоматический выход помечен как явный — вернёт не туда");

const сброс =
  /detail\.явный[\s\S]{0,220}setPage\("glavnaya"\)[\s\S]{0,120}setПодэкран\(null\)/.test(
    app,
  );
console.log(
  `  сброс экрана ТОЛЬКО при явном .......... ${сброс ? "да" : "НЕТ"}`,
);
if (!сброс) беды.push("сброс экрана не привязан к признаку явного выхода");

if (беды.length) {
  console.log(`\n  ⚠️ РАСХОЖДЕНИЙ ${беды.length}`);
  беды.forEach((б) => console.log(`  ✗ ${б}`));
  process.exit(1);
}
console.log(
  "  ИТОГ: явный выход возвращает на «Главную», автоматический — на место",
);
