// Сторож языка документа: страница обязана объявлять себя русской.
//
// ⚠️ ЗАЧЕМ. С первого коммита (875550d, 08.05.2026) index.html объявлял
// <html lang="en"> при полностью русском тексте, и строка прожила четыре
// месяца незамеченной: на глаз, в сборке и в линтере разницы нет никакой.
// Chrome на Android считает такую страницу английской и предлагает перевод,
// а если хоть раз нажато «всегда переводить с английского», переводит
// молча. Русский текст, прогнанный как английский, искажается:
// «Последние» → «Последний», «Можно учесть в расходах» → «Можно учитывать
// в расходах», названия продавцов — в бессмыслицу. Живьём у сотрудника
// на Android 16.09.2026; сотрудник перевод честно отрицал.
//
// ЧТО СТЕРЕЖЁТ — три источника, на каждый своя мутация
// (scripts/lang-mutations.mjs):
//   ① index.html — единственная страница, которую получает пользователь
//     (server.js на любой путь отдаёт dist/index.html, Vite копирует
//     атрибут как есть);
//   ② остальные HTML-страницы в git — сегодня это страницы проб. Сами они
//     человеку не отдаются, но новая точка входа появится ровно здесь;
//   ③ src/ — запись языка документа из кода. Она перекрыла бы атрибут
//     из разметки, и сторож разметки остался бы зелёным.
//
// ЧЕГО НЕ ВИДИТ: отданного на проде. Буквы в рабочей копии ≠ доехавшая
// сборка — после пуша язык мерится на самом app.aocgai.ru.
//
// КОДЫ ВЫХОДА: 0 — язык русский везде; 1 — найдена страница не на русском
// или запись языка из кода; 2 — ПРОВЕРКА НЕ ВЫПОЛНЕНА (нет index.html,
// git не отдал список файлов). «Не проверял» не смешивается с «чисто».
//
// ЗАПУСК: node scripts/check-doc-lang.mjs [--verbose]
import { execFileSync } from "node:child_process";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const КОРЕНЬ = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const ПОДРОБНО = process.argv.includes("--verbose");
const ВХОД = "index.html";

console.log("\nЯЗЫК ДОКУМЕНТА");

const отказ = (текст) => {
  console.log(`  ⚠️ ПРОВЕРКА НЕ ВЫПОЛНЕНА: ${текст}`);
  process.exit(2);
};

let файлы;
try {
  файлы = execFileSync("git", ["ls-files", "-z"], {
    cwd: КОРЕНЬ,
    encoding: "utf8",
  })
    .split("\0")
    .filter(Boolean);
} catch (е) {
  отказ(`git ls-files не отработал (${е.message.split("\n")[0]})`);
}
// ⚠️ Сначала убеждаемся, что главная страница ЕСТЬ: проверка
// несуществующего файла молча даёт «совпало» (T87).
if (!fs.existsSync(path.join(КОРЕНЬ, ВХОД))) отказ(`нет файла ${ВХОД}`);

const html = файлы.filter((ф) => /\.html?$/i.test(ф) && ф !== ВХОД);
const код = файлы.filter(
  (ф) => ф.startsWith("src/") && /\.(jsx?|tsx?|mjs)$/.test(ф),
);

const беды = [];

// Язык из разметки. Комментарии вырезаются: в них законно цитировать
// старое значение, и сторож не должен краснеть от истории.
function язык(отн) {
  const т = fs
    .readFileSync(path.join(КОРЕНЬ, отн), "utf8")
    .replace(/<!--[\s\S]*?-->/g, "");
  const тег = т.match(/<html\b[^>]*>/i);
  if (!тег) return { ок: false, что: "тега <html> нет — язык не объявлен" };
  const а = тег[0].match(/\slang\s*=\s*(?:"([^"]*)"|'([^']*)'|([^\s>]+))/i);
  if (!а) return { ок: false, что: `${тег[0]} — без lang` };
  const знач = а[1] ?? а[2] ?? а[3];
  return { ок: /^ru(-|$)/i.test(знач), что: `lang="${знач}"` };
}

const главная = язык(ВХОД);
console.log(`  ${главная.ок ? "✓" : "✗"} ${ВХОД}: ${главная.что}`);
if (!главная.ок) беды.push(ВХОД);

const прочие = html.map((ф) => [ф, язык(ф)]);
for (const [ф, р] of прочие) {
  if (!р.ок || ПОДРОБНО) console.log(`  ${р.ок ? "✓" : "✗"} ${ф}: ${р.что}`);
  if (!р.ок) беды.push(ф);
}
console.log(
  `  ${прочие.every(([, р]) => р.ок) ? "✓" : "✗"} прочие HTML-страницы: ` +
    `на русском ${прочие.filter(([, р]) => р.ок).length} из ${прочие.length}`,
);

// Запись языка документа из кода: documentElement.lang = … и
// documentElement.setAttribute("lang", …). Любая, даже «ru»: язык
// объявляется в одном месте — в index.html.
const ЗАПИСЬ =
  /documentElement\s*\.\s*(?:lang\s*=(?!=)|setAttribute\(\s*["'`]lang["'`])/;
let записей = 0;
for (const ф of код) {
  fs.readFileSync(path.join(КОРЕНЬ, ф), "utf8")
    .split("\n")
    .forEach((строка, и) => {
      if (!ЗАПИСЬ.test(строка)) return;
      записей++;
      console.log(`  ✗ ${ф}:${и + 1}: язык документа пишется из кода`);
      беды.push(`${ф}:${и + 1}`);
    });
}
if (!записей)
  console.log(`  ✓ src/: записи языка из кода нет (файлов ${код.length})`);

if (беды.length) {
  console.log(
    `\n  ✗ ЯЗЫК ДОКУМЕНТА НЕ РУССКИЙ: ${беды.join(" · ")}\n` +
      "    Chrome на Android предложит перевести русскую страницу «с английского»\n" +
      '    и исказит текст. Нужно <html lang="ru"> в разметке и ни одной записи\n' +
      "    языка из кода.",
  );
  process.exit(1);
}
// Итоговая строка обязательна и в зелёном исходе: по ней набор мутаций
// отличает вердикт от падения — упавший Node тоже выходит с кодом 1.
console.log("\n  ✓ ЯЗЫК ДОКУМЕНТА РУССКИЙ ВЕЗДЕ");
