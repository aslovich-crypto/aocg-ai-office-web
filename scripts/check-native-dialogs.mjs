// ⚠️ СТОРОЖ ЧУЖИХ ОКОН (Р-ОТКАЗЫ, T116). Запрещает во фронте `alert`,
// `confirm`, `prompt` и ссылки `mailto:`.
//
// ЗАЧЕМ, ЗАМЕРОМ 04.09.2026. Владелец нашёл на живой приёмке два места
// подряд: причина отклонения спрашивалась системным `prompt` («не в нашем
// дизайне, выглядит стоковым»), а кнопка «Открыть почту» делала `mailto:` —
// то есть открывала ЧЕРНОВИК НОВОГО ПИСЬМА вместо ящика. В тот же день
// грепом нашлись ещё четыре `alert`. Шесть мест одного класса — это не
// случайности, а отсутствие правила.
//
// ⚠️ ПОЧЕМУ ЭТО КЛАСС, А НЕ ПРИДИРКА К ВИДУ. Системное окно ломает три вещи
// разом: оно чужое (человек видит не наш продукт), оно блокирующее (перехват
// управления у страницы) и оно неинформативное — в `alert` нельзя показать
// ни разметку, ни таблицу, ни кнопку «Отменить». Юридический текст согласия
// в системном окне превращался в кашу без заголовков.
//
// ⚠️ `mailto:` ЗАПРЕЩЁН ОТДЕЛЬНО, и это не то же самое, что диалоги. Он
// РАБОТАЕТ — но делает не то, что написано на кнопке: открыть ЯЩИК из
// браузера нельзя в принципе, `mailto:` умеет только составление письма.
// Кнопка, которая работает не туда, хуже мёртвой: мёртвая молчит.
//
// ЧТО ДЕЛАТЬ ВМЕСТО: тост (`setToast`), подпись на месте или шторка —
// образцы есть в `SaveAsPhotoSheet`, `ConsentBottomSheet`, `RejectReasonSheet`.
//
// ЗАПУСК: в цепочке `npm run lint`.
import { readFileSync, readdirSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const КОРЕНЬ = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const ИСХОДНИКИ = path.join(КОРЕНЬ, "src");

// Пробы намеренно жмут кнопки живого приложения и читают чужие окна —
// им запрет не адресован. Внутри `src/` их нет, но путь назван явно,
// чтобы следующий человек не искал, почему сторож молчит на scripts/.
const СМОТРИМ = /\.(jsx?|tsx?)$/;

const ЗАПРЕТЫ = [
  {
    имя: "alert(",
    рег: /(^|[^.\w])alert\s*\(/,
    чем: "тостом или подписью на месте",
  },
  {
    имя: "confirm(",
    рег: /(^|[^.\w])confirm\s*\(/,
    чем: "шторкой с двумя кнопками (образец — SaveAsPhotoSheet)",
  },
  {
    имя: "prompt(",
    рег: /(^|[^.\w])prompt\s*\(/,
    чем: "шторкой с полем ввода (образец — RejectReasonSheet)",
  },
  {
    имя: "mailto:",
    рег: /["'`]mailto:/,
    чем: "ничем — открыть ящик из браузера нельзя, человек знает, где его почта",
  },
];

function файлы(каталог) {
  const итог = [];
  for (const и of readdirSync(каталог, { withFileTypes: true })) {
    const п = path.join(каталог, и.name);
    if (и.isDirectory()) {
      if (!["node_modules", "__dist", "dist"].includes(и.name))
        итог.push(...файлы(п));
    } else if (СМОТРИМ.test(и.name)) итог.push(п);
  }
  return итог;
}

const находки = [];
for (const файл of файлы(ИСХОДНИКИ)) {
  const строки = readFileSync(файл, "utf8").split("\n");
  // ⚠️ КОММЕНТАРИИ ПРОПУСКАЕМ, И ЭТО НЕ ПОБЛАЖКА. Сегодняшняя починка
  // оставила в коде объяснения «было `alert(...)`, стало то-то» — без этого
  // сторож краснел бы на СОБСТВЕННОМ разборе. Ложное срабатывание отменяет
  // сторожа: на него перестают смотреть.
  //
  // ⚠️ БЛОЧНЫЕ ТОЖЕ, А НЕ ТОЛЬКО `//`. Первая редакция смотрела на начало
  // строки и поймала мои же пояснения внутри `{/* … */}` — там строки
  // начинаются обычным текстом. Держим состояние «внутри блока».
  let вБлоке = false;
  строки.forEach((строка, i) => {
    const т = строка.trim();
    const былВБлоке = вБлоке;
    if (вБлоке && /\*\//.test(строка)) вБлоке = false;
    else if (!вБлоке && /\{?\/\*/.test(строка) && !/\*\//.test(строка))
      вБлоке = true;
    if (былВБлоке || т.startsWith("//") || т.startsWith("*")) return;
    for (const { имя, рег, чем } of ЗАПРЕТЫ) {
      if (рег.test(строка)) {
        находки.push({
          файл: path.relative(КОРЕНЬ, файл),
          строка: i + 1,
          имя,
          чем,
          текст: т.slice(0, 70),
        });
      }
    }
  });
}

console.log("\nЧУЖИЕ ОКНА ВО ФРОНТЕ (alert · confirm · prompt · mailto)");
if (!находки.length) {
  console.log("  ✓ ни одного: отказы говорят нашим интерфейсом\n");
  process.exit(0);
}
console.log(`  ✗ НАЙДЕНО: ${находки.length}\n`);
for (const н of находки) {
  console.log(`  ${н.файл}:${н.строка}  ${н.имя}`);
  console.log(`      ${н.текст}`);
  console.log(`      заменить: ${н.чем}`);
}
console.log(
  "\n  Системное окно — чужое, блокирующее и без разметки. Кнопка `mailto:`\n" +
    "  работает не туда: открыть ящик из браузера нельзя.\n",
);
process.exit(1);
