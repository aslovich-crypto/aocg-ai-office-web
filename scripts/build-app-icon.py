# -*- coding: utf-8 -*-
"""Иконка для экрана «Домой» — из КАНОНА В КОДЕ, а не из присланного файла.

⚠️ ИСТОЧНИК — `MarkPlate` в src/App.jsx: белая Λ на вишнёвой плашке.
Вишнёвый берётся из design/theme.mjs (`cherry`), контур Λ — тот же путь,
что рисует приложение. Присланный PNG/PDF не используется намеренно:
файл может разойтись с кодом молча, а код — источник истины по канону.
"""
import pathlib, re
from PIL import Image, ImageDraw

ФРОНТ = pathlib.Path("/Users/alekseishukalovich/aocg-ai-office-web")
РАЗМЕР = 180          # apple-touch-icon: 180×180 — размер для iPhone
НАДБОР = 8            # рисуем в 8 раз крупнее и уменьшаем — сглаживание краёв

# ── вишнёвый ВЫРЕЗАЕТСЯ из канона, а не вписывается сюда ──────────────
канон = (ФРОНТ / "design/theme.mjs").read_text(encoding="utf-8")
m = re.search(r'cherry:\s*"(#[0-9A-Fa-f]{6})"', канон)
if not m:
    raise SystemExit("⚠️ cherry не найден в design/theme.mjs — иконку не рисую")
ВИШНЁВЫЙ = m.group(1)

# ── контур Λ: тот же путь, что в MarkPlate. Только прямые линии. ──────
ПУТЬ = [(71.6279, 0), (0, 179.07), (35.814, 179.07), (89.5349, 44.7674),
        (143.256, 179.07), (179.07, 179.07), (107.442, 0)]
ИСХОДНЫЙ_БОК = 179.07

# ⚠️ ПЛАШКА БЕЗ СКРУГЛЕНИЯ, ХОТЯ КАНОН ГОВОРИТ radius 8. iOS накладывает
# СВОЮ маску-суперэллипс на apple-touch-icon. Своё скругление поверх даёт
# тёмные углы за пределами маски — двойное скругление видно глазом.
# Канон описывает марку ВНУТРИ приложения, где скругление рисуем мы.
плашка = Image.new("RGB", (РАЗМЕР * НАДБОР, РАЗМЕР * НАДБОР), ВИШНЁВЫЙ)

глиф = round(РАЗМЕР * 0.52) * НАДБОР      # 52% — пропорция из MarkPlate
к = глиф / ИСХОДНЫЙ_БОК
сдвиг = (РАЗМЕР * НАДБОР - глиф) / 2
ImageDraw.Draw(плашка).polygon(
    [(x * к + сдвиг, y * к + сдвиг) for x, y in ПУТЬ], fill="#FFFFFF"
)

итог = плашка.resize((РАЗМЕР, РАЗМЕР), Image.LANCZOS)
куда = ФРОНТ / "public/apple-touch-icon.png"
итог.save(куда, "PNG", optimize=True)

# ── САМОПРОВЕРКА ──────────────────────────────────────────────────────
# ⚠️ ПЕРВАЯ РЕДАКЦИЯ ПРОБЫ БЫЛА НЕВЕРНОЙ и уронила сборку на верном
# изображении: она брала точку внизу ПО ЦЕНТРУ и ждала белого. У Λ там
# ПРОСВЕТ между ножками — цвет плашки. Прибор поймал не рендер, а моё
# допущение о форме. Проба заменена на устойчивую к форме: считаем ДОЛЮ
# белого. Она не зависит от того, где именно проходят ножки.
угол = итог.getpixel((2, 2))
ожидаемый = tuple(int(ВИШНЁВЫЙ[i:i + 2], 16) for i in (1, 3, 5))
пиксели = list(итог.getdata())
белых = sum(1 for p in пиксели if p == (255, 255, 255))
доля = белых / len(пиксели)
беды = []
if угол != ожидаемый:
    беды.append(f"угол {угол} вместо вишнёвого {ожидаемый}")
if not 0.03 <= доля <= 0.30:
    беды.append(f"белого {доля:.1%} — вне полосы 3–30%, глиф не нарисовался или залил всё")
if беды:
    куда.unlink(missing_ok=True)
    raise SystemExit("⚠️ ИКОНКА НЕ СОХРАНЕНА: " + "; ".join(беды))

print(f"✓ {куда.name}: {РАЗМЕР}×{РАЗМЕР}, {куда.stat().st_size} байт")
print(f"  вишнёвый {ВИШНЁВЫЙ} вырезан из design/theme.mjs")
print(f"  угол {угол} = вишнёвый · белого {доля:.1%} — глиф на месте")
