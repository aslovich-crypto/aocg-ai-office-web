# -*- coding: utf-8 -*-
"""Иконка для экрана «Домой» — собирается ИЗ ВЕНДОРНОЙ КОПИИ КАНОНА.

ИСТОЧНИКИ, оба в репозитории и оба вычитываются, а не вписываются сюда:
  design/aocg-mark.svg — контур Λ, копия из выгрузки Claude Design
  design/theme.mjs     — вишнёвый (`cherry`)

⚠️ СПЕЦИФИКАЦИЯ ИКОНКИ — `preview/brand-appicon.html` в проекте ДС,
дословно: «Иконка приложения — только вишнёвая #A4161A. Белая „Λ“ на
вишнёвом поле, скруг. 22% (iOS superellipse)». Глиф там 42 из 84 = 50%.

⚠️ ПЕРВАЯ РЕДАКЦИЯ (e646c2a) БРАЛА КОНТУР ИЗ `MarkPlate` в App.jsx и глиф
52% — пропорцию ВНУТРИАППНОЙ плашки, а не иконки. Контур совпал побайтно
(сверено 28.08.2026), пропорция — нет. Теперь и то, и другое из канона.
"""
import pathlib, re, sys
from PIL import Image, ImageDraw

ФРОНТ = pathlib.Path(__file__).resolve().parent.parent
РАЗМЕР = 180          # apple-touch-icon: 180×180 — размер для iPhone
НАДБОР = 8            # рисуем в 8 раз крупнее и уменьшаем — сглаживание краёв

# ── вишнёвый ВЫРЕЗАЕТСЯ из канона, а не вписывается сюда ──────────────
канон = (ФРОНТ / "design/theme.mjs").read_text(encoding="utf-8")
m = re.search(r'cherry:\s*"(#[0-9A-Fa-f]{6})"', канон)
if not m:
    raise SystemExit("⚠️ cherry не найден в design/theme.mjs — иконку не рисую")
ВИШНЁВЫЙ = m.group(1)

# ── контур Λ ВЫЧИТЫВАЕТСЯ из вендорной копии канона ───────────────────
марка = (ФРОНТ / "design/aocg-mark.svg").read_text(encoding="utf-8")
d = re.search(r'\sd="([^"]+)"', марка)
if not d:
    raise SystemExit("⚠️ контур не найден в design/aocg-mark.svg — иконку не рисую")
# Путь Λ состоит ТОЛЬКО из прямых: M x y L x y H x L x y … Z
числа = [float(x) for x in re.findall(r'-?\d+\.?\d*', d.group(1))]
ПУТЬ, x, y, i = [], 0.0, 0.0, 0
for буква in re.findall(r'[MLHVZz]', d.group(1)):
    if буква in "ML":
        x, y = числа[i], числа[i + 1]; i += 2
    elif буква == "H":
        x = числа[i]; i += 1
    elif буква == "V":
        y = числа[i]; i += 1
    else:
        continue
    ПУТЬ.append((x, y))
ИСХОДНЫЙ_БОК = 179.07

# ⚠️ ПЛАШКА БЕЗ СВОЕГО СКРУГЛЕНИЯ, ХОТЯ КАНОН ГОВОРИТ 22%, И ЭТО НЕ
# РАСХОЖДЕНИЕ С НИМ. Канон описывает иконку КАК ОНА ВЫГЛЯДИТ на экране, и
# сам называет источник формы: «22% (iOS superellipse)». Эти 22% рисует
# САМА iOS — она накладывает маску-суперэллипс на apple-touch-icon, и её
# радиус (~22.4%) как раз тот. Полноразмерный квадрат ДАЁТ канонный вид.
# Своё скругление поверх добавило бы прозрачные углы, которые iOS для
# apple-touch-icon заливает ЧЁРНЫМ, — вид разошёлся бы с каноном.
плашка = Image.new("RGB", (РАЗМЕР * НАДБОР, РАЗМЕР * НАДБОР), ВИШНЁВЫЙ)

глиф = round(РАЗМЕР * 0.50) * НАДБОР      # 50% — канон: 42 из 84
к = глиф / ИСХОДНЫЙ_БОК
сдвиг = (РАЗМЕР * НАДБОР - глиф) / 2
ImageDraw.Draw(плашка).polygon(
    [(x * к + сдвиг, y * к + сдвиг) for x, y in ПУТЬ], fill="#FFFFFF"
)

итог = плашка.resize((РАЗМЕР, РАЗМЕР), Image.LANCZOS)
куда = ФРОНТ / "public/apple-touch-icon.png"

# ⚠️ РОЛЬ СМЕНИЛАСЬ 28.08.2026: ЭТО БОЛЬШЕ НЕ ИСТОЧНИК, А ПРОВЕРКА.
# Канонные файлы пришли из Claude Design и лежат в репозитории; сборка
# из спецификации отличалась от них на пиксель. Без --force скрипт ничего
# не пишет: он собирает и СРАВНИВАЕТ. Расхождение значит, что спецификацию
# в ДС поменяли, а файл сюда не подтянули, — и решать это человеку.
if "--force" not in sys.argv:
    if not куда.exists():
        raise SystemExit(f"⚠️ нет {куда.name}; подтяните канон из ДС или пересоберите с --force")
    эталон = Image.open(куда).convert("RGB")
    if list(эталон.getdata()) == list(итог.getdata()):
        print(f"✓ сборка совпадает с канонным {куда.name} попиксельно")
    else:
        разных = sum(1 for a, b in zip(эталон.getdata(), итог.getdata()) if a != b)
        print(f"⚠️ СБОРКА РАСХОДИТСЯ С КАНОНОМ: {разных} пикселей из {РАЗМЕР * РАЗМЕР}")
        print("   Это НЕ повод пересобирать. Проверьте, не менялась ли")
        print("   спецификация в ДС: preview/brand-appicon.html")
    raise SystemExit(0)

итог.save(куда, "PNG", optimize=True)

# ── САМОПРОВЕРКА ──────────────────────────────────────────────────────
# ⚠️ ПЕРВАЯ РЕДАКЦИЯ ПРОБЫ БЫЛА НЕВЕРНОЙ и уронила сборку на верном
# изображении: она брала точку внизу ПО ЦЕНТРУ и ждала белого. У Λ там
# ПРОСВЕТ между ножками — цвет плашки. Прибор поймал не рендер, а моё
# допущение о форме. Проба заменена на устойчивую к форме: считаем ДОЛЮ
# белого. Она не зависит от того, где именно проходят ножки.
угол = итог.getpixel((2, 2))
ожидаемый = tuple(int(ВИШНЁВЫЙ[i:i + 2], 16) for i in (1, 3, 5))
пиксели = list(итог.getdata())
белых = sum(1 for p in пиксели if p == (255, 255, 255))
доля = белых / len(пиксели)
беды = []
if угол != ожидаемый:
    беды.append(f"угол {угол} вместо вишнёвого {ожидаемый}")
if not 0.03 <= доля <= 0.30:
    беды.append(f"белого {доля:.1%} — вне полосы 3–30%, глиф не нарисовался или залил всё")
if беды:
    куда.unlink(missing_ok=True)
    raise SystemExit("⚠️ ИКОНКА НЕ СОХРАНЕНА: " + "; ".join(беды))

print(f"✓ {куда.name}: {РАЗМЕР}×{РАЗМЕР}, {куда.stat().st_size} байт")
print(f"  вишнёвый {ВИШНЁВЫЙ} вырезан из design/theme.mjs")
print(f"  угол {угол} = вишнёвый · белого {доля:.1%} — глиф на месте")
