#!/usr/bin/env node
// ⚠️ МУТАЦИИ СТОРОЖА КОЛОКОЛЬЧИКА (правило T11: непроверенный сторож —
// неработающий). Свод четырёхграфный: ПОСТАВЛЕНО · ПОЙМАНО · НЕ ПОСТАВЛЕНО ·
// НЕ МЕРЕНО. Четвёртая графа заведена 08.09.2026, когда «прибор не отработал»
// и «мутант не пойман» давали один ответ, и второе засчитывалось за первое.
//
// ⚠️ КАЖДАЯ МУТАЦИЯ ВОЗВРАЩАЕТ РОВНО ТО СОСТОЯНИЕ, ИЗ КОТОРОГО ПРАВКА
// ВЫВОДИЛА. Не «сломать что-нибудь», а «откатить конкретную строку блока Б»:
// мутант, не бывший настоящим состоянием кода, проверяет фантазию.
import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const КОРЕНЬ = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const ФАЙЛЫ = {
  шторка: path.join(КОРЕНЬ, "src/components/NotificationsSheet.jsx"),
  прил: path.join(КОРЕНЬ, "src/App.jsx"),
};
const СТОРОЖ = path.join(КОРЕНЬ, "scripts/check-uvedomleniya.mjs");
// Вердикт прибора отличается от его сбоя: без этого «не мерено» неотличимо
// от «не поймано».
const ВЕРДИКТ = /КОЛОКОЛЬЧИК: точка считает/;

const МУТАНТЫ = [
  {
    имя: "М1 точка рисуется безусловно (состояние до 04.09.2026)",
    файл: "прил",
    было: "{непрочитано > 0 && (",
    стало: "{true && (",
    ждём: /событий нет\/② точка[^\n]*ТОЧКА ГОРИТ ЗРЯ/,
    почему: "точка обещала непрочитанное, которого нет в природе",
  },
  {
    имя: "М2 отказ сервера снова выдаётся за пустоту (T171, форма ②)",
    файл: "прил",
    было: 'пометитьСбой("уведомления", true);\n        return;',
    стало: "return;",
    ждём: /сервер отказал\/④[^\n]*(ВЫДАНО ЗА ПУСТОТУ|МОЛЧИТ)/,
    почему: "седьмой источник класса: ранний return вместо пустого catch",
  },
  {
    имя: "М3 шторка без useModalA11y (состояние до блока Б)",
    файл: "шторка",
    было: "  const ref = useModalA11y(onClose);",
    стало: "  const ref = { current: null };",
    ждём: /③[^\n]*ФОКУС СНАРУЖИ|⑨[^\n]*ШТОРКА ОСТАЛАСЬ/,
    почему: "единственная модалка без хука: клавиатурой не закрыть ничем",
  },
  {
    имя: "М4 строка события снова мёртвая (report_id никуда не ведёт)",
    файл: "шторка",
    было: "const кликабельна = Boolean(н.report_id);",
    стало: "const кликабельна = false;",
    ждём: /⑥[^\n]*НЕ ВЕДЁТ/,
    почему: "report_id ехал по всей дороге и умирал на экране",
  },
  {
    имя: "М5 кнопка появляется и там, где вести некуда",
    файл: "шторка",
    было: "const кликабельна = Boolean(н.report_id);",
    стало: "const кликабельна = true;",
    ждём: /⑥[^\n]*ТОЖЕ КНОПКА/,
    почему: "мёртвая кнопка хуже её отсутствия — обратная сторона М4",
  },
  {
    имя: "М6 POST шлётся всегда, даже когда гасить нечего",
    файл: "прил",
    было: "    if (непрочитано > 0) {\n      setНепрочитано(0);",
    стало: "    if (true) {\n      setНепрочитано(0);",
    ждём: /(событий нет|всё прочитано)\/⑧[^\n]*ПОСЛАН ЗРЯ/,
    почему: "лишний запрос на каждом открытии пустого колокольчика",
  },
];

const прогнать = () => {
  for (let i = 0; i < 3; i++) {
    let вывод = "";
    try {
      вывод = execFileSync("node", [СТОРОЖ], {
        cwd: КОРЕНЬ,
        encoding: "utf8",
        timeout: 900000,
      });
    } catch (е) {
      вывод = String(е.stdout || "") + String(е.stderr || "");
    }
    if (ВЕРДИКТ.test(вывод)) return вывод;
  }
  return null;
};

console.log("\nМУТАЦИИ СТОРОЖА КОЛОКОЛЬЧИКА\n");
const исходники = Object.fromEntries(
  Object.entries(ФАЙЛЫ).map(([к, п]) => [к, readFileSync(п, "utf8")]),
);

const чисто = прогнать();
if (чисто === null) {
  console.log("  ⚠️ ПРИБОР НЕ ОТРАБОТАЛ трижды — мутации не мерились");
  process.exit(1);
}
if (/РАСХОЖДЕНИЙ/.test(чисто)) {
  console.log("  ⚠️ ОБРАТНЫЙ ХОД НЕ ПРОЙДЕН: сторож красен ДО мутаций");
  process.exit(1);
}
console.log("  обратный ход: на нетронутом коде расхождений нет ✓\n");

let поставлено = 0;
let поймано = 0;
const непоставленные = [];
const немерено = [];
for (const м of МУТАНТЫ) {
  const путь = ФАЙЛЫ[м.файл];
  const текст = исходники[м.файл];
  if (!текст.includes(м.было)) {
    непоставленные.push(м.имя);
    console.log(`  ✗ НЕ ПОСТАВЛЕН  ${м.имя}: якоря в файле нет`);
    continue;
  }
  writeFileSync(путь, текст.replace(м.было, м.стало), "utf8");
  поставлено += 1;
  const вывод = прогнать();
  writeFileSync(путь, текст, "utf8");
  if (вывод === null) {
    немерено.push(м.имя);
    console.log(`  ⚠️ ПРИБОР НЕ ОТРАБОТАЛ  ${м.имя} — исход неизвестен`);
    continue;
  }
  const есть = м.ждём.test(вывод);
  поймано += есть ? 1 : 0;
  console.log(
    `  ${есть ? "✓ поймана" : "✗ ПРОПУЩЕНА"}  ${м.имя}\n      — ${м.почему}`,
  );
}

console.log(
  `\nПОСТАВЛЕНО ${поставлено} · ПОЙМАНО ${поймано} · ` +
    `НЕ ПОСТАВЛЕНО ${непоставленные.length} · НЕ МЕРЕНО ${немерено.length}`,
);
if (немерено.length)
  console.log(`  ⚠️ прибор не дал вердикта: ${немерено.join(", ")}`);
for (const [к, п] of Object.entries(ФАЙЛЫ)) {
  if (readFileSync(п, "utf8") !== исходники[к]) {
    console.log(`  ⚠️ ФАЙЛ ${к} НЕ ВОССТАНОВЛЕН`);
    process.exit(1);
  }
}
console.log("исходные файлы не тронуты ✓");
process.exit(
  поймано === поставлено && !непоставленные.length && !немерено.length ? 0 : 1,
);
