// ⚠️ СТОРОЖ: ФОРМА НЕ МОЛЧИТ ПРИ ОТКАЗЕ. Читает исходник — и здесь это
// законно по правилу из docs/RULES-FRONTEND.md: проверяется НАЛИЧИЕ веток
// обработки, а сам отказ на живом сервере не воспроизвести без прода.
//
// ⚠️ ОТКУДА. Замер прода 31.08.2026: владелец «завёл сотрудника» — лист
// закрылся, ошибки не было, в базе НИ ОДНОЙ НОВОЙ ЗАПИСИ. Причина в двух
// строках: addUser возвращал `null` на любой отказ, а submit результат
// не проверял и закрывал лист безусловно. Закрытый лист без ошибки —
// это утверждение «добавлено», и оно было ложным.
import { readFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const КОРЕНЬ = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const app = readFileSync(path.join(КОРЕНЬ, "src/App.jsx"), "utf8");

const беды = [];
console.log("\nФОРМА СОТРУДНИКА НЕ МОЛЧИТ ПРИ ОТКАЗЕ");

const проверки = [
  [
    "addUser возвращает причину отказа",
    /ошибка:\s*\n?\s*\(тело && \(тело\.detail \|\| тело\.message\)\)/,
    "addUser снова глотает ответ — отказ неотличим от успеха",
  ],
  [
    "лист закрывается ТОЛЬКО при успехе",
    /if \(итог && итог\.ok\) \{\s*onClose\(\);/,
    "лист закрывается независимо от результата — закрытие лжёт человеку",
  ],
  [
    "ошибка показана на экране",
    /\{ошибка && \(\s*<div\s*\n?\s*role="alert"/,
    "причина никуда не выводится — человек не узнает, что произошло",
  ],
];

// ⚠️ ОТДЕЛЬНО — ДОСТИЖИМОСТЬ, А НЕ НАЛИЧИЕ ТЕКСТА. Мутация «вернуть null
// раньше ветки с причиной» оставляла ветку в файле живой, но НЕДОСТИЖИМОЙ,
// и проверка по наличию строки её пропускала. Голый `return null` — это
// в точности прежняя форма, из-за которой отказ и терялся.
const началоAddUser = app.indexOf("async function addUser(payload)");
const конецAddUser = app.indexOf(
  "\n  }",
  app.indexOf("async function updateUser"),
);
// ⚠️ границы по СЛЕДУЮЩЕЙ функции, а не по первой закрывающей скобке:
// внутри addUser их несколько (try, if, catch), и нежадный поиск
// обрывал тело на первой же — проверка смотрела в огрызок.
const телоAddUser =
  началоAddUser >= 0
    ? app.slice(началоAddUser, app.indexOf("async function updateUser"))
    : "";
const естьГолыйNull = /return null;/.test(телоAddUser);
console.log(`  ${естьГолыйNull ? "✗" : "✓"} в addUser нет голого return null`);
if (естьГолыйNull)
  беды.push("в addUser вернулся голый `return null` — отказ снова теряется");

for (const [имя, ре, беда] of проверки) {
  const есть = ре.test(app);
  console.log(`  ${есть ? "✓" : "✗"} ${имя}`);
  if (!есть) беды.push(беда);
}

if (беды.length) {
  console.log(`\n  ⚠️ РАСХОЖДЕНИЙ ${беды.length}`);
  беды.forEach((б) => console.log(`  ✗ ${б}`));
  process.exit(1);
}
console.log("  ИТОГ: отказ доходит до человека");
