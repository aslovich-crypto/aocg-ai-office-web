// ⚠️ СТОРОЖ: ФОРМА НЕ МОЛЧИТ ПРИ ОТКАЗЕ. Читает исходник — и здесь это
// законно по правилу из docs/RULES-FRONTEND.md: проверяется НАЛИЧИЕ веток
// обработки, а сам отказ на живом сервере не воспроизвести без прода.
//
// ⚠️ ОТКУДА. Замер прода 31.08.2026: владелец «завёл сотрудника» — лист
// закрылся, ошибки не было, в базе НИ ОДНОЙ НОВОЙ ЗАПИСИ. Причина в двух
// строках: addUser возвращал `null` на любой отказ, а submit результат
// не проверял и закрывал лист безусловно. Закрытый лист без ошибки —
// это утверждение «добавлено», и оно было ложным.
import { readFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const КОРЕНЬ = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const app = readFileSync(path.join(КОРЕНЬ, "src/App.jsx"), "utf8");

const беды = [];
console.log("\nПРИГЛАШЕНИЕ НЕ МОЛЧИТ ПРИ ОТКАЗЕ");

const проверки = [
  [
    // ⚠️ ЧЕРЕЗ `текстОшибки`, А НЕ `тело.detail` НАПРЯМУЮ. Правка 31.08.2026
    // по блокеру: сырое тело у FastAPI бывает МАССИВОМ ОБЪЕКТОВ, и React на
    // объекте в детях бросает — белый экран вместо плашки. Сторож требует
    // именно нормализацию, иначе он охранял бы прежнюю поломку.
    "форма приглашения читает причину отказа и приводит её к строке",
    /setОшибка\(текстОшибки\(тело,/,
    "форма приглашения глотает ответ либо кладёт его сырьём — отказ неотличим от успеха, а массив уносит экран",
  ],
  [
    "ошибка формы показана на экране",
    /\{ошибка && \(\s*\n?\s*<div\s*\n?\s*role="alert"/,
    "причина никуда не выводится — человек не узнает, что произошло",
  ],
  [
    "ошибка копирования ссылки не глотается",
    /setОшибкаПриглашений\(\s*\n?\s*"Не удалось скопировать/,
    "пустой catch у копирования — человек уходит с пустым буфером",
  ],
  [
    "повторная отправка показывает отказ строкой",
    /const resendInvite[\s\S]{0,900}setОшибкаПриглашений\(\s*\n?\s*текстОшибки\(тело,/,
    "повторная отправка молчит при отказе либо кладёт тело сырьём",
  ],
];

// ⚠️ СПЛОШНАЯ ПРОВЕРКА, А НЕ ТОЧЕЧНАЯ. Две проверки выше стерегут форму
// приглашения — но белый экран даёт ЛЮБОЕ место, где тело отказа попадает
// на экран сырьём. Замер 31.08.2026: таких мест было семь, из них четыре
// без всякой защиты. Считаем их числом, чтобы новое не завелось молча.
const сырые = [
  ...app.matchAll(/set(?:Err|Ошибка|ОшибкаПриглашений)\(\s*\n?\s*\(?\s*(?:тело|d|body|data)\s*&&/g),
];
console.log(`  СЫРЫХ ВЫВОДОВ ТЕЛА ОТКАЗА: ${сырые.length}`);
if (сырые.length) {
  беды.push(`тело отказа идёт на экран сырьём в ${сырые.length} местах`);
}

for (const [имя, ре, беда] of проверки) {
  const есть = ре.test(app);
  console.log(`  ${есть ? "✓" : "✗"} ${имя}`);
  if (!есть) беды.push(беда);
}

// ─── запрет отключения: по роли, а не по конкретной строке (T119) ─────
// ⚠️ Читается исходник, и здесь это законно: проверяется УСЛОВИЕ, а не то,
// что видит человек. Правило — docs/RULES-FRONTEND.md.
// ⚠️ БЫЛО `deletable={u.id !== 1}` — запрет на СТРОКЕ, а не на роли.
// Он берёг засеянного администратора и никого больше: любого другого
// админа, включая единственного, свайп гасил молча.
const поId = /deletable=\{u\.id !== 1\}/.test(app);
const поРоли =
  /deletable=\{[\s\S]{0,200}u\.id !== me\?\.id[\s\S]{0,200}активныхАдминов <= 1/.test(
    app,
  );
console.log(`  ${поId ? "✗" : "✓"} запрета по конкретному id больше нет`);
console.log(`  ${поРоли ? "✓" : "✗"} запрет считает себя и последнего админа`);
if (поId)
  беды.push("вернулся запрет `u.id !== 1` — он берёг одну строку, а не роль");
if (!поРоли)
  беды.push("запрет отключения не проверяет себя и последнего админа");

if (беды.length) {
  console.log(`\n  ⚠️ РАСХОЖДЕНИЙ ${беды.length}`);
  беды.forEach((б) => console.log(`  ✗ ${б}`));
  process.exit(1);
}
console.log("  ИТОГ: отказ доходит до человека");
