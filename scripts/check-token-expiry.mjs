// ⚠️ ЧТО УВИДИТ СОТРУДНИК ПОСЛЕ ОБЕДА (T152). Вопрос владельца дословно:
// «сотрудник откроет утром, вернётся после обеда — никто не знает, что он
// увидит». Механизм тихого обновления написан (authFetch → 401 → tryRefresh →
// повтор), но ни одна проба не ждала дольше пары секунд: путь «протух →
// обновился → продолжил работать» не проходили НИ РАЗУ. Класс T149/T151
// разом — код есть, путь не хожен.
//
// ⚠️ ЧАСА ЖДАТЬ НЕ НУЖНО: протухший access выпускается тем же секретом,
// что у живого сервера, с exp в прошлом. Сервер отвергает его по-настоящему —
// подделки в проверке нет, 401 приходит от настоящего FastAPI.
//
// ТРИ ПРОГОНА, ПО ПУНКТАМ СТРОКИ:
//   ① protuh — протух только access: данные пришли, человек внутри,
//               введённое не потеряно (пункты ① и ④ строки);
//   ② gonka  — два запроса ловят 401 разом: обновление не задваивается
//               и второй не убивает первый (пункт ②);
//   ③ oba    — протухли ОБА: честный выход на вход, а не полупустой
//               экран (пункт ③).
//
// ЗАПУСК: npm run token
import { итог, поднятьСтенд, сверитьШаги } from "./lib/skvoznoy-stend.mjs";

const беды = [];
console.log("\nПРОТУХШИЙ ТОКЕН: что увидит человек после обеда (T152)");

const стенд = await поднятьСтенд("probe-token");

// Протухший access — выпускаем питоном бэкенда, тем же секретом и той же
// библиотекой, что у сервера. Свой jwt тут писать нельзя: разойдётся
// алгоритмом или полями, и проба начнёт мерить собственную выдумку.
const протухший = стенд.питономБэка(
  // Поля ровно как у сервера (app/auth.py, _create_token): sub, type, iat, exp.
  // iat здесь не украшение: по нему проверяется отзыв токенов
  // (users.tokens_valid_from, S-16) — токен без iat проверялся бы иначе,
  // чем настоящий, и проба мерила бы не тот путь.
  // ⚠️ ta же библиотека, что у сервера: `from jose import jwt` (app/auth.py).
  // Не pyjwt: разойдись библиотеки — проба мерила бы собственную выдумку.
  "import os, datetime as d; from jose import jwt; " +
    "now=d.datetime.now(d.timezone.utc); " +
    "print(jwt.encode({'sub':'1','type':'access'," +
    "'iat':now-d.timedelta(hours=3),'exp':now-d.timedelta(hours=2)}," +
    "os.environ['JWT_SECRET_KEY'],algorithm='HS256'))",
);
if (!протухший || протухший.split(".").length !== 3)
  console.log(
    `  ✗ ПРОВЕРКА НЕ ВЫПОЛНЕНА: не выпущен протухший токен: ${протухший}`,
  );
const хвост = (режим) =>
  `?rezhim=${режим}&stale=${encodeURIComponent(протухший)}`;

// ─── ① работал, ушёл на обед, вернулся ──────────────────────────────────────
console.log("\n  ① УШЁЛ НА ОБЕД С ОТКРЫТЫМ ЭКРАНОМ (refresh жив)");
const обычный = await стенд.снять(хвост("protuh"));
сверитьШаги(
  обычный,
  [
    ["① приложение встало", "Главная"],
    ["② экран чеков", "Чеки"],
    ["③а открыт сканер", "сканер открыт"],
    ["③б открыты реквизиты", "реквизиты"],
    ["③в введён черновик", "введено"],
    ["④ ушёл на обед", "токен протух"],
    // ⚠️ ГЛАВНЫЕ ТРИ УТВЕРЖДЕНИЯ, которых не проверял никто: данные пришли,
    // введённое цело, человек остался внутри. «ЭКРАН ВХОДА» на шаге ⑦
    // означал бы, что после обеда сотрудника выбрасывает.
    ["⑤ вернулся и работает", "данные пришли"],
    ["⑥ черновик уцелел", "цел"],
    ["⑦ человек внутри", "Чеки"],
    ["⑧ обновлений токена", "было 1"],
  ],
  беды,
);

// ─── ② два запроса ловят 401 разом ─────────────────────────────────────────
console.log("\n  ② ДВА ЗАПРОСА РАЗОМ (обновление не должно задваиваться)");
const гонка = await стенд.снять(хвост("gonka"));
сверитьШаги(
  гонка,
  [
    ["① приложение встало", "Главная"],
    ["② ушёл на обед", "токен протух"],
    ["③ два запроса разом", "данные пришли"],
    ["④ обновлений токена", "было 1"],
    ["⑤ человек внутри", "Главная"],
  ],
  беды,
);

// ─── ③ протухли оба ────────────────────────────────────────────────────────
console.log("\n  ③ ПРОТУХЛИ ОБА (обновлять нечем)");
const оба = await стенд.снять(хвост("oba"));
сверитьШаги(
  оба,
  [
    // Честный выход на вход — ПРАВИЛЬНЫЙ исход: обновлять нечем, и держать
    // человека в полупустом экране хуже, чем попросить войти заново.
    ["① оба протухли", "ЭКРАН ВХОДА"],
    ["② попытка действия", "ЭКРАН ВХОДА"],
  ],
  беды,
);

итог(
  беды,
  стенд.журналБэка(),
  "после обеда человек продолжает работать: токен обновляется тихо, ввод цел",
);
