// ⚠️ МУТАЦИИ ПРИБОРА «УДАЛЕНИЕ ОТЧЁТА» (REP-EXPDEL ③, правило T11). Каждая
// ломает ровно одно обещание и требует покраснеть НАЗВАННОМУ шагу (поле
// «ждём»): красный другой шаг — «не тем», не поймано. Иначе засчиталась бы
// способность, которую никто не проверял.
//
// ⚠️ ПОЧЕМУ БЕЗ ЭТОГО НАБОРА ПРОБЕ ВЕРИТЬ НЕЛЬЗЯ: она прошла ПЯТЬ ФАЗ ИЗ ПЯТИ
// с первого прогона. Зелёный с первого раза — не повод радоваться, а повод
// проверить, что прибор вообще на что-то смотрит.
//
// ⚠️ СВОД В ЧЕТЫРЕ ГРАФЫ: ПОСТАВЛЕНО · ПОЙМАНО · НЕ ПОСТАВЛЕНО · НЕ МЕРЕНО.
// «Прибор не дал вердикта» и «мутант не пойман» — разные исходы; прогон без
// вердикта повторяется до трёх раз и только потом идёт в четвёртую графу.
//
// ⚠️ ЧЕГО ЗДЕСЬ НЕТ И ПОЧЕМУ. Мутация «удаление в меню без проверки прав»
// НЕ ЗАВОДИТСЯ: на стенде пользователь один и он администратор, то есть
// разницы не увидел бы ни один шаг — это эквивалентный мутант, а такой не
// считается ни пойманным, ни поставленным. Права удаления проверяются
// мутациями бэкенда ED-01…ED-03 и ED-10 на живой базе.
//
// ⚠️ МУТАНТЫ СТАВЯТСЯ НА МЕСТЕ И ВОЗВРАЩАЮТСЯ В finally; в конце — сверка,
// что исходники совпали побайтно. Не гонять, пока идёт коммит: pre-commit
// прячет незакоммиченное и возвращает — мутант мог бы уехать в коммит.
//
// ЗАПУСК: npm run vdel-mut    (одна полная проба ~30–60 с, мутантов 8)
import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const КОРЕНЬ = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const ФАЙЛЫ = {
  карточка: path.join(КОРЕНЬ, "src/components/ReportDetailModal.jsx"),
  список: path.join(КОРЕНЬ, "src/pages/OtchetyPage.jsx"),
};

const МУТАНТЫ = [
  {
    имя: "Д1 «⋯» снова только при отмене отправки в 1С",
    файл: "карточка",
    было: "  const естьМеню = можноУдалить || можноОтменить1С || можноОтозвать;",
    стало: "  const естьМеню = можноОтменить1С;",
    ждём: /✗ ①б удаление в меню/,
  },
  {
    имя: "Д2 удаление без шторки, сразу запросом",
    файл: "список",
    было: "  function askDelete(rep) {\n    setСпроситьУдаление(rep);\n  }",
    стало: "  function askDelete(rep) {\n    deleteReportNow(rep);\n  }",
    ждём: /✗ ①в шторка, а не тост/,
  },
  {
    имя: "Д3 запрос до базы не доходит, а экран говорит «удалено»",
    файл: "список",
    было: "    const ок = await deleteReportNow(rep);",
    стало: "    const ок = true;",
    ждём: /✗ база, черновик снесён/,
  },
  {
    имя: "Д4 низ «На проверке» снова с третьей кнопкой",
    файл: "карточка",
    было: "      ? { approve: true, reject: true }",
    стало: "      ? { approve: true, reject: true, withdraw: true }",
    ждём: /✗ ②а низ по канону/,
  },
  {
    имя: "Д5 «Отозвать» не уехал в меню",
    файл: "карточка",
    было: "  const можноОтозвать = !!(footer && footer.approve);",
    стало: "  const можноОтозвать = false;",
    ждём: /✗ ②б отзыв и удаление в меню/,
  },
  {
    имя: "Д6 удаление предлагается при живой отправке в 1С",
    файл: "карточка",
    было: "    !живаяОтправка &&\n",
    стало: "",
    ждём: /✗ ③а удаления в меню нет/,
  },
  {
    имя: "Д7 свайп в списке снова удаляет без спроса",
    файл: "список",
    было: "\n                        onPress: () => askDelete(rep),",
    стало: "\n                        onPress: () => deleteReportNow(rep),",
    ждём: /✗ ⑤а действие строки/,
  },
  {
    имя: "Д8 шторка закрывается, ничего не удалив",
    файл: "список",
    было: "          onConfirm={подтвердитьУдаление}",
    стало: "          onConfirm={() => setСпроситьУдаление(null)}",
    ждём: /✗ ①г удалено/,
  },
];

const прогнать = () => {
  try {
    return execFileSync("node", [path.join(КОРЕНЬ, "scripts/check-del.mjs")], {
      cwd: КОРЕНЬ,
      encoding: "utf8",
      timeout: 900000,
    });
  } catch (е) {
    return String(е.stdout || "") + String(е.stderr || "");
  }
};
// Вердикт есть, когда прибор дошёл до итога: зелёный итог или расхождения.
// «ПРОВЕРКА НЕ ВЫПОЛНЕНА» и пустота — вердикта нет.
const естьВердикт = (в) =>
  !/ПРОВЕРКА НЕ ВЫПОЛНЕНА/.test(в) && /✓ удаление отчёта|РАСХОЖДЕНИЙ/.test(в);
const прогнатьСВердиктом = () => {
  for (let п = 1; п <= 3; п++) {
    const в = прогнать();
    if (естьВердикт(в)) return { в, попыток: п };
  }
  return { в: null, попыток: 3 };
};

console.log("\nМУТАЦИИ ПРИБОРА «УДАЛЕНИЕ ОТЧЁТА»");
const исходники = Object.fromEntries(
  Object.entries(ФАЙЛЫ).map(([к, п]) => [к, readFileSync(п, "utf8")]),
);

const чисто = прогнатьСВердиктом();
if (!чисто.в || !/✓ удаление отчёта/.test(чисто.в)) {
  console.log(
    "  ⚠️ ОБРАТНЫЙ ХОД НЕ ПРОЙДЕН: прибор красен или молчит ДО мутаций",
  );
  console.log(
    String(чисто.в || "вердикта нет")
      .split("\n")
      .slice(-12)
      .join("\n"),
  );
  process.exit(1);
}
console.log("  обратный ход: на нетронутом коде прибор зелёный ✓\n");

let поставлено = 0;
let поймано = 0;
const непоставленные = [];
const немерено = [];
for (const м of МУТАНТЫ) {
  const путь = ФАЙЛЫ[м.файл];
  const текст = исходники[м.файл];
  const раз = текст.split(м.было).length - 1;
  if (раз !== 1) {
    непоставленные.push(м.имя);
    console.log(
      `  ✗ НЕ ПОСТАВЛЕН  ${м.имя}: якорь встречается ${раз} раз, нужен один`,
    );
    continue;
  }
  const мутант = текст.replace(м.было, м.стало);
  let итогМутанта;
  try {
    writeFileSync(путь, мутант, "utf8");
    if (readFileSync(путь, "utf8") === текст) {
      непоставленные.push(м.имя);
      console.log(`  ✗ НЕ ПОСТАВЛЕН  ${м.имя}: файл не изменился`);
      continue;
    }
    поставлено += 1;
    итогМутанта = прогнатьСВердиктом();
  } finally {
    writeFileSync(путь, текст, "utf8");
  }
  if (!итогМутанта.в) {
    немерено.push(м.имя);
    console.log(
      `  ⚠ НЕ МЕРЕНО     ${м.имя}: вердикта нет за ${итогМутанта.попыток} попытки`,
    );
    continue;
  }
  const есть = м.ждём.test(итогМутанта.в);
  поймано += есть ? 1 : 0;
  const хвост =
    итогМутанта.попыток > 1
      ? ` (вердикт с попытки ${итогМутанта.попыток})`
      : "";
  console.log(
    `  ${есть ? "✓ ПОЙМАН       " : "✗ НЕ ПОЙМАН    "} ${м.имя}${хвост}`,
  );
  if (!есть) {
    const красные = итогМутанта.в.split("\n").filter((с) => /^\s+✗/.test(с));
    console.log(
      `      ждали ${м.ждём}; красные: ${
        красные.slice(0, 3).join(" | ") || "нет"
      }`,
    );
  }
}

console.log(
  `\nПОСТАВЛЕНО ${поставлено} · ПОЙМАНО ${поймано} · НЕ ПОСТАВЛЕНО ${непоставленные.length} · НЕ МЕРЕНО ${немерено.length}`,
);
for (const [к, п] of Object.entries(ФАЙЛЫ)) {
  if (readFileSync(п, "utf8") !== исходники[к]) {
    console.log(`  ⚠️ ФАЙЛ ${к} НЕ ВОССТАНОВЛЕН — этого быть не должно`);
    process.exit(1);
  }
}
console.log("исходные файлы не тронуты ✓");
process.exit(
  поймано === поставлено && !непоставленные.length && !немерено.length ? 0 : 1,
);
