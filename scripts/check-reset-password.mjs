#!/usr/bin/env node
// Сторож восстановления пароля (S-56).
//
// ЗАЧЕМ. 26.08.2026, при сверке сторон, нашлось: бэкенд шлёт в письме ссылку
// на `/reset-password?token=…`, а во фронте такого маршрута НЕ БЫЛО. Человек,
// открывший письмо, попадал на экран входа, токен молча терялся, и никакой
// ошибки он не видел — видел форму логина, то есть ровно то, из-за чего
// и полез в почту. Ни eslint, ни сборка этого не замечают: с точки зрения
// кода отсутствующий маршрут — просто отсутствующая строка.
//
// ЧТО ПРОВЕРЯЕТСЯ (каждая способность сломана мутацией — tools/mutate-reset-password.mjs):
//   1. МАРШРУТ ПИСЬМА СУЩЕСТВУЕТ. `/reset-password` разбирается фронтом.
//   2. МАРШРУТ ФОРМЫ СУЩЕСТВУЕТ. `/forgot-password` — куда ведёт кнопка.
//   3. ⚠️ ОБА В ТОМ САМОМ УСЛОВИИ, что отдаёт LoginScreen. Проверять «строка
//      встречается в файле» НЕДОСТАТОЧНО: маршрут может быть объявлен рядом
//      и не участвовать в решении — тогда экран входа съест его молча,
//      а сторож будет зелёным.
//   4. КНОПКА НЕ ВРЁТ. Никаких alert про «скоро» рядом с восстановлением:
//      ручка работает, и кнопка, говорящая обратное, — противоречие в живом
//      продукте.
//   5. ⚠️ ОТВЕТ СЕРВЕРА ПОКАЗЫВАЕТСЯ ДОСЛОВНО. `forgot-password` отвечает
//      ОДИНАКОВО на существующий и несуществующий адрес — это защита
//      от перебора. Свой текст «письмо отправлено на ваш адрес» возвращает
//      утечку через интерфейс: бэкенд промолчал, фронт договорил за него.
//   6. ДВА РАЗНЫХ 400 РАЗЛИЧАЮТСЯ. «Ссылка недействительна» требует новой
//      ссылки, «не менее 8 символов» поправимо на месте. Свалить их в одно
//      «что-то пошло не так» — отправить человека за новым письмом из-за
//      опечатки в пароле.
//
// ГРАНИЦЫ. Сторож читает ТЕКСТ исходника, а не поведение браузера: он видит,
// что маршрут участвует в условии, но не проверяет, что экран отрисуется.
// Прогон вёрстки — отдельный инструмент (tools/layout-audit).

import { readFileSync } from "node:fs";

const ФАЙЛ = "src/App.jsx";
const сырой = readFileSync(ФАЙЛ, "utf8");
// ⚠️ ПРОВЕРЯЕТСЯ КОД, А НЕ КОММЕНТАРИИ, И ЭТО КУПЛЕНО ПЕРВЫМ ЖЕ ЗАПУСКОМ.
// Сторож упал на объяснении внутри самого экрана — там фраза «письмо отправлено
// на ваш адрес» приведена как ПРИМЕР ТОГО, ЧЕГО ПИСАТЬ НЕЛЬЗЯ. Сторож, ругающийся
// на объяснения, учит убирать объяснения; это дороже, чем то, что он ловит.
const текст = сырой
  .replace(/\/\*[\s\S]*?\*\//g, "")
  .replace(/^[ \t]*\/\/.*$/gm, "");
const беды = [];

// 1–3: маршруты и — главное — их участие в решающем условии
const условие = текст.match(
  /if\s*\(\s*route === "\/login"[\s\S]{0,400}?\)\s*\{\s*\n\s*return <LoginScreen/,
);
if (!условие) {
  беды.push(
    "не найдено условие, отдающее LoginScreen — сторож не может проверить маршруты",
  );
} else {
  for (const [имя, флаг] of [
    ["/reset-password", "isReset"],
    ["/forgot-password", "isForgot"],
  ]) {
    if (!текст.includes(`"${имя}"`))
      беды.push(
        `маршрут ${имя} не разбирается фронтом — ссылка ведёт в никуда`,
      );
    else if (!условие[0].includes(флаг))
      беды.push(
        `маршрут ${имя} объявлен, но НЕ участвует в условии LoginScreen: ` +
          `экран входа съест его молча`,
      );
  }
}

// 4: кнопка не врёт
if (/alert\(\s*"[^"]*[Вв]осстановлени/.test(текст))
  беды.push("alert про восстановление пароля — ручка работает, кнопка врёт");

// 5: ответ сервера показывается дословно
const экранФормы = текст.slice(
  текст.indexOf("function ForgotPasswordScreen"),
  текст.indexOf("function ResetPasswordScreen"),
);
if (!экранФормы) беды.push("ForgotPasswordScreen не найден");
else {
  if (!/setОтвет\(\s*d\.message/.test(экранФормы))
    беды.push(
      "ответ forgot-password не показывается дословно (нет setОтвет(d.message)) — " +
        "свой текст на этом месте возвращает утечку через интерфейс",
    );
  if (/отправлено на ваш|письмо отправлено на/i.test(экранФормы))
    беды.push(
      "на экране свой текст об отправке письма — это подтверждает существование адреса",
    );
}

// 6: два 400 различаются
const экранСброса = текст.slice(текст.indexOf("function ResetPasswordScreen"));
if (!/setСсылкаМертва\(\s*текст\.includes\("Ссылка"\)\)/.test(экранСброса))
  беды.push(
    "два разных 400 не различаются по тексту: короткий пароль и мёртвая ссылка " +
      "требуют разного от человека",
  );

if (беды.length) {
  console.error("СТОРОЖ ВОССТАНОВЛЕНИЯ ПАРОЛЯ — НАЙДЕНО:");
  for (const б of беды) console.error("  ✗ " + б);
  process.exit(1);
}
console.log("сторож восстановления пароля: 6 проверок пройдено");
