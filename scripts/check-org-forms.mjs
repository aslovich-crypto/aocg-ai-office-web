#!/usr/bin/env node
// Сторож сокращения организационно-правовых форм (`shortOrg` в src/lib/format.js).
//
// ЗАЧЕМ. Ошибка этого класса не выглядит ошибкой. 06.08.2026 на проде нашлось:
// «НЕПУБЛИЧНОЕ АКЦИОНЕРНОЕ ОБЩЕСТВО "РИТЕЙЛ"» → «НЕПАО "РИТЕЙЛ"». Правило ПАО
// срабатывало внутри слова «неПУБЛИЧНОЕ», от него оставался огрызок «НЕП» —
// и строка читалась как нормальное сокращение, а не как испорченные данные.
// Ни eslint, ни сборка, ни браузерный прогон вёрстки такого не видят: с точки
// зрения кода это корректная замена подстроки.
//
// ЧТО ПРОВЕРЯЕТСЯ (три источника, каждый сломан мутацией при сдаче):
//   1. РЕЗУЛЬТАТ. Каждая форма разворачивается в полное название и обязана
//      сократиться РОВНО в свою аббревиатуру: ни огрызка, ни хвоста.
//   2. ОХВАТ. Каждая строка таблицы форм обязана быть в списке ожиданий
//      ниже. Добавили форму в код и забыли про сторож — прогон падает.
//   3. ПОРЯДОК. Если полная фраза A содержит фразу B (как «НЕПУБЛИЧНОЕ
//      АКЦИОНЕРНОЕ ОБЩЕСТВО» содержит «ПУБЛИЧНОЕ АКЦИОНЕРНОЕ ОБЩЕСТВО»),
//      строка A обязана стоять ВЫШЕ B. Инвариант на будущее: ловит неверную
//      вставку новой формы, а не только уже известный случай.
//
// ═══ ПОЧЕМУ ОЖИДАНИЯ ЗАПИСАНЫ ЗДЕСЬ, А НЕ БЕРУТСЯ ИЗ ТАБЛИЦЫ ═══
// Первая версия сравнивала результат с аббревиатурой ИЗ ТОЙ ЖЕ таблицы —
// то есть таблицу саму с собой. Мутация ТСЖ → ТС прошла НЕЗАМЕЧЕННОЙ: менялись
// разом и результат, и ожидание. Сторож был зелёным и не проверял ничего.
// Поэтому канон ГК РФ переписан сюда руками и живёт отдельно от кода.
//
// ГРАНИЦЫ. Сторож проверяет ТАБЛИЦУ, а не полноту знаний о ГК РФ: форму,
// которой в таблице нет, он не заметит — такое название останется длинным.
// Это видно глазом и данных не искажает, в отличие от огрызка.

import { ORG_FORMS_TABLE, shortOrg } from "../src/lib/format.js";

// Канон: полная фраза → аббревиатура. Источник — ГК РФ (§ 4 гл. 4) и ОКОПФ.
// Список НЕЗАВИСИМ от таблицы в коде: в этом весь смысл проверки.
const CANON = [
  ["ПУБЛИЧНОЕ АКЦИОНЕРНОЕ ОБЩЕСТВО", "ПАО"],
  ["НЕПУБЛИЧНОЕ АКЦИОНЕРНОЕ ОБЩЕСТВО", "НАО"],
  ["ЗАКРЫТОЕ АКЦИОНЕРНОЕ ОБЩЕСТВО", "ЗАО"],
  ["ОТКРЫТОЕ АКЦИОНЕРНОЕ ОБЩЕСТВО", "ОАО"],
  ["АКЦИОНЕРНОЕ ОБЩЕСТВО", "АО"],
  ["ОБЩЕСТВО С ОГРАНИЧЕННОЙ ОТВЕТСТВЕННОСТЬЮ", "ООО"],
  ["ФЕДЕРАЛЬНОЕ ГОСУДАРСТВЕННОЕ УНИТАРНОЕ ПРЕДПРИЯТИЕ", "ФГУП"],
  ["ГОСУДАРСТВЕННОЕ УНИТАРНОЕ ПРЕДПРИЯТИЕ", "ГУП"],
  ["МУНИЦИПАЛЬНОЕ УНИТАРНОЕ ПРЕДПРИЯТИЕ", "МУП"],
  ["ФЕДЕРАЛЬНОЕ ГОСУДАРСТВЕННОЕ БЮДЖЕТНОЕ УЧРЕЖДЕНИЕ", "ФГБУ"],
  ["ЧАСТНОЕ ОБРАЗОВАТЕЛЬНОЕ УЧРЕЖДЕНИЕ", "ЧОУ"],
  ["АВТОНОМНАЯ НЕКОММЕРЧЕСКАЯ ОРГАНИЗАЦИЯ", "АНО"],
  ["ПУБЛИЧНО-ПРАВОВАЯ КОМПАНИЯ", "ППК"],
  ["ТОВАРИЩЕСТВО СОБСТВЕННИКОВ ЖИЛЬЯ", "ТСЖ"],
  ["ТОВАРИЩЕСТВО СОБСТВЕННИКОВ НЕДВИЖИМОСТИ", "ТСН"],
  ["СЕЛЬСКОХОЗЯЙСТВЕННЫЙ ПРОИЗВОДСТВЕННЫЙ КООПЕРАТИВ", "СПК"],
  ["ПРОИЗВОДСТВЕННЫЙ КООПЕРАТИВ", "ПК"],
  ["КРЕСТЬЯНСКОЕ (ФЕРМЕРСКОЕ) ХОЗЯЙСТВО", "КФХ"],
  ["ИНДИВИДУАЛЬНЫЙ ПРЕДПРИНИМАТЕЛЬ", "ИП"],
];

const VERBOSE = process.argv.includes("--verbose");
const errors = [];
const NAME = '"ТЕСТ"';

// ── 1 · результат: полная фраза → ровно аббревиатура канона ─────────────────
for (const [phrase, abbr] of CANON) {
  const got = shortOrg(`${phrase} ${NAME}`);
  const want = `${abbr} ${NAME}`;
  if (got !== want)
    errors.push(`форма «${abbr}»: ожидалось «${want}», получено «${got}»`);
  else if (VERBOSE) console.log(`  ✓ ${phrase} → ${got}`);
}

// ── 2 · охват: каждая строка таблицы описана в каноне ───────────────────────
const canonPhrases = new Set(CANON.map(([p]) => p.toUpperCase()));
const tablePhrases = ORG_FORMS_TABLE.map(([, , phrase]) => phrase).filter(
  Boolean,
);
for (const phrase of tablePhrases) {
  if (!canonPhrases.has(phrase.toUpperCase()))
    errors.push(
      `охват: форма «${phrase}» есть в коде, но не описана в CANON этого сторожа — ` +
        `значит она не проверяется ничем`,
    );
  else if (VERBOSE) console.log(`  ✓ охват: ${phrase}`);
}

// ── 3 · порядок: содержащая фраза стоит выше содержащейся ───────────────────
const withPhrase = ORG_FORMS_TABLE.map(([, abbr, phrase], i) => ({
  abbr,
  phrase,
  i,
})).filter((e) => e.phrase);
let pairs = 0;
for (const a of withPhrase) {
  for (const b of withPhrase) {
    if (a === b || !a.phrase.includes(b.phrase)) continue;
    pairs++;
    if (a.i > b.i)
      errors.push(
        `порядок: «${a.abbr}» (${a.phrase}) содержит «${b.abbr}» и обязан стоять ВЫШЕ него ` +
          `— сейчас строки ${a.i + 1} и ${b.i + 1}`,
      );
    else if (VERBOSE) console.log(`  ✓ порядок: ${a.abbr} выше ${b.abbr}`);
  }
}

if (errors.length) {
  console.error("\n✖ Сокращение форм юрлиц сломано:\n");
  for (const e of errors) console.error("  " + e);
  console.error(
    "\n  Таблица форм — ORG_FULL_FORMS в src/lib/format.js.\n" +
      "  Новая форма добавляется ВЫШЕ любой формы, которая входит в неё как\n" +
      "  часть (иначе от длинного названия останется огрызок вида «НЕПАО»),\n" +
      "  и одновременно вписывается в CANON этого сторожа.\n",
  );
  process.exit(1);
}

console.log(
  `✓ формы юрлиц: ${CANON.length} форм сокращаются целиком, ` +
    `${tablePhrases.length} строк таблицы покрыты, ${pairs} пар проверены на порядок`,
);
