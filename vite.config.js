import { defineConfig } from "vite";
import react from "@vitejs/plugin-react";
// Явный импорт, а не глобальный process: eslint проверяет этот файл теми же
// правилами, что и код приложения (браузерное окружение), и необъявленное имя
// здесь — ошибка. Пусть лучше будет импорт, чем исключение в конфиге линтера.
import process from "node:process";

// Куда прокси отправляет /api при локальном прогоне вёрстки. По умолчанию —
// боевой бэкенд: своей базы у нас нет (ни Docker, ни локального Postgres),
// а прогон читает экраны, поэтому данные нужны настоящие.
// ⚠️ ПРИ ПЕРЕЕЗДЕ ИНФРАСТРУКТУРЫ (S-06) АДРЕС МЕНЯЕТСЯ ЗДЕСЬ. Он записан
// и в чек-листе переезда — но если вы читаете этот файл раньше, знайте:
// молча прокси не сломается, он будет исправно ходить на старый адрес.
const БЭКЕНД =
  process.env.AUDIT_API || "https://aocg-ai-office-production.up.railway.app";

// ПРОКСИ ДЛЯ ЛОКАЛЬНОГО ПРОГОНА (T20).
//
// Зачем. Прогон вёрстки (tools/layout-audit) с 08.08.2026 гоняется ЛОКАЛЬНО:
// диагностика в боевую сборку больше не попадает (T19), и включать её на проде
// ради замера — значит оставлять панель вооружённой, если забыть выключить.
// Но локальная страница на :4173 — ЧУЖОЙ origin для боевого API, и whitelist
// CORS (S-19) её не пускает: замер preflight'ом дал 400 без
// access-control-allow-origin.
//
// Почему прокси, а не «добавить localhost в CORS_ORIGINS». Вторая правка
// решает то же самое одной переменной, но платит за удобство инструмента
// ПОСТОЯННЫМ расширением прод-доступа, и платит в панели Railway — там, где
// послабление не читается вместе с кодом. Здесь цена разовая и видна в файле.
//
// Куки не участвуют: авторизация у нас — JWT в localStorage и заголовок
// Authorization (src/lib/api.js), поэтому ни SameSite, ни credentials
// в игру не входят и хвоста у прокси нет.
const ПРОКСИ = {
  "/api": {
    target: БЭКЕНД,
    changeOrigin: true,
    secure: true,
  },
};

export default defineConfig({
  plugins: [react()],
  define: {
    __BUILD_TIME__: JSON.stringify(
      new Date().toLocaleString("ru-RU", {
        timeZone: "Europe/Moscow",
        dateStyle: "short",
        timeStyle: "short",
      }),
    ),
  },
  // Прокси и в dev, и в preview: прогон ходит по СОБРАННОМУ приложению
  // (preview), но при ручной отладке того же экрана удобно иметь то же
  // поведение в dev — иначе «у меня работает» будет зависеть от режима.
  server: { proxy: ПРОКСИ },
  preview: {
    host: "0.0.0.0",
    port: 4173,
    allowedHosts: ["aocgaiofficeweb.up.railway.app"],
    proxy: ПРОКСИ,
  },
});
