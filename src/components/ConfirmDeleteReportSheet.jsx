// владельца 22.09.2026, В4). До того захода удаление отчёта шло БЕЗ спроса:
// строка исчезала сразу, внизу висел тост «Отменить» на несколько секунд.
// Для черновика это годилось, а теперь удаляются и одобренные, и уже уехавшие
// в 1С — необратимое действие, у которого страховкой была секундная плашка.
// Решение владельца: спрашивать до, а не давать отменить после, и спрашивать
// ОДИНАКОВО из карточки и из списка.
//
// ⚠️ ФОРМА ШТОРКИ ВЫНЕСЕНА В `AskSheet` 23.09.2026 (REP-SWIPE1C): вопросов
// стало два — этот и «Отправить в 1С?», — и каждый живёт в двух местах.
// Здесь остался только СМЫСЛ: заголовок, объяснение и красная кнопка.
import AskSheet from "./AskSheet";
import { шторкаОпасная } from "../lib/cardUi";
import { theme, FONT } from "../lib/theme";

export default function ConfirmDeleteReportSheet({
  отчёт,
  занято,
  про1С,
  onKeep,
  onConfirm,
}) {
  const название = (отчёт && отчёт.title) || "";
  return (
    <AskSheet
      заголовок="Удалить отчёт?"
      занято={занято}
      onKeep={onKeep}
      onConfirm={onConfirm}
      стильДействия={шторкаОпасная}
      подписьДействия="Удалить"
      подписьЗанято="Удаляем…"
    >
      <div style={{ font: `400 14px/1.45 ${FONT}`, color: theme.fg2 }}>
        {название ? `Отчёт «${название}»` : "Отчёт"} будет удалён без
        возможности восстановления. Чеки из него не пропадут — они освободятся и
        снова станут доступны для другого отчёта.
      </div>
      {/* ⚠️ ПРО ЧУЖОЙ УЧЁТ ГОВОРИМ ДО ЖЕСТА, А НЕ ПОСЛЕ. Наш отчёт исчезает,
          документ в базе клиента остаётся: платформа документ 1С не трогает
          никогда — пометку на удаление ставит бухгалтер руками. */}
      {про1С && (
        <div style={{ font: `400 14px/1.45 ${FONT}`, color: theme.warningFg }}>
          Документ в 1С не удалится. Пометку на удаление платформа ставит при
          отмене отправки — отмените её в карточке, если документ нужно убрать
          из 1С.
        </div>
      )}
    </AskSheet>
  );
}
