// владельца 22.09.2026, В4). До этого захода удаление отчёта шло БЕЗ спроса:
// строка исчезала сразу, внизу висел тост «Отменить» на несколько секунд.
// Для черновика это годилось, а с этого захода удаляются и одобренные, и
// уже уехавшие в 1С — необратимое действие, у которого страховкой была
// секундная плашка. Решение владельца: спрашивать до, а не давать отменить
// после, и спрашивать ОДИНАКОВО из карточки и из списка.
//
// ⚠️ ПОЧЕМУ ЭТА ШТОРКА ЖИВЁТ НЕ В КАРТОЧКЕ. Мест два — карточка отчёта и
// свайп в списке. Второе окно рядом с первым разошлось бы с ним молча: ровно
// так уже было у чеков, и лечилось это тем же — одним экспортируемым
// подтверждением (`ConfirmDeleteSheet` в карточке чека, 05.09.2026).
//
// ⚠️ СЛОЙ 300, А НЕ «НА ЕДИНИЦУ БОЛЬШЕ КАРТОЧКИ». Число берётся по РОЛИ из
// таблицы слоёв правил фронта: 300–399 — «подтверждения поверх полноэкранного».
// Карточка отчёта живёт на 120, поверх карточки чека — на 180; подтверждение
// обязано накрывать любую из них, и `fixed` нужен ровно поэтому — из списка
// шторку открывают, когда никакой карточки нет вовсе.
//
// Вид кнопок повторяет подтверждение удаления ЧЕКА дословно (высота 48,
// белая «Отмена» и красная заливка «Удалить»): удаление документа обязано
// выглядеть одинаково, чем бы документ ни был.
import { theme, FONT } from "../lib/theme";

const КНОПКА = {
  flex: 1,
  // Сторож вёрстки (T14): flex:1 без minWidth:0 не сожмётся уже содержимого.
  minWidth: 0,
  height: 48,
  borderRadius: 8,
  cursor: "pointer",
  whiteSpace: "nowrap",
};

export default function ConfirmDeleteReportSheet({
  отчёт,
  занято,
  про1С,
  onKeep,
  onConfirm,
}) {
  const название = (отчёт && отчёт.title) || "";
  return (
    <div
      onClick={() => !занято && onKeep()}
      style={{
        position: "fixed",
        inset: 0,
        zIndex: 300,
        background: "rgba(22,26,29,0.5)",
        display: "flex",
        flexDirection: "column",
        justifyContent: "flex-end",
      }}
    >
      <div
        role="alertdialog"
        aria-modal="true"
        aria-label="Удалить отчёт?"
        onClick={(e) => e.stopPropagation()}
        style={{
          background: theme.surface,
          borderRadius: "16px 16px 0 0",
          padding: "18px 16px calc(16px + env(safe-area-inset-bottom))",
          display: "flex",
          flexDirection: "column",
          gap: 12,
          // Оболочка приложения уже центрирует содержимое по ширине телефона,
          // но шторка лежит ВНЕ её потока (fixed) — ширину держим сами.
          width: "100%",
          maxWidth: 480,
          boxSizing: "border-box",
          margin: "0 auto",
        }}
      >
        <div style={{ font: `600 17px/1.3 ${FONT}`, color: theme.fg1 }}>
          Удалить отчёт?
        </div>
        <div style={{ font: `400 14px/1.45 ${FONT}`, color: theme.fg2 }}>
          {название ? `Отчёт «${название}»` : "Отчёт"} будет удалён без
          возможности восстановления. Чеки из него не пропадут — они освободятся
          и снова станут доступны для другого отчёта.
        </div>
        {/* ⚠️ ПРО ЧУЖОЙ УЧЁТ ГОВОРИМ ДО ЖЕСТА, А НЕ ПОСЛЕ. Наш отчёт исчезает,
            документ в базе клиента остаётся: платформа документ 1С не трогает
            никогда — пометку на удаление ставит бухгалтер руками. */}
        {про1С && (
          <div
            style={{ font: `400 14px/1.45 ${FONT}`, color: theme.warningFg }}
          >
            Документ в 1С не удалится — пометьте его на удаление в 1С.
          </div>
        )}
        <div style={{ display: "flex", gap: 8, alignItems: "stretch" }}>
          <button
            type="button"
            onClick={onKeep}
            disabled={занято}
            style={{
              ...КНОПКА,
              border: `1px solid ${theme.borderStrong}`,
              background: theme.surface,
              color: theme.fg1,
              font: `500 15px/1 ${FONT}`,
            }}
          >
            Отмена
          </button>
          <button
            type="button"
            onClick={onConfirm}
            disabled={занято}
            style={{
              ...КНОПКА,
              border: "none",
              background: theme.errorFg,
              color: theme.surface,
              font: `600 15px/1 ${FONT}`,
              cursor: занято ? "default" : "pointer",
            }}
          >
            {занято ? "Удаляем…" : "Удалить"}
          </button>
        </div>
      </div>
    </div>
  );
}
