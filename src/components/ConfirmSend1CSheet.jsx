// ⚠️ ПОДТВЕРЖДЕНИЕ ОТПРАВКИ В 1С СВАЙПОМ (REP-SWIPE1C, решение владельца
// 23.09.2026). У КНОПКИ в карточке подтверждения НЕТ и не нужно: до неё надо
// открыть отчёт и нажать осознанно. У СВАЙПА оно обязательно — жест задевается
// случайно, а отправка пишет документ в чужую бухгалтерию: вернуть его оттуда
// дороже, чем один лишний вопрос.
//
// ⚠️ ДЕЙСТВИЕ ВИШНЁВОЕ, А НЕ КРАСНОЕ. Отправка — движение документа вперёд,
// тот же стиль, что «Отправить в 1С» в карточке (канон карточки документа).
// Красная здесь читалась бы как «опасно, лучше не надо».
import AskSheet from "./AskSheet";
import { шторкаДвижения } from "../lib/cardUi";
import { theme, FONT } from "../lib/theme";

export default function ConfirmSend1CSheet({
  отчёт,
  занято,
  onKeep,
  onConfirm,
}) {
  const название = (отчёт && отчёт.title) || "";
  return (
    <AskSheet
      заголовок={
        название ? `Отправить «${название}» в 1С?` : "Отправить отчёт в 1С?"
      }
      занято={занято}
      onKeep={onKeep}
      onConfirm={onConfirm}
      стильДействия={шторкаДвижения}
      подписьДействия="Отправить в 1С"
      подписьЗанято="Отправляется в 1С…"
    >
      <div style={{ font: `400 14px/1.45 ${FONT}`, color: theme.fg2 }}>
        В бухгалтерии клиента появится авансовый отчёт. Отменить отправку можно
        будет в карточке отчёта — документ в 1С при этом останется.
      </div>
    </AskSheet>
  );
}
