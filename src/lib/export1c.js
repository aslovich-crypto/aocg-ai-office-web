// Отправка одобренного отчёта в 1С (1C-29, заход ②а). Три ручки бэкенда
// (коммит 632b71c, app/routers/odata.py):
//   GET  /api/odata/reports/{id}/export-state — живая отправка и последняя
//        неудача
//   POST /api/odata/reports/{id}/export        — отправить
//   POST /api/odata/reports/{id}/cancel-export — отменить НАШУ запись
//        об отправке
// Круг ролей у всех трёх — бухгалтер и администратор (canApprove), сотруднику
// бэкенд отвечает 403, поэтому и звать их для него незачем.
//
// ⚠️ ЗАПРОСЫ ЗДЕСЬ, А НЕ В КАРТОЧКЕ: правило фронта «логика запросов — в
// src/lib, не размазывать fetch по компонентам». Карточка отчёта и так 1256
// строк, и монолит не растим.

import { authFetch, текстОшибки } from "./api";
import { fmtDate } from "./format";

// ⚠️ ОЖИДАНИЕ ОТПРАВКИ — 130 С, А НЕ 15 ПО УМОЛЧАНИЮ authFetch. До ответа
// бэкенд читает два справочника 1С (чтение повторяется: 2 × (20 + 20 + 1) =
// 82 с в худшем случае), создаёт документ (20 с, без повтора) и проводит его
// (20 с): около 122 с. Оборвав ожидание раньше, мы сказали бы «нет связи»,
// пока документ ещё едет в 1С, — а правду покажет только перечитанное
// состояние, которое карточка и так запрашивает после любого исхода.
const ЖДАТЬ_ОТПРАВКУ = 130000;

// { ок: true, тело } — сервер ответил успехом;
// { ок: false, текст } — ответил отказом: текст ДОСЛОВНО из detail;
// { ок: false, текст: null } — ответа нет (сеть, таймаут): исход неизвестен.
async function позвать(путь, опции, мс, запасной) {
  try {
    const res = await authFetch(путь, опции, мс);
    const тело = await res.json().catch(() => null);
    if (res.ok) return { ок: true, тело };
    return { ок: false, текст: текстОшибки(тело, запасной) };
  } catch {
    return { ок: false, текст: null };
  }
}

export const состояниеОтправки = (id) =>
  позвать(
    `/api/odata/reports/${id}/export-state`,
    {},
    undefined,
    "Не удалось узнать, что с отправкой в 1С",
  );

export const отправитьВ1С = (id) =>
  позвать(
    `/api/odata/reports/${id}/export`,
    { method: "POST" },
    ЖДАТЬ_ОТПРАВКУ,
    "1С не приняла отчёт",
  );

export const отменитьОтправку = (id) =>
  позвать(
    `/api/odata/reports/${id}/cancel-export`,
    { method: "POST" },
    undefined,
    "Отправку отменить не удалось",
  );

// Текст строки состояния — ПО ИСХОДУ (решение владельца 22.09.2026, В2).
// ⚠️ ПОЛЕ «заметка» ИЗ ОТВЕТА НЕ ПОКАЗЫВАЕМ: в журнале бэкенда оно несёт
// служебные слова («политика проведения «never»», имя класса ошибки), а
// человеку нужна причина его словами.
// Возвращает { текст, тон, доп } или null (строки нет); тон — ключ цвета.
export function строкаСостояния(с) {
  if (!с || с.статус_отчёта !== "Одобрен") return null;
  const ж = с.живая;
  if (!ж) {
    const н = с.последняя_неудача;
    if (н) {
      return {
        текст:
          "Последняя отправка не удалась: " +
          (н.исход === "unavailable" ? "1С не ответила" : "1С отказала"),
        тон: "error",
        доп: null,
      };
    }
    return { текст: "В 1С не отправлен", тон: "neutral", доп: null };
  }
  const номер = ж.документ || "без номера";
  const категории = ж.категории_по_умолчанию || [];
  const доп = категории.length
    ? "Счёт по умолчанию: " + категории.join(", ")
    : null;
  if (ж.исход === "running") {
    return ж.прервана
      ? {
          текст:
            "Отправка в 1С прервалась. Проверьте документ в 1С и отмените отправку",
          тон: "warning",
          доп: null,
        }
      : { текст: "Отправляется в 1С…", тон: "info", доп: null };
  }
  if (ж.исход === "ok") {
    const когда = ж.закончена || ж.начата;
    return {
      текст:
        `В 1С · документ ${номер} · проведён` +
        (когда ? " · " + fmtDate(когда) : ""),
      тон: "success",
      доп,
    };
  }
  if (ж.исход === "unposted") {
    return {
      текст: `В 1С · документ ${номер} · не проведён — проведите его в 1С`,
      тон: "warning",
      доп,
    };
  }
  if (ж.исход === "partial") {
    return {
      текст: `В 1С · документ ${номер} создан, проведение не прошло`,
      тон: "warning",
      доп,
    };
  }
  // Исход, которого фронт не знает: бэкенд добавил новый. Честнее назвать
  // его как есть, чем промолчать или выдать за один из известных.
  return {
    текст: `В 1С · документ ${номер} · исход «${ж.исход}»`,
    тон: "neutral",
    доп,
  };
}
