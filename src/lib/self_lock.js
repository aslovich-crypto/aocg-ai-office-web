export const ИМЁН_ЦЕЛИКОМ = 3;
export const ИМЁН_ПРИ_ОБРЕЗКЕ = 2;

export function ктоВернётСловами(имена) {
  const с = (имена || []).filter(Boolean);
  if (с.length === 0) return "";
  if (с.length <= ИМЁН_ЦЕЛИКОМ) return с.join(", ");
  const ещё = с.length - ИМЁН_ПРИ_ОБРЕЗКЕ;
  return `${с.slice(0, ИМЁН_ПРИ_ОБРЕЗКЕ).join(", ")} и ещё ${ещё}`;
}
