// Выбор чеков за период (T148). Логика ОДНА на оба места — шторку создания
// отчёта и добавление в черновик из карточки отчёта: две копии условия
// «этот месяц» разошлись бы первой же правкой (класс «три вида полосы»).
//
// ⚠️ Сравниваем СТРОКИ «ГГГГ-ММ», а не Date: дата чека приходит как
// «2026-08-31», разбор через new Date(строка) зависит от зоны исполнения
// (UTC-полночь против местной) — чек, снятый вечером последнего дня, при
// таком разборе уезжал бы в соседний месяц. Ровно класс №20 из трекера.

export const РЕЖИМЫ_ПЕРИОДА = [
  ["все", "Все"],
  ["месяц", "Этот месяц"],
  ["прошлый", "Прошлый месяц"],
];

function ым(смещение = 0, теперь = new Date()) {
  const д = new Date(теперь.getFullYear(), теперь.getMonth() + смещение, 1);
  return `${д.getFullYear()}-${String(д.getMonth() + 1).padStart(2, "0")}`;
}

export function вПериоде(датаЧека, режим, теперь = new Date()) {
  if (режим === "все") return true;
  const ключ = String(датаЧека || "").slice(0, 7);
  if (режим === "месяц") return ключ === ым(0, теперь);
  if (режим === "прошлый") return ключ === ым(-1, теперь);
  return true;
}
