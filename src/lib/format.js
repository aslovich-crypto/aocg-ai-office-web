// Форматтеры дат и нормализация названия организации. Вынесено из App.jsx
// для переиспользования в выделяемых компонентах. Чистые функции, без состояния.

export const fmtDate = (s) => {
  if (!s) return "";
  const d = new Date(s);
  if (isNaN(d.getTime())) return "";
  return d.toLocaleDateString("ru-RU", {
    day: "2-digit",
    month: "2-digit",
    year: "numeric",
  });
};

export const fmtDateTime = (ts) => {
  if (!ts) return "";
  const d = new Date(ts);
  if (isNaN(d.getTime())) return String(ts);
  return d.toLocaleString("ru-RU", {
    day: "2-digit",
    month: "2-digit",
    year: "numeric",
    hour: "2-digit",
    minute: "2-digit",
  });
};

// ФОРМЫ ЮРЛИЦ ПО ГК РФ. Тройка: [регулярка, аббревиатура, полная фраза].
// Фраза в работе не участвует — она для сторожа scripts/check-org-forms.mjs:
// он гоняет по ней каждую строку таблицы и проверяет порядок.
//
// ═══ ПОРЯДОК ОТ ДЛИННЫХ К КОРОТКИМ — ЭТО КОРРЕКТНОСТЬ, А НЕ СТИЛЬ ═══
// Замена берёт ПЕРВОЕ совпадение и выходит. Если короткая форма стоит выше
// длинной, которая её содержит, получается огрызок: до 06.08.2026
// «НЕПУБЛИЧНОЕ АКЦИОНЕРНОЕ ОБЩЕСТВО "РИТЕЙЛ"» превращалось в «НЕПАО "РИТЕЙЛ"»
// — правило ПАО срабатывало внутри слова «неПУБЛИЧНОЕ», и от него оставалось
// «НЕП». Опасность именно в том, что это ВЫГЛЯДИТ сокращением: строка не
// читается как испорченная и уходит бухгалтеру как есть.
// Инвариант «фраза, содержащая другую фразу, стоит выше» проверяет сторож.
const ORG_FULL_FORMS = [
  // хозяйственные общества
  [
    /непубличное\s+акционерное\s+общество/i,
    "НАО",
    "НЕПУБЛИЧНОЕ АКЦИОНЕРНОЕ ОБЩЕСТВО",
  ],
  [
    /публичное\s+акционерное\s+общество/i,
    "ПАО",
    "ПУБЛИЧНОЕ АКЦИОНЕРНОЕ ОБЩЕСТВО",
  ],
  [
    /закрытое\s+акционерное\s+общество/i,
    "ЗАО",
    "ЗАКРЫТОЕ АКЦИОНЕРНОЕ ОБЩЕСТВО",
  ],
  [
    /открытое\s+акционерное\s+общество/i,
    "ОАО",
    "ОТКРЫТОЕ АКЦИОНЕРНОЕ ОБЩЕСТВО",
  ],
  [
    /общество\s+с\s+ограниченной\s+ответственностью/i,
    "ООО",
    "ОБЩЕСТВО С ОГРАНИЧЕННОЙ ОТВЕТСТВЕННОСТЬЮ",
  ],
  [/акционерное\s+общество/i, "АО", "АКЦИОНЕРНОЕ ОБЩЕСТВО"],
  // унитарные предприятия
  [
    /федеральное\s+государственное\s+унитарное\s+предприятие/i,
    "ФГУП",
    "ФЕДЕРАЛЬНОЕ ГОСУДАРСТВЕННОЕ УНИТАРНОЕ ПРЕДПРИЯТИЕ",
  ],
  [
    /государственное\s+унитарное\s+предприятие/i,
    "ГУП",
    "ГОСУДАРСТВЕННОЕ УНИТАРНОЕ ПРЕДПРИЯТИЕ",
  ],
  [
    /муниципальное\s+унитарное\s+предприятие/i,
    "МУП",
    "МУНИЦИПАЛЬНОЕ УНИТАРНОЕ ПРЕДПРИЯТИЕ",
  ],
  // учреждения
  [
    /федеральное\s+государственное\s+бюджетное\s+учреждение/i,
    "ФГБУ",
    "ФЕДЕРАЛЬНОЕ ГОСУДАРСТВЕННОЕ БЮДЖЕТНОЕ УЧРЕЖДЕНИЕ",
  ],
  [
    /частное\s+образовательное\s+учреждение/i,
    "ЧОУ",
    "ЧАСТНОЕ ОБРАЗОВАТЕЛЬНОЕ УЧРЕЖДЕНИЕ",
  ],
  // некоммерческие
  [
    /автономная\s+некоммерческая\s+организация/i,
    "АНО",
    "АВТОНОМНАЯ НЕКОММЕРЧЕСКАЯ ОРГАНИЗАЦИЯ",
  ],
  [/публично-правовая\s+компания/i, "ППК", "ПУБЛИЧНО-ПРАВОВАЯ КОМПАНИЯ"],
  [
    /товарищество\s+собственников\s+жилья/i,
    "ТСЖ",
    "ТОВАРИЩЕСТВО СОБСТВЕННИКОВ ЖИЛЬЯ",
  ],
  [
    /товарищество\s+собственников\s+недвижимости/i,
    "ТСН",
    "ТОВАРИЩЕСТВО СОБСТВЕННИКОВ НЕДВИЖИМОСТИ",
  ],
  // кооперативы и хозяйства
  [
    /сельскохозяйственный\s+производственный\s+кооператив/i,
    "СПК",
    "СЕЛЬСКОХОЗЯЙСТВЕННЫЙ ПРОИЗВОДСТВЕННЫЙ КООПЕРАТИВ",
  ],
  [/производственный\s+кооператив/i, "ПК", "ПРОИЗВОДСТВЕННЫЙ КООПЕРАТИВ"],
  // скобки у «(фермерское)» ставят не все — принимаем оба написания
  [
    /крестьянское\s*\(?\s*фермерское\s*\)?\s*хозяйство/i,
    "КФХ",
    "КРЕСТЬЯНСКОЕ (ФЕРМЕРСКОЕ) ХОЗЯЙСТВО",
  ],
  [/индивидуальный\s+предприниматель/i, "ИП", "ИНДИВИДУАЛЬНЫЙ ПРЕДПРИНИМАТЕЛЬ"],
  // Anchored: "И П Иванов" / "И. П. Иванов" / "И.П. Иванов" at the very start
  // collapse to "ИП". The trailing-space lookahead prevents matching inside
  // an org name that happens to contain those letters. Фразы нет: эта строка
  // не разворачивает полное название, а чинит уже сокращённое написание.
  [/^(\s*)И\s*\.?\s*П\s*\.?(?=\s)/i, "$1ИП", null],
];

// Сторожу нужна сама таблица: он проверяет и её порядок, и результат по каждой
// строке. Больше её никто не импортирует — работа идёт через shortOrg.
export const ORG_FORMS_TABLE = ORG_FULL_FORMS;

export function shortOrg(org) {
  if (!org) return org;
  let s = String(org);
  for (const [re, abbr] of ORG_FULL_FORMS) {
    if (re.test(s)) {
      s = s.replace(re, abbr);
      break;
    }
  }
  return elki(s.replace(/\s+/g, " ").trim());
}

// Кавычки: ФНС отдаёт название в машинописных "…", в макете деталей чека
// стоит «ООО «ВкусВилл»» — ёлочки. Приведение к макету, не вкусовщина.
// Меняются только ПАРНЫЕ кавычки: непарная (обрезанное название, ошибка
// ввода) остаётся как есть — превратить её в одинокую «ёлочку» значит
// нарисовать открытую скобку без закрывающей.
// РЕГИСТР ЗДЕСЬ НЕ ТРОГАЕТСЯ СОЗНАТЕЛЬНО: у ФНС название заглавными, в макете
// человеческое написание, но однозначного алгоритма между ними нет —
// «MERKAFFE» превратилось бы в «Merkaffe», «РЖД» в «Ржд». Это вопрос
// к дизайн-линии, заведён строкой в трекер (UX-19).
function elki(s) {
  return s.replace(/"([^"]*)"/g, "«$1»");
}

// Способ оплаты в КОМПАКТНОМ списке — только последние четыре цифры карты.
// Так в макете (`templates/receipts/Чеки.html`: иконка карты + «3950»);
// имя карты там не показывают вовсе, оно остаётся в деталях чека.
//
// ОТКУДА ЦИФРЫ — порядок выведен из данных прода, а не из схемы:
//  1. receipts.card_last4 — её заполняют парсеры ФНС и OCR, когда номер виден
//     в самом чеке. НА 05.08.2026 ОНА ПУСТА У ВСЕХ 30 ЧЕКОВ: карта приходит
//     из справочника организации, а не из чека. Проверяем первой всё равно —
//     это единственный источник, где цифры взяты из документа;
//  2. хвост из четырёх цифр в имени карты («Корпоративная 3950»,
//     «Личная 6645») — покрытие 29 из 29 на момент замера;
//  3. цифр нет вовсе («Наличные», «Не указано», карта без номера в имени) —
//     возвращаем НАЗВАНИЕ: короткие значения влезают целиком, а пустое место
//     хуже огрызка.
export function paymentShort(r) {
  const fromColumn = String(r?.card_last4 || "").match(/\d{4}/);
  const fromName = String(r?.payment || "").match(/(\d{4})\s*$/);
  const digits = fromColumn ? fromColumn[0] : fromName ? fromName[1] : null;
  return digits || r?.payment || "—";
}

// Наличные рисуются другой иконкой (Banknote), карты — CreditCard.
// Признак берём по тексту способа оплаты: отдельного поля у нас нет.
export const isCash = (r) => /налич/i.test(String(r?.payment || ""));
