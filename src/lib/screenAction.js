import { createContext } from "react";

// Контексты полосы действия — ОТДЕЛЬНЫМ модулем не из любви к слоям.
// Правило react-refresh: файл экспортирует ЛИБО только компоненты, либо
// только прочее. Контекст рядом с компонентом ломает горячую перезагрузку,
// а хук рядом с компонентом — тоже. Отсюда раскладка:
//   src/lib/screenAction.js       — контексты (это «прочее»);
//   src/hooks/useScreenAction.js  — хук объявления действия;
//   src/components/ActionBar.jsx  — полоса, провайдер и слот (компоненты).
//
// ДВА КОНТЕКСТА, А НЕ ОДИН: значение и сеттер разделены намеренно. Сеттер из
// useState стабилен, поэтому эффект в экране не перезапускается при каждом
// изменении действия. С одним контекстом его значение менялось бы вместе с
// действием, эффект перезапускался бы, снова звал сеттер — и цикл.
export const ActionValue = createContext(null);
export const ActionSetter = createContext(() => {});
